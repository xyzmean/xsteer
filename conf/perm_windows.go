// В Windows проверки прав нет, и это осознанный отказ, а не пропущенная работа.
//
// os.FileInfo на Windows не отдаёт настоящий список доступа: Go синтезирует режим из атрибута
// «только чтение», то есть возвращает 0666 или 0444 независимо от того, кто на самом деле
// может открыть файл. Проверить «доступен ли он всем» этим способом нельзя — она либо всегда
// молчала бы, либо всегда жаловалась, и второе хуже: постоянная жалоба учит не читать жалобы.
//
// Настоящая проверка потребовала бы разбора DACL через advapi32, а это заметный кусок
// платформенного кода ради предупреждения. Пока его нет, честнее не притворяться: файл кладётся
// в каталог профиля пользователя (%LOCALAPPDATA%), права на который выставляет сама система.
