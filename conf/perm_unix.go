//go:build !windows

package conf

import (
	"fmt"
	"os"
)

// checkPerm: доступ «остальным» — ОТКАЗ, а не предупреждение.
//
// Приватный ключ, читаемый любым процессом пользователя, — это чужой пир в вашей звезде;
// запустить туннель «пока так» значило бы согласиться с этим навсегда, а предупреждение в
// журнале не читает никто. Команда даётся готовой, потому что человек, увидевший отказ,
// должен закончить дело одной строкой, а не идти читать про восьмеричные права.
func checkPerm(path string, st os.FileInfo) error {
	if st.Mode().Perm()&0o007 != 0 {
		return fmt.Errorf("%s: файл доступен всем — приватный ключ обязан быть закрыт: chmod 600 %s",
			path, path)
	}
	return nil
}
