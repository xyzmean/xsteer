// Пакет conf — конфигурация xsteer в стиле WireGuard.
//
// ФОРМАТ ВЗЯТ У WG НАРОЧНО. Человек, поднимавший WireGuard, уже знает этот файл, а значит не
// изучает новый синтаксис ради того же смысла. Отсюда и пределы разумного заимствования:
// ключи, которых мы не обслуживаем, ОТВЕРГАЮТСЯ с объяснением, а не принимаются молча —
// иначе `Table = off`, скопированный из рабочего wg-quick, означал бы «настроено», не
// настроив ничего.
//
// РАЗБОР СТРОГИЙ. Файл пишет человек руками или печатает наш же хаб, поэтому запас «на
// будущие ключи» защищать нечего, а опечатка в AllowedIPs, исчезнувшая молча, — это «туннель
// поднялся, половина маршрутов пропала». Неизвестный ключ — отказ с номером строки и, где
// можно, с подсказкой.
//
// СЕКРЕТЫ ОТДЕЛЕНЫ ТИПОМ, А НЕ ДИСЦИПЛИНОЙ. Conf не содержит приватного ключа вовсе, и
// печатает наружу (состояние, диагностика) только она. Обещание «секретов в выводе нет»
// держится не на внимательности того, кто добавит новое поле, а на том, что дотянуться до
// них из этой структуры нечем. Приватный ключ живёт в Secrets и затирается Wipe.
//
// Это порт src/ext/xsconf.{c,h}: тексты отказов и все пределы совпадают с движком на C
// намеренно — конфигурацию человек носит между роутером и десктопом, и один файл обязан
// приниматься или отвергаться обеими реализациями одинаково.
package conf

import "errors"

// KeyB64 — ключ на 32 байта в base64: ровно 44 символа с одним '=' на конце. Формат тот же,
// что печатает `wg genkey`.
const KeyB64 = 44

// ErrKey — ключ не разобрался. Отдельная ошибка, потому что вызывающий печатает при ней
// подсказку про `wg genkey`, а не общий текст «не разобрано».
var ErrKey = errors.New("ключ должен быть 32 байта в base64 (44 символа)")

const b64alpha = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"

func b64val(c byte) int {
	switch {
	case c >= 'A' && c <= 'Z':
		return int(c - 'A')
	case c >= 'a' && c <= 'z':
		return int(c-'a') + 26
	case c >= '0' && c <= '9':
		return int(c-'0') + 52
	case c == '+':
		return 62
	case c == '/':
		return 63
	}
	return -1
}

// KeyDecode разбирает ключ СТРОГО, а не через encoding/base64.
//
// Причина не в экономии: стандартный декодер с StdEncoding.DecodeString принял бы и строку без
// '=' в RawStdEncoding, и строку с переводом строки, если её сначала подчистить, — то есть у
// одного ключа появилось бы несколько написаний. Для ключа это означает ровно одно: строка с
// выпавшим символом молча превращается в ключ на 31 байт, и криптография оказывается слабее
// заявленной, причём заметить это нельзя ничем. Здесь: ровно 44 символа, только стандартный
// алфавит, только один '=' на конце, ровно 32 байта на выходе, и лишние биты обязаны быть
// нулевыми — иначе у одного ключа было бы четыре разных написания.
func KeyDecode(s string) ([32]byte, error) {
	var out [32]byte
	if len(s) != KeyB64 || s[KeyB64-1] != '=' {
		return out, ErrKey
	}
	var acc uint32
	bits, o := 0, 0
	for i := 0; i < KeyB64-1; i++ {
		v := b64val(s[i])
		if v < 0 {
			return out, ErrKey
		}
		acc = acc<<6 | uint32(v)
		bits += 6
		if bits >= 8 {
			bits -= 8
			if o >= 32 {
				return out, ErrKey
			}
			out[o] = byte(acc >> bits)
			o++
		}
	}
	// 43 символа дают 258 бит: два лишних обязаны быть нулевыми, иначе это не запись 32 байт,
	// а другая строка, случайно похожая на неё.
	if o != 32 || acc&((1<<bits)-1) != 0 {
		return out, ErrKey
	}
	return out, nil
}

// KeyEncode печатает ключ так же, как `wg genkey`.
func KeyEncode(key [32]byte) string {
	out := make([]byte, 0, KeyB64)
	for i := 0; i < 30; i += 3 {
		v := uint32(key[i])<<16 | uint32(key[i+1])<<8 | uint32(key[i+2])
		out = append(out, b64alpha[v>>18&63], b64alpha[v>>12&63], b64alpha[v>>6&63], b64alpha[v&63])
	}
	v := uint32(key[30])<<16 | uint32(key[31])<<8
	out = append(out, b64alpha[v>>18&63], b64alpha[v>>12&63], b64alpha[v>>6&63], '=')
	return string(out)
}

// KeyFP — отпечаток публичного ключа для журнала: первые восемь символов base64.
//
// Публичный ключ секретом не является (его печатает и `wg show`), но полный ключ в каждой
// строке журнала — это шум, в котором перестают читать сами строки.
func KeyFP(pub [32]byte) string { return KeyEncode(pub)[:8] }
