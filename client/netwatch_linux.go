//go:build linux

package client

import (
	"context"
	"time"

	"golang.org/x/sys/unix"
)

// СЛЕЖЕНИЕ ЗА СЕТЬЮ — то, чем «интернет пропал и вернулся» перестаёт стоить сорока пяти секунд.
//
// ЧТО БЫЛО. Единственным признаком беды была тишина: соединение объявляло путь мёртвым, отсчитав
// DeadMS, после чего клиент ждал ещё пять секунд и пробовал снова. То есть смена сети (Wi-Fi на
// мобильную, переезд между точками, перезапуск PPPoE) стоила почти минуты молчания туннеля — при
// том что ядро узнало о ней в тот же миг и готово было рассказать.
//
// ЧТО СТАЛО. Мы слушаем netlink на три группы событий: интерфейсы, адреса IPv4 и маршруты IPv4. На
// любое событие спрашиваем у ядра то единственное, что нас касается: «с какого адреса ты СЕЙЧАС
// уходишь к хабу?». Изменился ответ — соединения поднимаются заново немедленно, не дожидаясь ни
// тишины, ни ошибки отправки. Пропал ответ (пути нет вовсе) — это тоже событие: клиент перестаёт
// молотить в мёртвый сокет и ждёт, а как только путь появится, поднимается сразу.
//
// ПОЧЕМУ НЕ РАЗБИРАЕМ САМИ СООБЩЕНИЯ. Внутри netlink лежит подробность, которая нам не нужна и
// которую пришлось бы разбирать правильно: какой интерфейс, какой адрес, какая таблица, какая метка.
// Решение всё равно принимает ядро (link.EgressAddr), а событие служит только поводом спросить.
// Значит достаточно знать, что что-то произошло, — и это делает код короче ровно настолько, насколько
// меньше в нём места для ошибки.
//
// СОБЫТИЯ СКЛЕИВАЮТСЯ. Один переезд даёт их десятки (интерфейс вниз, адреса ушли, маршруты ушли,
// интерфейс вверх, адрес пришёл, маршруты пришли), поэтому после первого мы ждём netQuiet и лишь
// потом спрашиваем: иначе на каждый переезд выходило бы двадцать переподключений вместо одного.
const (
	// netQuiet — сколько ждать затишья после первого события, прежде чем спрашивать ядро.
	netQuiet = 250 * time.Millisecond
	// netPoll — как часто спрашивать ядро БЕЗ событий.
	//
	// Нужно потому, что netlink рассказывает не обо всём: маршрут, уехавший из-за смены метрики в
	// другой таблице, или путь, пропавший на стороне провайдера, событием не сопровождаются. Раз в
	// пять секунд — это дешевле любого замера (один connect на UDP, ни одного пакета) и вдвое
	// быстрее, чем прежний шаг повтора.
	netPoll = 5 * time.Second
)

// watchNet следит за сетью и зовёт fn, когда путь к хабу изменился. Возврат — только по отмене или
// по невозможности слушать вовсе.
func (c *Client) watchNet(ctx context.Context) {
	// Что ядро отвечало в прошлый раз. Ноль означает «пути нет».
	var have [4]byte
	var had bool
	if a, err := linkEgress(c.hub.addr); err == nil {
		have, had = a, true
	}

	ev := make(chan struct{}, 1)
	stop := c.netlinkSub(ctx, ev)
	if stop != nil {
		defer stop()
	}

	check := func() {
		a, err := linkEgress(c.hub.addr)
		now, ok := a, err == nil
		if ok == had && now == have {
			return
		}
		switch {
		case !ok:
			c.logf("сеть: пути к %s больше нет — жду, когда вернётся", c.hub.str)
		case !had:
			c.logf("сеть: путь к %s появился (с адреса %d.%d.%d.%d) — поднимаю соединения сразу",
				c.hub.str, now[0], now[1], now[2], now[3])
		default:
			c.logf("сеть: адрес выхода к %s сменился с %d.%d.%d.%d на %d.%d.%d.%d — "+
				"поднимаю соединения заново, не дожидаясь тишины",
				c.hub.str, have[0], have[1], have[2], have[3], now[0], now[1], now[2], now[3])
		}
		have, had = now, ok
		c.bumpNet()
	}

	t := time.NewTicker(netPoll)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-t.C:
			check()
		case <-ev:
			// Затишье: один переезд даёт десятки сообщений, и спрашивать надо один раз в конце.
			for {
				select {
				case <-ctx.Done():
					return
				case <-ev:
					continue
				case <-time.After(netQuiet):
				}
				break
			}
			check()
		}
	}
}

// netlinkSub подписывается на события netlink и толкает ev на каждое. Возвращает функцию закрытия
// или nil, если подписаться не удалось: тогда остаётся опрос по таймеру, и это рабочий путь, а не
// отказ, — просто медленнее.
func (c *Client) netlinkSub(ctx context.Context, ev chan struct{}) func() {
	fd, err := unix.Socket(unix.AF_NETLINK, unix.SOCK_RAW|unix.SOCK_CLOEXEC, unix.NETLINK_ROUTE)
	if err != nil {
		c.logf("сеть: слежение за netlink недоступно (%v) — смена сети будет замечаться опросом "+
			"раз в %s", err, netPoll)
		return nil
	}
	if err := unix.Bind(fd, &unix.SockaddrNetlink{
		Family: unix.AF_NETLINK,
		Groups: unix.RTMGRP_LINK | unix.RTMGRP_IPV4_IFADDR | unix.RTMGRP_IPV4_ROUTE,
	}); err != nil {
		unix.Close(fd)
		c.logf("сеть: подписка на netlink не встала (%v) — остаётся опрос раз в %s", err, netPoll)
		return nil
	}
	go func() {
		buf := make([]byte, 8192)
		for ctx.Err() == nil {
			n, _, err := unix.Recvfrom(fd, buf, 0)
			if err == unix.EINTR {
				continue
			}
			if err != nil || n <= 0 {
				return
			}
			// Содержимое сообщения не разбирается намеренно — см. шапку файла.
			select {
			case ev <- struct{}{}:
			default:
			}
		}
	}()
	return func() { unix.Close(fd) }
}
