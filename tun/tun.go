// Пакет tun — устройство, через которое трафик попадает в туннель.
//
// Одна на всю программу граница: наружу отдаются только Read и Write пакета, без заголовков
// платформы. На Linux это /dev/net/tun с IFF_NO_PI, на macOS будет utun (там перед каждым пакетом
// едут четыре байта семейства адресов), на Windows — Wintun с его собственным кольцевым буфером.
// Различия обязаны остаться здесь: путь данных не должен знать, на чём он исполняется.
package tun

import (
	"errors"
	"time"
)

// ErrNoDevice — устройства нет или его нельзя создать. Отдельная ошибка: на Linux это чаще всего
// отсутствующий модуль tun, и вызывающий говорит об этом человеку прямо, а не «не удалось открыть».
var ErrNoDevice = errors.New("tun: устройство недоступно")

// TxQueueLen — длина очереди устройства, которую мы просим у ядра при подъёме.
//
// Это НЕ про наши записи в устройство, хотя так было написано в комментарии к Write и в движке на
// C: 200 000 неблокирующих записей в TUN на ядре 6.8 дали ноль EAGAIN и ноль rx_dropped — запись
// идёт в приёмный путь ядра и в эту очередь не упирается вовсе. Очередь работает в обратную
// сторону: в ней лежат пакеты, которые ядро отдаёт НАМ, и её длина — ровно txqueuelen. Замерено
// той же пробой на этой реализации: из 20 000 отправленных при 500 до читателя доехали ровно 500
// (tx_dropped +19 501), при 4096 — ровно 4096. Числа сошлись с пробой в движке на C до штуки.
//
// Отсюда и смысл запаса: он про то, сколько пакетов уцелеет, пока цикл занят предыдущим витком
// (шифрованием, записью в сокеты, разбором), а не про паузы на записи. Памяти заранее это не
// стоит — очередь занимает столько, сколько в ней реально лежит.
//
// Число то же, что в движке на C (tun_bring_up), и это осознанно: настройка, у которой есть
// замер, не должна зависеть от того, на каком языке написана половина туннеля.
const TxQueueLen = 4096

// ErrAgain — прямо сейчас читать нечего. Отдельная ошибка, потому что это НЕ отказ: путь данных
// на ней перестаёт добирать пакеты в пачку и отправляет набранное.
var ErrAgain = errors.New("tun: пока пусто")

// Device — открытое устройство.
type Device interface {
	// Read читает ОДИН пакет. Пакет всегда читается целиком: в отличие от потока, здесь короткое
	// чтение означает не «остаток придёт потом», а потерянный пакет.
	//
	// Чтение НЕБЛОКИРУЮЩЕЕ: когда пакетов нет, возвращается ErrAgain. Так сделано ради пачек —
	// путь данных забирает всё, что уже пришло, одним заходом и без единого ожидания. Блокирующее
	// чтение потребовало бы отдельной горутины и канала, а это переключение на КАЖДЫЙ пакет:
	// замерено — 255 Мбит/с против 1582 на том же коде и том же железе.
	Read(p []byte) (int, error)
	// WaitRead ждёт появления пакетов не дольше timeout; false — истекло время.
	WaitRead(timeout time.Duration) (bool, error)
	// Write отдаёт один пакет ядру.
	//
	// ПАКЕТ МОГ НЕ УЙТИ К МОМЕНТУ ВОЗВРАТА. С разгрузкой сегментации (Linux, offload_linux.go)
	// подряд идущие пакеты одного потока накапливаются в супер-кадр и уезжают одним вызовом —
	// именно этим она в 14,6 раза дешевле. Поэтому на границе всплеска — когда читать больше нечего
	// — вызывающий ОБЯЗАН позвать Flush; иначе последний пакет пролежит в буфере до следующего, то
	// есть разгрузка обернётся задержкой.
	Write(p []byte) (int, error)
	// Flush отдаёт то, что накопила разгрузка. Там, где разгрузки нет, ничего не делает.
	Flush() error
	// Name — имя устройства, как его видит система.
	Name() string
	// SetMTU ставит MTU устройства. Зовётся не только при подъёме: согласование пути узнаёт
	// настоящий предел уже после того, как туннель поднялся, и обязано его применить.
	SetMTU(mtu int) error
	Close() error
}
