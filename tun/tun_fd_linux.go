//go:build linux

package tun

import (
	"sync"

	"golang.org/x/sys/unix"
)

// FromFD — устройство поверх ГОТОВОГО дескриптора, который открыл кто-то другой.
//
// ЗАЧЕМ ОНО. На Android туннель заводит система: приложение просит VpnService, а обратно получает
// уже открытый дескриптор. Открыть /dev/net/tun там нельзя — это право есть только у ядра и у
// самой системы, — но всё остальное устройство ведёт себя ровно как обычное, потому что оно и
// есть обычное устройство TUN. Поэтому здесь не новая реализация, а тот же linuxDev с тем же
// чтением, записью и ожиданием: различается только способ заполучить дескриптор.
//
// ЧТО С ВЛАДЕНИЕМ. Дескриптор переходит НАМ: Close его закроет. На стороне Android это значит,
// что отдавать надо detachFd(), а не getFd() — иначе дескриптор закроют дважды, и второй раз
// попадёт уже в чужой, переиспользованный номер. Такая ошибка проявляется не здесь и не сразу, а
// в произвольном месте программы через минуты.
//
// РАЗГРУЗКИ СЕГМЕНТАЦИИ ЗДЕСЬ НЕТ. Она требует, чтобы устройство было открыто с IFF_VNET_HDR, а
// этот флаг ставится при создании — то есть тем, кто дескриптор открыл. Мы его только получили,
// поэтому путь простой: один пакет, одно чтение.
func FromFD(fd int, name string, mtu int) (Device, error) {
	if fd < 0 {
		return nil, ErrNoDevice
	}
	// Неблокирующий режим обязателен: контракт Read — «когда пусто, ErrAgain», и на блокирующем
	// дескрипторе он превратился бы в «жди пакета», то есть путь данных перестал бы собирать
	// пачки и замер бы на первом же затишье.
	if err := unix.SetNonblock(fd, true); err != nil {
		return nil, err
	}
	if name == "" {
		name = "xs0"
	}
	return &fdDev{
		linuxDev: &linuxDev{fd: fd, name: name, offWhy: "устройство открыто системой"},
		mtu:      mtu,
	}, nil
}

// fdDev отличается от linuxDev ровно одним методом — SetMTU. Всё остальное берётся как есть, и
// это не экономия строк: чтение, запись и ожидание у обычного устройства уже проверены тестами и
// измерены, а второй их экземпляр разошёлся бы с первым на первой же правке.
type fdDev struct {
	*linuxDev
	mu     sync.Mutex
	mtu    int
	closed bool
}

// Close закрывает дескриптор РОВНО ОДИН РАЗ.
//
// Однократность здесь не осторожность впрок, а необходимость: закрыть устройство норовят двое —
// клиент, когда уходят его рабочие горутины, и тот, кто туннель поднимал, когда его останавливают.
// У обычного устройства второй unix.Close вернул бы EBADF и на этом кончился, но между двумя
// вызовами ядро успевает выдать этот же номер кому угодно — новому сокету, открытому файлу, —
// и второй Close закроет ЕГО. Проявляется такое не здесь и не сразу, а в произвольном месте
// программы через минуты, и искать это можно долго.
func (d *fdDev) Close() error {
	d.mu.Lock()
	if d.closed {
		d.mu.Unlock()
		return nil
	}
	d.closed = true
	d.mu.Unlock()
	return d.linuxDev.Close()
}

// SetMTU запоминает и соглашается.
//
// У обычного устройства этот метод зовёт `ip link set`, но здесь так нельзя по двум причинам, и
// каждой хватило бы одной. Имени интерфейса мы не знаем: система дала дескриптор, а не имя.
// Прав менять настройки интерфейса у приложения нет.
//
// Согласиться при этом ОБЯЗАТЕЛЬНО, а не отказать. Согласование пути узнаёт настоящий предел уже
// после подъёма и применяет его этим вызовом; отказ означал бы, что клиент не обновит свой
// рабочий MTU и навсегда останется на стартовом. То есть отказ сделал бы хуже, чем согласие.
// Настоящий MTU туннеля задаёт тот, кто его создавал, — и его значение обязано совпадать с тем,
// что стоит в настройке.
func (d *fdDev) SetMTU(mtu int) error {
	d.mu.Lock()
	d.mtu = mtu
	d.mu.Unlock()
	return nil
}

// MTU — то, что запомнено последним.
func (d *fdDev) MTU() int {
	d.mu.Lock()
	defer d.mu.Unlock()
	return d.mtu
}

// компиляция падёт здесь, если интерфейс разойдётся с реализацией
var _ Device = (*fdDev)(nil)
