// Пакет csum — контрольная сумма интернета (RFC 1071) одним быстрым проходом.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПАКЕТ. Сумму считают три разных места, и все три на горячем пути: заголовок TCP
// поддельного соединения (link), заголовки сегментов, на которые разрезается супер-кадр разгрузки
// (tun), и завершение НЕПОЛНОЙ суммы, которую ядро отдаёт вместе с пакетом, оставив её на разгрузку
// устройству (тоже tun). Держать три копии одного цикла — это три места, где ошибка в хвосте
// нечётной длины проявится как «большие пакеты иногда не доходят».
//
// ПОЧЕМУ ПОРЯДОК БАЙТ ПЕРЕВЁРНУТ ВНУТРИ. Сумма определена над 16-битными словами В СЕТЕВОМ
// порядке, но для одно-дополнительной суммы верно тождество: свёрнутая сумма слов с
// переставленными байтами равна перестановке байт свёрнутой суммы. Поэтому слова читаются машинным
// порядком — по четыре и по восемь байт за раз, без перестановки на слово, — а перестановка
// делается ОДИН раз над готовым результатом. Замер выигрыша: 447 нс против 98 нс на 1460 байтах,
// то есть с суммы снято больше, чем стоит AES-128-GCM на том же пакете (362 нс).
package csum

import "encoding/binary"

// Sum — незавершённая сумма байт: складывает 16-битные слова, но НЕ сворачивает и НЕ дополняет.
// Нужна тем, кто складывает несколько частей (псевдозаголовок и тело) до свёртки.
//
// Возвращается в «машинном» порядке слов (см. шапку пакета): смешивать её с числами из сети без
// перестановки нельзя, для этого есть Word.
func Sum(b []byte) uint64 {
	var s uint64
	for len(b) >= 32 {
		s += uint64(binary.LittleEndian.Uint32(b[0:4]))
		s += uint64(binary.LittleEndian.Uint32(b[4:8]))
		s += uint64(binary.LittleEndian.Uint32(b[8:12]))
		s += uint64(binary.LittleEndian.Uint32(b[12:16]))
		s += uint64(binary.LittleEndian.Uint32(b[16:20]))
		s += uint64(binary.LittleEndian.Uint32(b[20:24]))
		s += uint64(binary.LittleEndian.Uint32(b[24:28]))
		s += uint64(binary.LittleEndian.Uint32(b[28:32]))
		b = b[32:]
	}
	for len(b) >= 4 {
		s += uint64(binary.LittleEndian.Uint32(b[0:4]))
		b = b[4:]
	}
	if len(b) >= 2 {
		s += uint64(binary.LittleEndian.Uint16(b[0:2]))
		b = b[2:]
	}
	if len(b) == 1 {
		// Последний байт нечётной длины — СТАРШИЙ байт неполного сетевого слова, то есть младший в
		// машинном порядке: добавляется как есть.
		s += uint64(b[0])
	}
	return s
}

// Word — слагаемое-число (например, номер протокола или длина) в том же машинном порядке, в каком
// складываются слова из буфера. Отдельной функцией, чтобы перестановка не повторялась на месте
// вызова и не забывалась.
func Word(v uint16) uint64 { return uint64(v>>8 | v<<8) }

// Fold сворачивает накопленное до 16 бит, дополняет и возвращает в СЕТЕВОМ порядке — то есть
// готовым для записи в поле пакета через binary.BigEndian.PutUint16.
func Fold(s uint64) uint16 {
	// Переносов не больше 32 бит на любой длине пакета, поэтому трёх сложений хватает с запасом.
	s = s&0xFFFFFFFF + s>>32
	s = s&0xFFFF + s>>16
	s = s&0xFFFF + s>>16
	v := uint16(^s)
	return v>>8 | v<<8
}

// FoldNoInv — то же, но БЕЗ дополнения: такой вид требует поле, оставленное под разгрузку
// устройству (VIRTIO_NET_HDR_F_NEEDS_CSUM), — там лежит сумма псевдозаголовка, которую устройство
// достроит нагрузкой.
func FoldNoInv(s uint64) uint16 {
	s = s&0xFFFFFFFF + s>>32
	s = s&0xFFFF + s>>16
	s = s&0xFFFF + s>>16
	v := uint16(s)
	return v>>8 | v<<8
}

// Of — готовая сумма над одним куском: столько же, сколько Fold(Sum(b)). Ею считается заголовок
// IPv4 и ею же ЗАВЕРШАЕТСЯ неполная сумма: поле с суммой псевдозаголовка входит в считаемый
// отрезок, поэтому отдельного слагаемого не нужно — ровно так это делает ядро в skb_checksum_help.
func Of(b []byte) uint16 { return Fold(Sum(b)) }

// PseudoV4 — сумма псевдозаголовка IPv4 для протокола proto и длины L4-части l4len. Без свёртки:
// её складывают с телом (TCPv4) или сворачивают отдельно (поле под разгрузку).
func PseudoV4(saddr, daddr []byte, proto byte, l4len int) uint64 {
	return Sum(saddr[:4]) + Sum(daddr[:4]) + Word(uint16(proto)) + Word(uint16(l4len))
}

// PseudoV6 — то же для IPv6: адреса по 16 байт, длина 32-битная (но пакетов длиннее 65535 у нас
// нет, поэтому в слово она укладывается).
func PseudoV6(saddr, daddr []byte, proto byte, l4len int) uint64 {
	return Sum(saddr[:16]) + Sum(daddr[:16]) + Word(uint16(proto)) + Word(uint16(l4len))
}

// TCPv4 — полная сумма сегмента TCP с псевдозаголовком; на готовом сегменте даёт 0.
func TCPv4(saddr, daddr [4]byte, seg []byte) uint16 {
	return Fold(PseudoV4(saddr[:], daddr[:], 6, len(seg)) + Sum(seg))
}
