// ErrDead — путь молчит при активной отправке. Отдельная ошибка: вызывающий на неё поднимает
// соединение заново, а не завершает работу.
var ErrDead = errors.New("link: путь молчит при активной отправке")

// ErrPathGone — отправить не удалось потому, что пути наружу больше нет: интерфейс упал, адрес
// уехал, маршрут исчез. Отдельно от прочих ошибок отправки, потому что решение разное: здесь нет
// смысла ни повторять, ни ждать тишины сорок пять секунд — соединение надо поднимать заново, а
// перед этим дождаться, пока сеть вернётся.
//
// Прежде такая ошибка была неотличима от любой другой и просто увеличивала счётчик отброшенных: при
// пропавшем интернете клиент продолжал молотить в мёртвый сокет, пока не истечёт DeadMS.
var ErrPathGone = errors.New("link: путь наружу пропал")

// ErrAgain — прямо сейчас читать нечего. Тот же смысл, что у tun.ErrAgain, и та же роль: цикл
// приёма перестаёт добирать пакеты, отдаёт накопленное ядру и уходит ждать. Отказом это НЕ является.
var ErrAgain = errors.New("link: пока нечего читать")

// Conn — поддельное TCP-соединение к хабу.
//
// ЗАМОК ЗДЕСЬ ЕСТЬ, В ОТЛИЧИЕ ОТ РЕАЛИЗАЦИИ НА C, и это следствие того, что цикл в Go устроен
// иначе. В C один поток на соединение и один poll на два дескриптора, поэтому состояние никому не
// приходится защищать. Здесь направления разведены по горутинам (блокирующее чтение вместо poll —
// так этот же код работает и на тех системах, где poll по TUN устроен по-другому), а значит номер
// последовательности трогают двое: поток данных и тот, кто отправляет подтверждения и keepalive.
//
// Цена замка названа честно: около двадцати наносекунд на пакет без соперничества против примерно
// микросекунды, которую на том же пакете стоит AEAD, — то есть проценты процента. Соперничество
// низкое по построению: обратный путь отправляет только голые подтверждения.
type Conn struct {
	mu sync.Mutex

	SAddr, DAddr [4]byte
	SPort, DPort uint16

	isnTX, isnRX uint32
	seq, ack     uint32
	state        int
	synTries     int
	unacked      int

	born, lastRX, lastTX, lastAck int64

	// lastDataTX — когда мы последний раз отправили НАГРУЗКУ, а не голое подтверждение.
	//
	// Приговор о мёртвом пути обязан считаться от него, а не от lastTX, и разница не тонкая.
	// Голое подтверждение ничего не спрашивает: ответа на него не будет по построению, потому что
	// другая сторона подтверждает подтверждения не больше, чем настоящий стек. Пока мерка была
	// «отправили после того, как получили», подтверждение считалось разговором — и сторона,
	// которая ТОЛЬКО ПОДТВЕРДИЛА принятое и замолчала, через DeadMS объявляла живой путь мёртвым.
	//
	// На хабе это уносило простаивающую сессию: он подтверждал последнюю запись пира, дальше оба
	// молчали (свой keepalive хаб на покое не шлёт — ему нечего сказать), и через восемь секунд
	// сессия освобождалась. Пир об этом не узнавал никак: RST на его следующую запись не уходил,
	// хаб просто перестал отвечать, — и переподнимал соединение по своей тишине. У клиента та же
	// беда на скачивании: принял, подтвердил, поток кончился — и туннель пересоздавался на ровном
	// месте. Поймано захватом на живой связи роутер↔VPS.
	lastDataTX int64

	// tickAt и stall — учёт СВОЕЙ незанятости.
	//
	// tickAt — когда Tick вызывали в прошлый раз; stall — сколько времени за ТЕКУЩУЮ тишину наш
	// собственный цикл вообще не исполнялся. Тишина сравнивается с DeadMS за вычетом stall, поэтому
	// «нам не давали процессор» больше не выглядит как «путь умер». Обнуляется на любом принятом
	// сегменте: запас относится к текущей тишине, а не накапливается за всё время жизни.
	tickAt, stall int64

	// win — ОБЪЯВЛЯЕМОЕ окно, и оно меняется, а не стоит на месте.
	//
	// Постоянное окно — один из самых дешёвых признаков, какие есть у наблюдателя: в записи
	// настоящего соединения окно принимающей стороны меняется на каждом чтении приложения (в
	// замере — 141 разное значение на клиенте и 10 на сервере), а у нас стояло ровно одно на все
	// шесть тысяч пакетов. Считать «сколько разных значений окна» умеет любой разбор потока, и
	// единица там — это не «похоже на TLS», это «вообще не похоже на стек TCP».
	//
	// Мы контролем потока не пользуемся, поэтому значение можем выбирать свободно — но НЕ любое:
	// conntrack по дороге верит объявленному окну и метит наши же сегменты недействительными, как
	// только неподтверждённого в полёте становится больше. Поэтому блуждание идёт в верхней части
	// диапазона: при масштабе 7 даже нижняя граница означает восемь мегабайт в полёте.
	win  uint16
	wrnd uint64

	// rxSinceAck — сколько сегментов С ДАННЫМИ принято с прошлого ГОЛОГО подтверждения.
	//
	// Считается отдельно от unacked и НЕ обнуляется отправкой данных, и это не оплошность. У
	// настоящей загрузки обратное направление состоит в основном из голых подтверждений: клиент
	// принял 6154 сегмента и отправил 1857 голых ACK — примерно один на три. У нас же каждое
	// внутреннее подтверждение TCP едет как данные и заодно подтверждает принятое, поэтому голых
	// ACK не было почти вовсе (5 штук на 2423 пакета). Разница считается одной строкой и говорит
	// «это туннель, а не загрузка».
	//
	// Поэтому подтверждаем и данными, и отдельно: лишние 40 байт на три принятых полноразмерных
	// сегмента — это 0,9% обратного направления, которое при загрузке всё равно почти пустое.
	// Номер подтверждения при этом каждый раз новый (мы непрерывно принимаем), так что для
	// посредника это не повторные ACK и на быструю повторную передачу он их не примет.
	rxSinceAck int

	rxTotal  int64
	lastBare int64

	// winFresh — принимали ли данные с прошлой смены окна.
	//
	// Окно меняется ТОЛЬКО у того, кто принимает, и это тоже измерено: у настоящей загрузки
	// принимающая сторона показала 141 разное значение, отдающая — 10. Первая версия шевелила окно
	// у обеих сторон на каждом пакете и давала 2015 разных значений — то есть перестаралась ровно
	// настолько же, насколько прежняя версия недоделала.
	winFresh bool

	// pshRun — сколько сегментов подряд ушло без флага PSH. Настоящий стек ставит PSH на последнем
	// сегменте записи приложения, то есть примерно на каждом шестом при потоковой загрузке (в
	// замере — 16%); у нас он стоял на 99%, и это тоже считается одной строкой.
	pshRun int

	// ---- пакетная отправка (см. RawBatch) ----
	//
	// Буферы ПРИНАДЛЕЖАТ СОЕДИНЕНИЮ и защищены его же замком: SendRecord держит его от выдачи
	// смещения до последнего байта. Держать их у вызывающего значило бы отдать один буфер под два
	// разных замка — ровно та ошибка, которая уже случилась с буфером продолжения записи на хабе.
	hdrs [batchSegs * 20]byte
	segs [batchSegs]Seglet

	raw Raw
}

// batchSegs — сколько сегментов записи умеет отдать одна пачка.
//
// Шестнадцать: предельная запись (8213 байт вместе с заголовком и тегом) при самом узком сегменте,
// какой вообще бывает (MTUFloor 576 плюс накладные минус заголовки — 597 байт), режется на
// четырнадцать. Шестнадцать — это тот же предел с запасом на два, и он выведен из чисел формата, а
// не выбран на глаз; больше не нужно, потому что записей длиннее MaxRecord мы не отправляем никогда.
const batchSegs = 16

// Seglet — сегмент, разложенный на заголовок и тело.
//
// РАЗДЕЛЬНО, А НЕ ОДНИМ КУСКОМ, и это снимает копию. Запись, разрезанная на сегменты, лежит в
// памяти ОДНИМ куском: тело второго сегмента продолжает тело первого. Своего заголовка перед ним
// нет и быть не может — там последние байты предыдущего сегмента. Прежде продолжение поэтому
// копировалось в отдельный буфер (по 20 байт заголовка плюс до 1460 байт тела на сегмент); отправка
// двумя частями отдаёт ядру заголовок и тело как есть, и копировать нечего.
type Seglet struct {
	Hdr  []byte // ровно 20 байт заголовка TCP
	Body []byte // нагрузка этого сегмента: срез в записи, без копии
}

// Raw — сырой сокет. Интерфейс, а не структура, ровно по двум причинам: платформы устроены
// по-разному (на Windows сырой TCP запрещён вовсе, и там придётся ходить через перехватчик), а
// тест хочет соединение без прав root.
type Raw interface {
	Send(seg []byte) error
	Recv(buf []byte) (int, error)
	// WaitRead ждёт готовности к чтению не дольше timeout; false — истекло время.
	WaitRead(timeout time.Duration) (bool, error)
	Local() [4]byte
	Close() error
}

// errNoBatch — этот сокет пачку не умеет (нет sendmmsg или он не реализован на этой платформе).
// Вызывающий на неё уходит на путь по одному сегменту.
var errNoBatch = errors.New("link: пакетная отправка недоступна")

// RawBatch — сырой сокет, умеющий отдать несколько сегментов ОДНИМ системным вызовом.
//
// Необязательное расширение, а не часть Raw, потому что умеют это не все: на Linux это sendmmsg, а
// на платформе без него (и в тестовом сокете) остаётся прежний путь по одному сегменту. Проверяется
// утверждением типа — так же, как SendTo.
//
// ЗАЧЕМ. Замер на этой машине, сегмент 1480 байт в сырой сокет: по одному 3325 нс, пачкой по восемь
// 2641 нс, пачкой по 64 — 2543 нс. То есть около четверти работы снимается, и снимается она с
// САМОГО дорогого шага на быстрой машине: путь вывода ядра стоит там больше, чем шифр и сумма
// вместе. Записи мы и так режем на сегменты пачками по шесть-восемь, поэтому выигрыш достаётся без
// единого изменения формата.
type RawBatch interface {
	// SendBatch отдаёт сегменты по порядку. Возвращает, сколько ушло: остаток вызывающий НЕ
	// повторяет — датаграммы потеряны, а номера последовательности уже потрачены.
	SendBatch(segs []Seglet) (int, error)
}

// Open открывает соединение и отправляет SYN.
//
// shard задаёт МЛАДШИЕ БИТЫ порта источника: порт выбираем мы сами, а хаб раскладывает соединения
// по своим воркерам именно по этим битам. Клиент с несколькими соединениями обязан дать им РАЗНЫЕ
// значения — иначе все его соединения достанутся одному воркеру хаба, и второе ядро там не
// заработает. Отрицательное значение означает «любой порт».
func Open(raw Raw, daddr [4]byte, dport int, shard int, isnTX uint32, sport uint16) (*Conn, error) {
	c := &Conn{
		raw:   raw,
		DAddr: daddr,
		DPort: uint16(dport),
		SPort: sport,
		isnTX: isnTX,
		SAddr: raw.Local(),
		state: StateSynSent,
	}
	if shard >= 0 {
		c.SPort = c.SPort&^uint16(wire.ConnsMax-1) | uint16(shard&(wire.ConnsMax-1))
	}
	c.seq = isnTX
	c.wrnd = uint64(isnTX)*6364136223846793005 + 1442695040888963407
	c.win = winFloor + uint16(c.wrnd>>33%uint64(winCeil-winFloor))
	now := nowMS()
	c.born, c.lastRX, c.lastTX, c.lastDataTX = now, now, now, now
	if err := c.send(SYN, nil, OptScale); err != nil {
		raw.Close()
		return nil, fmt.Errorf("link: SYN не ушёл: %w", err)
	}
	c.synTries = 1
	return c, nil
}

func nowMS() int64 {
	// Монотонные часы: время стенное на десктопе прыгает при синхронизации и при выходе из сна, и
	// «тишина сорок пять секунд» случилась бы на ровном месте — как раз после пробуждения ноутбука.
	return time.Now().UnixNano() / int64(time.Millisecond)
}

func (c *Conn) Close() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.state = StateClosed
	return c.raw.Close()
}

// State — текущее состояние. Только для журнала и решений вызывающего.
func (c *Conn) State() int {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.state
}

// Age — сколько живёт соединение. Нужно пределам: ретайр наступает по объёму ИЛИ по времени.
func (c *Conn) Age() int64 { return nowMS() - c.born }

// send отправляет служебный сегмент или короткую нагрузку. Замок обязан быть взят вызывающим.
func (c *Conn) send(flags byte, payload []byte, opts int) error {
	buf := make([]byte, 60+len(payload))
	n := BuildSeg(buf, c.SAddr, c.DAddr, c.SPort, c.DPort, c.seq, c.ack, flags, opts, payload)
	err := c.raw.Send(buf[:n])
	// Номер двигается ДАЖЕ при неудачной отправке — см. инвариант в шапке пакета. Датаграмма
	// потеряна, номер потрачен; вернуть его назад значило бы однажды повторить nonce.
	c.seq += uint32(len(payload))
	if flags&SYN != 0 {
		c.seq++ // SYN занимает один номер
	}
	c.lastTX = nowMS()
	// Нагрузка — это разговор, голое подтверждение — нет. См. lastDataTX.
	if len(payload) > 0 {
		c.lastDataTX = c.lastTX
	}
	if flags&ACK != 0 {
		c.unacked = 0
		c.lastAck = c.lastTX
	}
	return err
}

// Send отправляет служебный сегмент под замком: для рукопожатия и keepalive.
func (c *Conn) Send(flags byte, payload []byte) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.send(flags, payload, OptNone)
}

// RelNext — смещение, с которым уйдёт следующий пакет данных.
//
// Шифровать по нему НЕЛЬЗЯ: между чтением и отправкой номер может уйти вперёд в другой горутине.
// Для шифрования есть SendData с обратным вызовом, где смещение выдаётся под замком. Здесь оно
// нужно только для пределов соединения (ретайр), где ошибка на пакет-другой безразлична.
func (c *Conn) RelNext() uint32 {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.seq - c.isnTX
}

// RelOf — смещение принятого сегмента.
func (c *Conn) RelOf(seq uint32) uint32 {
	c.mu.Lock()
	defer c.mu.Unlock()
	return wire.Rel(seq, c.isnRX)
}

// SendData отправляет ОДИН пакет данных, заголовок которого пишется ПЕРЕД нагрузкой в том же
// буфере.
//
// row — строка длиной не меньше wire.HdrRoom + plen, где нагрузка (готовая запись: заголовок
// записи, шифротекст и тег) окажется по смещению wire.HdrRoom - wire.RecHdr. Копий нет: сегмент
// уходит с того места, где его собрали.
//
// seal ВЫЗЫВАЕТСЯ ПОД ТЕМ ЖЕ ЗАМКОМ, что выдаёт смещение, и это несущая конструкция, а не
// удобство вызова.
//
// Первая версия отдавала смещение наружу (RelNext), вызывающий шифровал им и только потом звал
// отправку. Между этими двумя шагами в другой горутине помещалась целая отправка — и тогда два
// пакета шифровались ОДНИМ смещением, то есть одним nonce под одним ключом. Повтор nonce означает
// не потерянный пакет, а полную потерю стойкости AEAD на этой сессии, причём молча. Поймать это
// тестом почти невозможно: окно гонки — сотни наносекунд, а последствие не видно вообще никак.
//
// Поэтому выдача смещения, шифрование им и запись заголовка стали одной неделимой операцией.
// Ровно тот же инвариант записан в движке на C у send_to хаба — там он выражен тем, что вся
// отправка идёт под замком сессии.
func (c *Conn) SendData(row []byte, plen int, seal func(rel uint32) error) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.state != StateEst {
		return errors.New("link: соединение не установлено")
	}
	rel := c.seq - c.isnTX
	if seal != nil {
		if err := seal(rel); err != nil {
			// Смещение НЕ тратим: наружу ничего не ушло, а пропуск в нумерации безвреден только
			// когда пакет действительно был отправлен.
			return err
		}
	}
	off := wire.HdrRoom - wire.RecHdr - 20
	seg := row[off : wire.HdrRoom-wire.RecHdr+plen]
	c.fillHdr(seg, c.seq, plen)
	c.seq += uint32(plen)
	c.afterSend()
	return c.raw.Send(seg)
}

// OnSeg учитывает принятый сегмент: подтверждения, состояние, счётчики.
//
// data == true означает «несёт данные, которые надо разобрать»; err == ErrDead — пришёл RST, и
// соединение закрылось.
func (c *Conn) OnSeg(s *Seg) (data bool, err error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.lastRX = nowMS()
	c.stall = 0
	// RST принимается только с номером, которого мы ЖДЁМ, — то же правило, что у настоящего
	// стека после RFC 5961, и то же, что в движке на C (xsconn.c, xs_conn_on_seg). Четвёрка
	// наблюдаема на всём пути, адрес источника подделывается свободно, а аутентификации на
	// служебном сегменте нет по построению: обфускатор притворяется TCP, а не защищает его.
	// Пока номер не спрашивался, один пакет с угаданной четвёркой рвал живой туннель, и
	// повторять его можно было сколько угодно.
	//
	// Почему именно РАВЕНСТВО, а не «в пределах окна»: окно объявляется с масштабом, то есть
	// восемь мегабайт (см. nextWin), и «в окне» стоило бы слепому 2^32/8 МиБ ≈ 512 попыток.
	// Равенство стоит 2^32.
	//
	// Законный RST от этого не страдает, и он один — хаба на порту нет (упал, переехал, порт
	// закрыт правилом). Ядро той стороны отвечает RST'ом, номер которого равен полю
	// подтверждения нашего сегмента, то есть ровно c.ack. На наш SYN, у которого поля
	// подтверждения нет, ядро отвечает RST с подтверждением нашего ISN + 1 — своего номера у
	// него в этой фазе ещё нет, и проверять можно только его.
	//
	// Отвергнутый RST не значит «висеть вечно»: путь, который действительно умер, всё равно
	// объявляется мёртвым по тишине через DeadMS.
	if s.Flags&RST != 0 {
		if c.state == StateSynSent {
			if s.Flags&ACK == 0 || s.Ack != c.isnTX+1 {
				return false, nil
			}
		} else if s.Seq != c.ack {
			return false, nil
		}
		c.state = StateClosed
		return false, ErrDead
	}
	if c.state == StateSynSent {
		if s.Flags&(SYN|ACK) != SYN|ACK {
			return false, nil
		}
		c.isnRX = s.Seq
		c.ack = s.Seq + 1
		c.state = StateEst
		// Подтверждаем рукопожатие сразу: без этого хаб не считает соединение установившимся и
		// будет повторять SYN-ACK.
		_ = c.send(ACK, nil, OptNone)
		return false, nil
	}
	// Подтверждение нашего SYN-ACK: с этой секунды соединение установлено. Без этой строки
	// слушающая сторона остаётся в StateSynRcvd навсегда и молча отбрасывает ВСЕ данные — при
	// полностью верном рукопожатии. Строка была потеряна при переносе с C, и снаружи это выглядело
	// как «хаб не ответил на рукопожатие»: SYN-ACK уходит, а на Hello тишина.
	if c.state == StateSynRcvd && s.Flags&ACK != 0 {
		c.state = StateEst
	}
	if len(s.Payload) == 0 || c.state != StateEst {
		return false, nil
	}
	c.ack = NextAck(c.ack, s.Seq, len(s.Payload))
	c.unacked++
	c.rxSinceAck++
	c.rxTotal++
	// Окно шевелим не на каждом принятом сегменте, а раз в восемь: настоящий приёмник меняет его,
	// когда приложение вычитало порцию, а не на каждый пакет. Первая версия двигала на каждом и
	// дала 934 разных значения там, где у настоящего клиента 141 — перестараться здесь так же
	// заметно, как не сделать вовсе.
	if c.rxTotal%8 == 0 {
		c.winFresh = true
	}
	// ГОЛОЕ подтверждение отправляется ЗДЕСЬ, а не по таймеру, и это принципиально: таймер тикает
	// раз в двадцать миллисекунд, то есть даёт не больше пятидесяти подтверждений в секунду, а
	// принимаем мы при загрузке пятьдесят тысяч сегментов в секунду. По таймеру голых ACK выходило
	// восемь штук на восемь мегабайт — то есть признак «туннель, а не загрузка» оставался на месте.
	if c.rxSinceAck >= AckBare {
		if now := time.Now().UnixNano(); now-c.lastBare >= AckBareGapNS {
			_ = c.send(ACK, nil, OptNone)
			c.rxSinceAck = 0
			c.lastBare = now
		}
	}
	return true, nil
}

// Tick: раз в TickMS — повторить SYN, отправить отложенное подтверждение, сказать про мёртвый путь.
//
// «Активная отправка» здесь означает «мы отправили НАГРУЗКУ после того, как получили», а не «мы
// вообще когда-нибудь отправляли» и не «мы отправили хоть что-нибудь». Оба уточнения оплачены
// ошибками: со вторым условием туннель на покое, однажды отправивший пакет, считался бы мёртвым
// навсегда; с третьим — голое подтверждение сходило за разговор, и сторона, которая только
// подтвердила принятое и замолчала, убивала живой путь через DeadMS (см. lastDataTX).
func (c *Conn) Tick() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.tick(nowMS())
}

// tick — то же решение, но со временем аргументом. Так его проверяет стенд: покой в двадцать пять
// секунд надо уметь прожить, не платя за него настоящими секундами и не подменяя часы процесса.
// Ровно та же форма, что у xs_conn_tick в движке на C, и это не совпадение — расхождение в этом
// решении означает, что один и тот же пир на одном хабе живёт, а на другом переподнимается.
//
// Замок обязан быть взят вызывающим.
func (c *Conn) tick(now int64) error {
	// ДВА вида не нашей тишины, и оба обязаны вычитаться из порога.
	//
	// Первый — нас не исполняли: перерыв между вызовами больше stallGapMS означает, что горутине
	// не давали процессор. Ради него этот учёт и заводился.
	//
	// Второй — НАМ БЫЛО НЕЧЕГО СКАЗАТЬ (lastTX <= lastRX). Пока мы молчим, путь не обязан
	// отвечать ничем, и это время такая же не наша тишина, как первая. Без этого вычета покой
	// дольше порога убивал соединение ПЕРВЫМ ЖЕ тиком после того, как отправлять снова стало что:
	// вся тишина уже была накоплена на покое, и другой стороне не оставалось на круг ни
	// миллисекунды. На живой связи роутер↔VPS это выглядело как переподъём каждые
	// пятнадцать-двадцать пять секунд, и тем чаще, чем МЕНЬШЕ шло трафика (пир говорит раз в
	// двадцать пять секунд по PersistentKeepalive, а хаб на покое молчит сам). В пространствах
	// имён такого покоя не бывает — трафик там идёт непрерывно, — поэтому поймано это вживую.
	if c.tickAt != 0 {
		if gap := now - c.tickAt; gap > stallGapMS || c.lastDataTX <= c.lastRX {
			c.stall += gap
		}
	}
	c.tickAt = now
	if c.state == StateSynSent {
		if now-c.lastTX >= SynRetryMS {
			if c.synTries >= SynRetries {
				return ErrDead
			}
			// Повтор ТОГО ЖЕ SYN: номер уже потрачен на первую попытку, поэтому откатываем его на
			// единицу перед отправкой — это единственное место, где номер идёт назад, и оно
			// безопасно, потому что нагрузки в SYN нет и nonce из него не выводится.
			c.seq--
			_ = c.send(SYN, nil, OptScale)
			c.synTries++
		}
		return nil
	}
	if c.state != StateEst {
		return nil
	}
	if c.unacked > 0 && (c.unacked >= AckSegs || now-c.lastAck >= AckMS) {
		_ = c.send(ACK, nil, OptNone)
		c.rxSinceAck = 0
	}
	// Мёртвый путь считается ТОЛЬКО при активной отправке: молчание на покое — это покой, а не
	// поломка, и поднимать из-за него соединение заново значило бы дёргать туннель на простое.
	if c.lastDataTX > c.lastRX && now-c.lastRX-c.stall > DeadMS {
		return ErrDead
	}
	return nil
}

// SinceTX — сколько прошло с последней отправки. Нужно keepalive.
func (c *Conn) SinceTX() int64 {
	c.mu.Lock()
	defer c.mu.Unlock()
	return nowMS() - c.lastTX
}

// Recv читает один пакет с сырого сокета и разбирает его, отбрасывая всё, что не принадлежит
// этой четвёрке. Фильтр на сокете отбивает основную массу чужого ещё в ядре, но проверка нужна и
// здесь: фильтр отбирает по порту, а не по нашему соединению целиком.
func (c *Conn) Recv(buf []byte) (Seg, bool, error) {
	n, err := c.raw.Recv(buf)
	if err != nil {
		return Seg{}, false, err
	}
	s, ok := ParseSeg(buf[:n])
	if !ok || s.SPort != c.DPort || s.DPort != c.SPort {
		return Seg{}, false, nil
	}
	return s, true, nil
}

// WaitRead — ожидание на сыром сокете.
func (c *Conn) WaitRead(d time.Duration) (bool, error) { return c.raw.WaitRead(d) }

func putU16(b []byte, v uint16) { b[0], b[1] = byte(v>>8), byte(v) }
func putU32(b []byte, v uint32) {
	b[0], b[1], b[2], b[3] = byte(v>>24), byte(v>>16), byte(v>>8), byte(v)
}

// ---- сторона, которая слушает ----------------------------------------------

// StateSynRcvd — увидели SYN, ответили SYN-ACK, ждём подтверждения. У клиента такого состояния
// нет: он всегда начинает соединение сам.
const StateSynRcvd = 3

// Accept создаёт соединение по ПРИНЯТОМУ SYN и отвечает SYN-ACK.
//
// raw обязан быть подключён к адресу того, кто позвонил (link.OpenRawSend): тогда ядро само
// демультиплексирует отправку, и адрес не приходится указывать на каждый пакет. Тот же приём, что
// в движке на C.
//
// isn — наш начальный номер. Приходит снаружи, а не берётся здесь, ровно потому же, почему у
// клиента: источник случайности выбирает вызывающий, а тест хочет предсказуемые номера.
func Accept(raw Raw, seg *Seg, listenPort uint16, isn uint32) (*Conn, error) {
	c := &Conn{
		raw:   raw,
		SAddr: seg.DAddr,
		DAddr: seg.SAddr,
		SPort: listenPort,
		DPort: seg.SPort,
		isnTX: isn,
		isnRX: seg.Seq,
	}
	c.seq = isn
	c.ack = seg.Seq + 1
	c.wrnd = uint64(isn)*6364136223846793005 + 1442695040888963407
	c.win = winFloor + uint16(c.wrnd>>33%uint64(winCeil-winFloor))
	now := nowMS()
	c.born, c.lastRX, c.lastTX, c.lastDataTX = now, now, now, now
	c.state = StateSynRcvd
	if err := c.SendSynAck(); err != nil {
		return nil, err
	}
	return c, nil
}

// SendSynAck отвечает на SYN. Зовётся и на ПОВТОРНЫЙ SYN — тогда номер откатывается на единицу,
// потому что первая попытка его уже потратила: это то же единственное безопасное место для откака
// номера, что и повтор SYN у клиента (нагрузки в нём нет, nonce из него не выводится).
func (c *Conn) SendSynAck() error {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.synTries > 0 {
		c.seq--
	}
	c.synTries++
	return c.send(SYN|ACK, nil, OptScale)
}

// OnSynAgain — повторный SYN по живой четвёрке: обновляем номера и отвечаем снова. Отдельным
// методом, а не внутри OnSeg, потому что решение «это новая сессия или повтор» принимает
// вызывающий: у него есть таблица сессий, а у соединения её нет.
//
// ЗВАТЬ ЭТО МОЖНО ТОЛЬКО ПОКА СОЕДИНЕНИЕ НЕ ПОДТВЕРЖДЕНО. Метод переписывает isnRX, а из него
// выводится смещение принятой записи и nonce её расшифровки, — то есть на работающей сессии он
// останавливает входящий поток целиком. SYN не несёт ни байта аутентификации, поэтому решать,
// повтор это или посторонний пакет, обязан тот, кто знает фазу сессии: см. hub.worker.onSeg, где
// SYN в сессию не в фазе «syn» отбрасывается со счётчиком.
func (c *Conn) OnSynAgain(seg *Seg) error {
	c.mu.Lock()
	c.isnRX = seg.Seq
	c.ack = seg.Seq + 1
	c.state = StateSynRcvd
	c.lastRX = nowMS()
	if c.synTries > 0 {
		c.seq--
	}
	c.synTries++
	err := c.send(SYN|ACK, nil, OptScale)
	c.mu.Unlock()
	return err
}

// Idle — сколько прошло с последнего принятого сегмента. Нужно уборке сессий на хабе.
func (c *Conn) Idle() int64 {
	c.mu.Lock()
	defer c.mu.Unlock()
	return nowMS() - c.lastRX
}

// NeedKeepalive — получали, но давно не отправляли.
//
// Хаб ОБЯЗАН присылать пустую запись в этом случае, а не «может»: пир считает путь мёртвым по
// тишине при активной отправке, и без этого односторонний трафик (пир отправляет, отвечать нечем)
// выглядел бы для него обрывом. Ровно это и показал живой стенд движка на C. Так же устроен
// WireGuard: keepalive посылает ПРИНИМАЮЩАЯ сторона.
func (c *Conn) NeedKeepalive(everyMS int64) bool {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.lastRX > c.lastTX && nowMS()-c.lastTX >= everyMS
}

// Границы блуждания объявляемого окна. Верх — предел поля; низ выбран так, чтобы при масштабе 7
// даже он означал больше восьми мегабайт в полёте: ниже начинается риск, что conntrack по дороге
// сочтёт наши сегменты недействительными (этот отказ уже стоил проекту потолка в 10 Мбит/с).
const (
	winFloor = 63000
	winCeil  = 65535
)

// nextWin — следующее объявляемое окно. Замок обязан быть взят вызывающим.
//
// Блуждание, а не случайное число: у настоящего приёмника окно ползёт вверх и вниз небольшими
// шагами, потому что приложение читает данные порциями. Прыжки по всему диапазону выглядели бы
// так же неестественно, как постоянное значение, только иначе.
func (c *Conn) nextWin() uint16 {
	// Окно шевелится только у ПРИНИМАЮЩЕЙ стороны: у отдающей приложение ничего не вычитывает, и
	// значение стоит почти неподвижно. Ровно так ведут себя настоящие стороны загрузки.
	if !c.winFresh {
		return c.win
	}
	c.winFresh = false
	c.wrnd = c.wrnd*6364136223846793005 + 1442695040888963407
	step := int(c.wrnd>>35%97) - 48 // ±48
	v := int(c.win) + step
	if v > winCeil {
		v = winCeil - (v - winCeil)
	}
	if v < winFloor {
		v = winFloor + (winFloor - v)
	}
	c.win = uint16(v)
	return c.win
}

// nextFlags — флаги сегмента данных: ACK всегда, PSH по политике.
//
// Политика повторяет поведение настоящего стека: PSH означает «конец записи приложения», и при
// потоковой передаче он приходится примерно на каждый шестой сегмент. Мы не знаем, будет ли за
// этим пакетом следующий, поэтому считаем сегменты: шесть без PSH, потом с ним. Отдельно PSH
// ставится после ПАУЗЫ — там запись действительно закончилась.
func (c *Conn) nextFlags() byte {
	now := nowMS()
	if now-c.lastTX >= 5 {
		c.pshRun = 0
		return PSH | ACK
	}
	c.pshRun++
	if c.pshRun >= 6 {
		c.pshRun = 0
		return PSH | ACK
	}
	return ACK
}

// SendRecord отправляет ОДНУ запись, разрезая её на сегменты по maxSeg байт.
//
// Зачем резать — в шапке wire.Reasm и wire.BatchBuild: у настоящего TLS запись живёт своей длиной
// и границ сегментов не соблюдает, а у нас соблюдала всегда, и это был самый дешёвый признак
// протокола. Заодно это единственный способ увезти пачку кадров: она больше сегмента по
// построению.
//
// scratch — буфер под второй и последующие сегменты: их заголовки TCP иначе затёрли бы хвост
// предыдущего. Нужен размером не меньше 20 + maxSeg.
//
// БУФЕР ОБЯЗАН ПРИНАДЛЕЖАТЬ ТОМУ ЖЕ ЗАМКУ, ЧТО И СОЕДИНЕНИЕ, — то есть либо одной горутине, либо
// той же сессии. Замок берётся ниже, но он защищает соединение, а не переданную сюда память: у
// хаба буфер лежал у ВОРКЕРА, а отправка шла под замком сессии-получателя, и на двух получателях
// один буфер писали одновременно. Снаружи это выглядело как отказ по тегу AEAD у пира и молчаливая
// потеря записи. У хаба буфер теперь у сессии (hub.session.cont), у клиента — у горутины
// соединения (client.outbound).
//
// ВСЕ СЕГМЕНТЫ УХОДЯТ ПОД ОДНИМ ЗАМКОМ. Между ними номер последовательности двигать никому нельзя:
// продолжение приедет с чужим номером, и собрать запись будет невозможно. По той же причине
// смещение выдаётся один раз на всю запись — им зашифрована вся она целиком.
func (c *Conn) SendRecord(row []byte, plen, maxSeg int, scratch []byte, seal func(rel uint32) error) error {
	if maxSeg <= 0 || plen <= maxSeg {
		return c.SendData(row, plen, seal)
	}
	if len(scratch) < 20+maxSeg {
		return errors.New("link: мал буфер под продолжение записи")
	}
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.state != StateEst {
		return errors.New("link: соединение не установлено")
	}
	rel := c.seq - c.isnTX
	if seal != nil {
		if err := seal(rel); err != nil {
			return err
		}
	}
	body := row[wire.HdrRoom-wire.RecHdr : wire.HdrRoom-wire.RecHdr+plen]
	seq := c.seq
	// Номер тратится на ВСЮ запись сразу и до отправки: неудача на середине не должна оставить
	// смещение недоиспользованным — вернуть его назад значило бы однажды повторить nonce.
	c.seq += uint32(plen)
	defer c.afterSend()

	// ПАЧКОЙ, ЕСЛИ СОКЕТ УМЕЕТ. Заголовки собираются в свой массив, тела берутся срезами прямо из
	// записи, и всё уезжает одним вызовом: минус системный вызов на сегмент и минус копия
	// продолжения. Если сокет пачку не умеет — прежний путь ниже, байт в байт тот же.
	if b, ok := c.raw.(RawBatch); ok {
		segs := c.segs[:0]
		hdrs := c.hdrs[:]
		for off, i := 0, 0; off < plen; i++ {
			n := plen - off
			if n > maxSeg {
				n = maxSeg
			}
			if i >= batchSegs {
				// Сегментов больше, чем мест под заголовки: такого не бывает при законных
				// размерах (предельная запись 8213 байт при самом узком сегменте 597 даёт
				// четырнадцать), но досылать хвост прежним путём дешевле, чем считать это
				// невозможным.
				break
			}
			h := hdrs[i*20 : i*20+20]
			c.fillHdrInto(h, seq+uint32(off), body[off:off+n])
			segs = append(segs, Seglet{Hdr: h, Body: body[off : off+n]})
			off += n
		}
		if len(segs)*maxSeg >= plen {
			n, err := b.SendBatch(segs)
			if !errors.Is(err, errNoBatch) {
				// Неотправленный остаток НЕ повторяется: номера на всю запись потрачены, и повтор с
				// теми же номерами означал бы второй пакет с тем же nonce. Потеря датаграммы для
				// этого протокола обычна, повтор nonce — полная потеря стойкости AEAD.
				_ = n
				return err
			}
			// Сокет пачку не умеет — уходим на путь по одному сегменту ниже.
		}
	}

	seg1 := row[wire.HdrRoom-wire.RecHdr-20 : wire.HdrRoom-wire.RecHdr+maxSeg]
	c.fillHdr(seg1, seq, maxSeg)
	if err := c.raw.Send(seg1); err != nil {
		return err
	}
	off := maxSeg
	for off < plen {
		n := plen - off
		if n > maxSeg {
			n = maxSeg
		}
		out := scratch[:20+n]
		copy(out[20:], body[off:off+n])
		c.fillHdr(out, seq+uint32(off), n)
		if err := c.raw.Send(out); err != nil {
			return err
		}
		off += n
	}
	return nil
}

// fillHdr пишет заголовок TCP в начало сегмента (нагрузка идёт сразу за ним). Замок обязан быть
// взят вызывающим.
func (c *Conn) fillHdr(seg []byte, seq uint32, plen int) {
	c.hdrFields(seg[:20], seq)
	putU16(seg[16:18], Csum(c.SAddr, c.DAddr, seg[:20+plen]))
}

// fillHdrInto пишет заголовок в ОТДЕЛЬНЫЙ буфер: нагрузка лежит не за ним, а своим срезом, поэтому
// сумма считается по двум частям. Нужно пакетной отправке.
func (c *Conn) fillHdrInto(h []byte, seq uint32, body []byte) {
	c.hdrFields(h, seq)
	// Сумма по псевдозаголовку, заголовку и телу: те же байты, что сосчитал бы Csum над одним
	// куском, только сложенные из двух. Тождество проверяется тестом
	// (TestПачкаДаётТеЖеБайтыЧтоПоОдному): расхождение здесь означало бы поток, который conntrack
	// по дороге считает недействительным, — то есть тихо съеденный туннель.
	putU16(h[16:18], CsumParts(c.SAddr, c.DAddr, h[:20], body))
}

// hdrFields — поля заголовка, кроме суммы.
func (c *Conn) hdrFields(h []byte, seq uint32) {
	for i := 0; i < 20; i++ {
		h[i] = 0
	}
	putU16(h[0:2], c.SPort)
	putU16(h[2:4], c.DPort)
	putU32(h[4:8], seq)
	putU32(h[8:12], c.ack)
	h[12] = 5 << 4
	h[13] = c.nextFlags()
	putU16(h[14:16], c.nextWin())
}

func (c *Conn) afterSend() {
	now := nowMS()
	c.lastTX, c.lastAck, c.lastDataTX = now, now, now
	c.unacked = 0
}

// ISNRX — начальный номер той стороны. Нужен сборке записей: смещение считается от него.
func (c *Conn) ISNRX() uint32 {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.isnRX
}
