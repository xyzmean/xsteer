// Пороги. Значения взяты из движка на C, кроме особо отмеченных.
const (
	TickMS     = 20
	SynRetryMS = 1000
	SynRetries = 6
	// AckSegs — через сколько принятых сегментов подтверждать. Двойка, а не восьмёрка, — из
	// ПРАВДОПОДОБИЯ: Linux подтверждает примерно через сегмент, и поток, подтверждающий раз в
	// восемь, отличим от настоящего именно ритмом. Цена на обратном пути загрузки — 40 байт на
	// два сегмента по 1500, то есть 1,3%; при двустороннем трафике голых подтверждений не нужно
	// вовсе.
	AckSegs = 2
	AckMS   = 40
	// AckBare — через сколько принятых сегментов с данными отправлять ГОЛОЕ подтверждение, даже
	// если принятое уже подтверждено попутно ушедшими данными. Три — как у настоящей загрузки
	// (1857 голых ACK на 6154 принятых сегмента).
	AckBare = 3
	// AckBareGapNS — но не чаще, чем раз в двести микросекунд, то есть не больше пяти тысяч в
	// секунду.
	//
	// Ограничение по ЧАСТОТЕ, а не по числу, и вот почему. Каждое голое подтверждение — это
	// системный вызов на горячем пути приёма. Без ограничения на полутора гигабитах (55 тысяч
	// сегментов в секунду) выходило восемнадцать тысяч лишних вызовов в секунду и минус 20%
	// скорости — замерено. С ограничением на реальных скоростях (до ~180 Мбит/с) соотношение
	// голых подтверждений остаётся тем же, что у настоящей загрузки, а на предельных оно
	// ухудшается — но там уже никто и не разглядывает форму потока пакет за пакетом.
	AckBareGapNS = 200000
	// DeadMS — тишина при АКТИВНОЙ отправке, после которой путь считается мёртвым.
	//
	// БЫЛО СОРОК ПЯТЬ СЕКУНД, И ПРИЧИНА ОКАЗАЛАСЬ НЕ В ПУТИ, А В НАС. Пятнадцать секунд (порог
	// WireGuard) однажды сработали ЛОЖНО на живом роутере: два посторонних процесса заняли оба ядра,
	// наш получил 4% времени, входящие сегменты пролежали в очереди дольше порога — и туннель
	// пересоздался на ровном месте. Порог поднялся до сорока пяти, и это лечило симптом: тишина по
	// стенным часам смешивала «путь молчит» с «мы не работали», а разделить их было нечем.
	//
	// Теперь есть чем: Tick замечает, что его самого не вызывали (см. поле stall), и это время в
	// тишину не засчитывается. Смешения больше нет, и порог можно вернуть к тому, что диктует сам
	// протокол.
	//
	// А диктует он немного. При активной отправке обратный путь НЕ МОЛЧИТ ни секунды: хаб
	// подтверждает принятое голым ACK через AckMS (40 мс), и время последнего приёма обновляет любой
	// принятый сегмент, включая эти подтверждения. То есть при живом пути тишина измеряется
	// десятками миллисекунд, а не секундами, и восемь секунд — это двести пропущенных подтверждений
	// подряд. Запас оставлен на затор в мобильной сети, где ответ может опоздать на секунды.
	//
	// Что это даёт наружу: пропавший интернет замечается за восемь секунд вместо сорока пяти. Ещё
	// быстрее его замечают два других признака — ошибка отправки (ErrPathGone, мгновенно) и
	// изменение адреса или маршрута (слежение за netlink у клиента, тоже мгновенно), — а этот порог
	// закрывает единственный оставшийся случай: путь цел с точки зрения ядра, но пакеты в него
	// уходят в никуда.
	DeadMS = 8000
	// stallGapMS — с какого перерыва между вызовами Tick мы считаем, что не работали МЫ, а не путь.
	//
	// Секунда: исправный цикл клиента тикает раз в двадцать миллисекунд, обслуживание хаба — раз в
	// сто, то есть на порядок чаще. Перерыв в секунду означает, что горутине не давали процессор, —
	// ровно тот случай, из-за которого порог когда-то и подняли до сорока пяти секунд.
	stallGapMS = 1000
)

