// Пакет link — поддельное TCP-соединение поверх сырого сокета.
//
// ЗАЧЕМ ПОДДЕЛЬНОЕ TCP, А НЕ НАСТОЯЩЕЕ. Настоящее означало бы TCP внутри TCP: две системы
// повторов и два окна, накладывающиеся друг на друга, и лавину повторных передач при первой же
// потере — известный и хорошо изученный способ получить туннель, который «работает, но иногда
// встаёт». Здесь заголовок TCP настоящий (и потому проходит там, где UDP блокируют, и выглядит
// для DPI как обычная сессия на :443), а семантика остаётся датаграммной: один пакет — один
// сегмент — одна запись, ни повторов, ни окна, ни контроля потока.
//
// ЗАЧЕМ НЕ TUN НА ЭТОЙ СТОРОНЕ. Всё внешнее устройство пакета — заголовки IP и TCP — мы пишем
// сами, и это дешевле, чем отдать пакет ядру: сравнение проводилось замером (tests/transportcost
// в движке на C), и разница в пользу сырого сокета.
//
// ГЛАВНЫЙ ИНВАРИАНТ ФАЙЛА. Смещение в потоке (seq минус начальный номер) служит nonce для AEAD,
// поэтому он ОБЯЗАН двигаться только вперёд — даже когда отправка не удалась. Откат номера ради
// «переиспользуем» означал бы повтор nonce, то есть полную потерю защиты.
//
// Порт src/ext/xsconn.{c,h} и той части src/obfs.c, которая собирает и разбирает сегмент.
package link

import (
	"encoding/binary"

	"github.com/xyzmean/xsteer/csum"
)

// Флаги TCP и объявляемое окно.
const (
	FIN = 0x01
	SYN = 0x02
	RST = 0x04
	PSH = 0x08
	ACK = 0x10
	// Win — объявляем максимальное. Само поле — те же 65535, но в SYN согласован МАСШТАБ, поэтому
	// для conntrack по дороге это 8 МиБ, а не 64 КиБ. Без масштаба он ограничивал бы нас
	// шестьюдесятью четырьмя килобайтами в полёте — то есть 10 Мбит/с на круге 50 мс, что и было
	// измерено на живом роутере до появления опции.
	Win = 65535
	// WScale — множитель окна. Семь, потому что 65535 << 7 это восемь мегабайт: с запасом на любой
	// канал и любую задержку, и при этом ровно то значение, которое ставят настоящие стеки.
	WScale = 7
)

// Что кладём в опции SYN.
const (
	OptNone  = 0 // обычный сегмент данных или голый ACK
	OptMSS   = 1 // только MSS
	OptScale = 2 // MSS и масштаб окна
)

// Seg — разобранный сегмент.
type Seg struct {
	SAddr, DAddr [4]byte // как в пакете
	SPort, DPort uint16
	Seq, Ack     uint32
	Flags        byte
	Payload      []byte // ссылка в исходный буфер, без копии
}

// BuildSeg собирает сегмент (заголовок TCP и нагрузку) в buf и возвращает его длину.
//
// Заголовка IP здесь нет НАМЕРЕННО: сырой сокет IPPROTO_TCP без IP_HDRINCL заполняет его сам —
// адреса, идентификатор, контрольную сумму, — и делает это правильнее, чем мы. На приёме, наоборот,
// пакет приходит целиком с заголовка IP (см. ParseSeg).
func BuildSeg(buf []byte, saddr, daddr [4]byte, sport, dport uint16,
	seq, ack uint32, flags byte, opts int, payload []byte) int {

	for i := 0; i < 20; i++ {
		buf[i] = 0
	}
	binary.BigEndian.PutUint16(buf[0:2], sport)
	binary.BigEndian.PutUint16(buf[2:4], dport)
	binary.BigEndian.PutUint32(buf[4:8], seq)
	binary.BigEndian.PutUint32(buf[8:12], ack)
	buf[13] = flags
	binary.BigEndian.PutUint16(buf[14:16], Win)
	hlen := 20

	// MSS в SYN — не оптимизация, а правдоподобие: SYN вообще без опций встречается так редко, что
	// сам по себе служит признаком. Заодно честно называет размер сегмента промежуточным узлам.
	if opts >= OptMSS {
		buf[hlen] = 2
		buf[hlen+1] = 4
		binary.BigEndian.PutUint16(buf[hlen+2:hlen+4], 1500-40)
		hlen += 4
	}
	// Масштаб окна и РАЗРЕШЕНИЕ SACK — только в SYN, и порядок здесь не произвольный.
	//
	// НАБОР И ПОРЯДОК ОПЦИЙ В SYN — ЭТО ОТПЕЧАТОК СТЕКА, и его сравнили с настоящим трафиком
	// (tests/xhttp-compare.sh). Было: MSS, NOP, WS — и это не похоже ни на один современный стек:
	// разрешение SACK посылают все, и его отсутствие видно первым же пакетом соединения, бесплатно
	// для наблюдателя.
	//
	// Стало: MSS, NOP, WS, NOP, NOP, SACK_PERM — ровно то, что посылает Windows. Именно Windows, а
	// не Linux, потому что метки времени (TS) мы не посылаем и посылать не можем: они стоят 12 байт
	// в КАЖДОМ сегменте, то есть 61 байт накладных превратились бы в 73 и вся затея потеряла бы
	// смысл. Linux и macOS метки посылают, Windows по умолчанию нет — значит наш профиль обязан
	// быть виндовым целиком, а не наполовину.
	//
	// SACK мы объявляем и НЕ ПОСЫЛАЕМ: у нас нет повторных передач, значит нечего и подтверждать
	// выборочно. Объявленный и неиспользуемый SACK — это нормально и для настоящих стеков: пока
	// потерь нет, его не видно.
	if opts >= OptScale {
		buf[hlen] = 1 // NOP
		buf[hlen+1] = 3
		buf[hlen+2] = 3
		buf[hlen+3] = WScale
		hlen += 4
		buf[hlen] = 1 // NOP
		buf[hlen+1] = 1
		buf[hlen+2] = 4 // SACK permitted
		buf[hlen+3] = 2
		hlen += 4
	}
	buf[12] = byte(hlen/4) << 4
	n := hlen + copy(buf[hlen:], payload)
	binary.BigEndian.PutUint16(buf[16:18], Csum(saddr, daddr, buf[:n]))
	return n
}

// ParseSeg разбирает пакет, начинающийся с заголовка IP: именно так приходит с сырого сокета.
// ok == false означает «не наше или битое» — без разбора, чем именно: разговаривать об этом с тем,
// кто прислал пакет, незачем.
func ParseSeg(pkt []byte) (Seg, bool) {
	var s Seg
	if len(pkt) < 20 || pkt[0]>>4 != 4 {
		return s, false
	}
	ihl := int(pkt[0]&0x0F) * 4
	if ihl < 20 || len(pkt) < ihl+20 || pkt[9] != 6 {
		return s, false
	}
	total := int(binary.BigEndian.Uint16(pkt[2:4]))
	// Длина берётся из заголовка, но не больше принятого: ядро отдаёт ровно пакет, а завышенное
	// поле означало бы чтение за буфером.
	if total > len(pkt) || total < ihl+20 {
		total = len(pkt)
	}
	tcp := pkt[ihl:total]
	thl := int(tcp[12]>>4) * 4
	if thl < 20 || thl > len(tcp) {
		return s, false
	}
	// КОНТРОЛЬНАЯ СУММА НА ПРИЁМЕ НЕ СЧИТАЕТСЯ ВОВСЕ, и это не послабление, а снятая впустую
	// работа.
	//
	// Отвергать по ней нельзя, и это уже выяснено. Первая версия (и реализация на C) отбрасывала
	// сегмент с несошедшейся суммой. На пакетах от НАШИХ сторон это работает: и клиент, и хаб
	// пишут сумму сами, в пользовательском пространстве. А вот сегмент от ОБЫЧНОГО стека TCP
	// через veth или loopback несёт сумму НЕЗАВЕРШЁННОЙ — ядро оставляет её на разгрузку
	// устройству, и в буфере лежит только частичная сумма псевдозаголовка. Такой сегмент
	// отбрасывался молча, то есть хаб вообще не видел ни одного соединения от постороннего
	// клиента TLS на той же машине — а именно это и есть зондирование, ради ответа на которое
	// существует дорожка неопознанных.
	//
	// Отвергать и не нужно: целостность здесь обеспечивает AEAD, тег которого несравнимо строже
	// шестнадцати бит, а испорченный сегмент всё равно не расшифруется.
	//
	// Раньше сумма всё же считалась — «признаком в Seg, по нему считают порчу на пути». Счётчика
	// не появилось, поле не читал никто, кроме теста, а проход по нагрузке стоил 424 нс на
	// сегменте 1460 байт — БОЛЬШЕ, чем AES-128-GCM на тех же байтах (373 нс) и две трети от
	// ChaCha20-Poly1305. Платить столько за величину, которую никто не смотрит, нельзя; если
	// счётчик порчи однажды понадобится, он и появится вместе со своим вычислением, а не раньше.
	copy(s.SAddr[:], pkt[12:16])
	copy(s.DAddr[:], pkt[16:20])
	s.SPort = binary.BigEndian.Uint16(tcp[0:2])
	s.DPort = binary.BigEndian.Uint16(tcp[2:4])
	s.Seq = binary.BigEndian.Uint32(tcp[4:8])
	s.Ack = binary.BigEndian.Uint32(tcp[8:12])
	s.Flags = tcp[13]
	s.Payload = tcp[thl:]
	return s, true
}

// Csum — контрольная сумма TCP с псевдозаголовком; на готовом сегменте даёт 0.
//
// Считать её обязаны мы сами: сырой сокет её не заполняет (в отличие от заголовка IP). Забыть —
// значит получить поток, который conntrack по дороге считает недействительным, и правило вида
// «drop invalid» на любом промежуточном роутере тихо съест весь туннель. Именно это уже
// случалось при отладке: NAT не применялся, потому что запись conntrack была INVALID.
//
// САМ ЦИКЛ ЖИВЁТ В ПАКЕТЕ csum, и не ради красоты: ту же сумму считает разгрузка сегментации на
// устройстве (tun) — и над заголовками сегментов супер-кадра, и завершая неполную сумму, которую
// ядро оставило устройству. Три копии одного цикла означали бы три места, где ошибка в хвосте
// нечётной длины проявится как «большие пакеты иногда не доходят».
//
// Замер выигрыша от прохода по восемь байт вместо двух: 447 нс против 98 нс на сегменте 1460 байт,
// то есть с суммы снято больше, чем стоит AES-128-GCM на том же пакете (362 нс) и две трети
// ChaCha20-Poly1305 (688 нс). Совпадение с прежней реализацией закреплено TestCsumSameAsSlow.
func Csum(saddr, daddr [4]byte, seg []byte) uint16 { return csum.TCPv4(saddr, daddr, seg) }

// NextAck — куда сдвинуть подтверждение, приняв сегмент. Только вперёд, с учётом переполнения
// uint32: знаковая разность и есть понятие «позже», и без неё поток через заворот номера
// подтверждался бы назад — то есть выглядел бы для conntrack как повторная передача старого.
func NextAck(have, seq uint32, plen int) uint32 {
	end := seq + uint32(plen)
	if int32(end-have) > 0 {
		return end
	}
	return have
}
