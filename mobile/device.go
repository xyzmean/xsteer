// Пакет mobile — граница между клиентом на Go и приложением на платформе, где туннельного
// устройства в виде файла не существует.
//
// ЗАЧЕМ ОН ЕСТЬ. На iOS туннель живёт в расширении, и пакеты приходят не из /dev/net/tun, а из
// объекта системы NEPacketTunnelFlow: расширение просит у него очередной пакет и отдаёт ему
// исходящий. Дескриптора нет, ioctl нет, адрес, MTU и маршруты задаёт система, а не мы. Поэтому
// здесь два предмета: устройство, изображающее tun.Device поверх вызовов из Swift, и обёртка
// Tunnel с плоским набором методов, который умеет перенести gomobile (см. mobile.go).
//
// ЧТО gomobile ПЕРЕНОСИТ. Только целые, дробные, bool, string, []byte, типы этого же пакета и
// объявленные здесь интерфейсы; error — последним возвращаемым значением. Ни срезов (кроме
// []byte), ни map, ни функций, ни time.Duration, ни context.Context. Отсюда и вид API: списки
// передаются строкой через запятую, обратные вызовы — интерфейсами.
//
// ПОЧЕМУ ИМЯ ПАКЕТА НЕ СОВПАДАЕТ С КАТАЛОГОМ. gomobile приставляет к каждому вынесенному
// имени имя ПАКЕТА: у пакета mobile получились бы MobileTunnel и MobileNewTunnel, то есть в
// Swift всё звалось бы «мобильным» вместо «xsteer». Каталог при этом остаётся mobile, потому
// что он про назначение, а не про продукт.
package xsteer

import (
	"sync"
	"time"

	"github.com/xyzmean/xsteer/tun"
)

// PacketSink — куда уходят пакеты ИЗ туннеля наружу, то есть в систему. Реализуется на стороне
// платформы.
//
// ПОЧЕМУ ОТДАЁТСЯ СРАЗУ, А НЕ ПАЧКОЙ ПО Flush. Соблазн накапливать здесь и отдавать по
// tun.Device.Flush велик — переход через границу gomobile стоит около микросекунды, — но он
// ломает туннель, и вот почему: единственный работающий на iOS транспорт это режим потока
// (сырых сокетов там нет), а входящий путь режима потока Flush не зовёт ВООБЩЕ (client/stream.go,
// streamIn). Последний пакет всплеска пролежал бы в буфере до следующего пакета, то есть
// навсегда, если человек открыл одну страницу и замолчал.
//
// Поэтому склейка живёт на стороне платформы и опирается на её собственный признак конца
// всплеска, а не на наш: Swift складывает пакеты в массив и отдаёт его одним writePackets на
// следующем витке очереди. Это даёт ту же экономию и не зависит от того, позвал ли кто-то Flush.
type PacketSink interface {
	// WritePacket принимает ОДИН пакет IP без всяких приставок. Срез принадлежит вызывающему и
	// живёт только до возврата: реализация обязана скопировать.
	//
	// ipv6 говорит, какое семейство назвать системе: writePackets на iOS требует его на каждый
	// пакет, а в байтах пакета его нет — есть только версия в первом полубайте. Выводим её здесь,
	// чтобы у платформы не было своего разбора заголовка.
	WritePacket(p []byte, ipv6 bool)
	// Flush — необязательная подсказка «всплеск кончился». Ни одной гарантии на её вызов нет, и
	// правильная работа не должна от неё зависеть.
	Flush()
}

// queueLen — сколько пакетов от системы ждут своей очереди.
//
// На Linux здесь стоит txqueuelen устройства, то есть 4096 (tun.TxQueueLen), и смысл тот же:
// сколько пакетов уцелеет, пока путь данных занят предыдущим витком. Но у расширения сети на iOS
// жёсткий предел памяти около пятнадцати мегабайт на весь процесс, а 4096 пакетов по 1439 байт
// это почти шесть — то есть очередь одна съела бы треть бюджета и уронила бы расширение раньше,
// чем проявилась бы перегрузка.
//
// 512 пакетов это около 740 КБ в худшем случае. Запас всё равно велик: путь данных забирает
// пачку до восьми кадров за виток, и 512 пакетов — это шестьдесят четыре витка подряд, которых
// он не пропустит.
const queueLen = 512

// Device — tun.Device поверх вызовов платформы.
type Device struct {
	name string

	in     chan []byte
	notify chan struct{} // ёмкость 1: будильник для WaitRead, пакеты через него не ходят

	mu      sync.Mutex
	sink    PacketSink
	closed  bool
	mtu     int
	dropped uint64
	oversz  uint64
}

// NewDevice собирает устройство. name попадает в журнал и в снимок состояния.
func NewDevice(name string, sink PacketSink, mtu int) *Device {
	if name == "" {
		name = "xs0"
	}
	return &Device{
		name:   name,
		sink:   sink,
		in:     make(chan []byte, queueLen),
		notify: make(chan struct{}, 1),
		mtu:    mtu,
	}
}

// Inject кладёт пакет ОТ системы в очередь на отправку в туннель. Зовётся с платформы на каждый
// пакет из readPackets.
//
// Не блокирует никогда: переполненная очередь означает, что путь данных не успевает, и ждать
// здесь значило бы задержать чтение у системы, то есть сделать хуже. Ядро на Linux в этом месте
// поступает так же — молча теряет и считает (tx_dropped).
func (d *Device) Inject(p []byte) {
	if len(p) == 0 {
		return
	}
	// Копия обязательна по двум причинам. Первая: срез принадлежит границе gomobile и живёт не
	// дольше возврата. Вторая: путь данных правит пакет НА МЕСТЕ (подрезка MSS, уменьшение TTL),
	// то есть буфер обязан быть нашим и изменяемым.
	b := make([]byte, len(p))
	copy(b, p)
	select {
	case d.in <- b:
	default:
		d.mu.Lock()
		d.dropped++
		d.mu.Unlock()
		return
	}
	select {
	case d.notify <- struct{}{}:
	default:
	}
}

// Dropped — сколько пакетов от системы не влезло в очередь.
func (d *Device) Dropped() uint64 {
	d.mu.Lock()
	defer d.mu.Unlock()
	return d.dropped
}

// Oversize — сколько пакетов пришлось выбросить, потому что они не влезли в буфер чтения.
// Отдельно от Dropped: это не перегрузка, а расхождение MTU, и лечение у него другое.
func (d *Device) Oversize() uint64 {
	d.mu.Lock()
	defer d.mu.Unlock()
	return d.oversz
}

// Read отдаёт один пакет из очереди. Неблокирующее, как требует tun.Device: когда пусто —
// tun.ErrAgain, и путь данных на этом закрывает пачку и отправляет набранное.
//
// ПАКЕТ, НЕ ВЛЕЗШИЙ В БУФЕР, ВЫБРАСЫВАЕТСЯ ЦЕЛИКОМ. Отдать начало нельзя: путь данных читает
// окнами ровно wire.MTUDefault и признака усечения не имеет, так что в туннель уехал бы обрубок
// с настоящей длиной в заголовке IP, а получатель молча выбросил бы его как испорченный. Класс
// отказа «мелкое ходит, крупное пропадает» — самый дорогой в отладке, поэтому здесь счётчик.
// Возникать этого не должно вовсе: MTU в настройках расширения обязан быть не больше того, что
// туннель готов нести.
func (d *Device) Read(p []byte) (int, error) {
	for {
		select {
		case b := <-d.in:
			if len(b) > len(p) {
				d.mu.Lock()
				d.oversz++
				d.mu.Unlock()
				continue
			}
			return copy(p, b), nil
		default:
			return 0, tun.ErrAgain
		}
	}
}

// WaitRead ждёт появления пакетов не дольше timeout; false — истекло время.
//
// ОШИБКУ ЗДЕСЬ ВОЗВРАЩАТЬ ПОЧТИ НЕЛЬЗЯ: вызывающий считает её смертельной и уходит из соединения
// (client.go, stream.go, hub/worker.go — все три). Поэтому закрытое устройство отвечает «времени
// нет», а не отказом: уходить пути данных положено по отмене контекста, и он уйдёт, максимум
// через один такой таймаут.
//
// Пакет при этом НЕ забирается из очереди — забирает его Read. Будильник отдельным каналом
// именно поэтому: подсмотреть и положить обратно значило бы уметь потерять пакет на полной
// очереди и переставить порядок, если читателей когда-нибудь станет двое.
func (d *Device) WaitRead(timeout time.Duration) (bool, error) {
	if len(d.in) > 0 {
		return true, nil
	}
	d.mu.Lock()
	closed := d.closed
	d.mu.Unlock()
	if closed {
		return false, nil
	}
	t := time.NewTimer(timeout)
	defer t.Stop()
	select {
	case <-d.notify:
		return len(d.in) > 0, nil
	case <-t.C:
		return len(d.in) > 0, nil
	}
}

// Write отдаёт пакет системе — сразу, без накопления. Почему сразу, объяснено у PacketSink.
//
// Предела размера здесь НЕТ, и это не упущение: пир с большим MTU законно присылает пакет
// крупнее нашего MTU, и предел открытого текста записи — wire.MaxPlain, то есть 8176 байт.
func (d *Device) Write(p []byte) (int, error) {
	if len(p) < 1 {
		return 0, nil
	}
	ver := p[0] >> 4
	if ver != 4 && ver != 6 {
		// Не IP — угадывать семейство нельзя, а назвать неверное значит отдать системе мусор
		// под чужой вывеской. Считаем отброшенным.
		d.mu.Lock()
		d.dropped++
		d.mu.Unlock()
		return 0, nil
	}
	d.mu.Lock()
	closed, sink := d.closed, d.sink
	d.mu.Unlock()
	if closed || sink == nil {
		return 0, tun.ErrNoDevice
	}
	sink.WritePacket(p, ver == 6)
	return len(p), nil
}

// Flush передаёт подсказку платформе. Работать правильно без неё обязаны обе стороны.
func (d *Device) Flush() error {
	d.mu.Lock()
	closed, sink := d.closed, d.sink
	d.mu.Unlock()
	if closed || sink == nil {
		return nil
	}
	sink.Flush()
	return nil
}

func (d *Device) Name() string { return d.name }

// SetMTU молча соглашается.
//
// Это НЕ небрежность. Согласование пути узнаёт настоящий предел уже после подъёма и обязано его
// применить (applyMTU в клиенте); на iOS размер туннеля задан системой при подъёме и на ходу не
// меняется. Отказ отсюда означал бы, что клиент не обновит свой mtuNow и навсегда останется на
// стартовом значении, — то есть сделал бы хуже, чем согласие. Поэтому MTU в настройках
// расширения и поле MTU в конфигурации обязаны совпадать.
func (d *Device) SetMTU(mtu int) error {
	d.mu.Lock()
	d.mtu = mtu
	d.mu.Unlock()
	return nil
}

// MTU — то, что стоит на устройстве.
func (d *Device) MTU() int {
	d.mu.Lock()
	defer d.mu.Unlock()
	return d.mtu
}

// Close снимает ссылку на объект платформы. Сам объект принадлежит расширению, а не нам.
//
// Очередь НЕ закрывается: Inject мог войти до выставления признака, и отправка в закрытый канал
// была бы паникой. Будильник тоже остаётся открытым — WaitRead уходит по своему таймауту.
func (d *Device) Close() error {
	d.mu.Lock()
	d.closed = true
	d.sink = nil
	d.mu.Unlock()
	select {
	case d.notify <- struct{}{}:
	default:
	}
	return nil
}

// компиляция падёт здесь, если интерфейс разойдётся с реализацией
var _ tun.Device = (*Device)(nil)
