package wire

// ---- согласование MTU ------------------------------------------------------
//
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Арифметика «MTU канала минус накладные» даёт лишь ВЕРХНЮЮ оценку.
// Настоящий путь бывает уже, и хуже всего то, что он обычно не сообщает об этом никак:
// слишком большой пакет молча исчезает, ICMP «нужна фрагментация» не приходит. Тогда
// внутренний TCP теряет все полноразмерные сегменты, вдвое увеличивает таймаут за таймаутом,
// и туннель отдаёт единицы мегабит при свободном канале.
//
// Измерено на живом роутере: канал PPPoE 1492 (то есть предел 1431 по арифметике), а путь до
// сервера нёс только 1448 байт — предел 1387. Разница в 44 байта стоила бы всей скорости, и
// найти её удалось только перебором вручную.
//
// КАК СОГЛАСУЕМ. Две ступени, и первая без второй недостаточна:
//
//  1. Каждая сторона сообщает в рукопожатии СВОЙ предел — MTU своего канала минус накладные.
//     Обе берут минимум: это «максимальное для обоих устройств».
//  2. Дальше путь ПРОВЕРЯЕТСЯ пробами: кадр ровно нужного размера уходит на ту сторону, та
//     отвечает эхом с дошедшим размером. Первый размер, который вернулся, и есть рабочий.
//
// Схема повторяет veil (engine/pmtu.go) — там это уже проходили, и оттуда же взяты два
// решения, до которых иначе доходят через поломку: НАЧИНАТЬ СНИЗУ (пока проба не подтвердила
// размер, несём безопасный минимум, иначе до конца проверки трафик идёт в ту самую чёрную
// дыру, которую мы и ищем) и ПОВТОРЯТЬ ПРОБУ (путь меняется под живой сессией — переход между
// точками WiFi, смена маршрута у провайдера).
const (
	// MTUFloor — безопасный низ: столько несёт любой реальный путь. 1219 = 1280 (наименьший
	// MTU, который обязан нести любой канал с IPv6, и практически любой без него) минус наши
	// накладные. Округлено вниз до 1200 — запас дешевле, чем разбирательство.
	MTUFloor = 1200
	// MTUGrain — точность, до которой доводим поиск. Восемь байт: дальше уточнять нечего —
	// выигрыш меньше одной тысячной пакета, а каждая проба стоит круга задержки.
	MTUGrain = 8
	// MTUTriesMax — предел числа проб. Отрезок 1439…1200 делением пополам сходится за пять
	// шагов; восемь — с запасом и заодно защита от зацикливания при противоречивых границах.
	MTUTriesMax = 8
	// ProbeWaitMS и ProbeTries: у пробы нет повторной передачи, поэтому одна потеря не должна
	// означать «этот размер не проходит».
	ProbeWaitMS = 300
	ProbeTries  = 2
	// ProbeEveryMS — как часто перепроверять путь под живой сессией. Две минуты — как у veil:
	// чаще незачем, реже означало бы, что суженный путь глотает кадры до конца сессии.
	ProbeEveryMS = 120 * 1000

	// ProbeMin — самая маленькая проба, какую умеет собрать ProbeBuild: тип, два байта размера
	// и один байт набивки.
	//
	// Нужна не для измерения пути, а как проба ЖИВОСТИ: хаб отвечает на неё эхом, и по эху видно,
	// что канал несёт трафик обратно. Размер взят наименьший намеренно — такая проба проходит
	// всегда, поэтому её молчание означает мёртвый канал, а не слишком большой кадр.
	ProbeMin = 4
)

// ConnsMax — сколько поддельных соединений пир открывает к хабу. По одному на воркер: одно
// соединение обслуживается одной горутиной целиком, и тогда счётчик nonce остаётся её личным —
// без атомиков и замков в самом опасном месте протокола (повтор nonce = полная потеря AEAD).
//
// Живёт здесь, а не в пакете noise, потому что число нужно трём сторонам: рукопожатию (номер
// соединения едет в подписанной части), выбору порта (младшие биты порта = номер) и хабу.
// Предел — три бита в поле flags рукопожатия.
const ConnsMax = 4

// MTUNext — следующий размер для пробы; 0, когда проверять больше нечего.
//
// lo — размер, который ЗАВЕДОМО проходит (в начале это безопасный низ), hi — размер, который
// заведомо НЕ проходит, или 0, если такого ещё нет. Пока hi неизвестен, проверяется потолок: в
// обычном случае он сразу и подтверждается, то есть полная скорость достаётся одной пробой.
// Если потолок не прошёл — отрезок делится пополам, и поиск сходится к настоящему пределу с
// точностью MTUGrain.
//
// Почему делением, а не лестницей с шагом: лестница с шагом 40 на живом пути (предел 1387 при
// потолке 1431) остановилась бы на 1351 и потеряла бы 36 байт из каждого пакета. Деление даёт
// настоящий максимум за то же число проб.
func MTUNext(lo, hi, ceiling int) int {
	if ceiling > MTUDefault {
		ceiling = MTUDefault
	}
	if lo < MTUFloor {
		lo = MTUFloor
	}
	if ceiling <= lo {
		return 0 // потолок не выше низа — проверять нечего
	}
	if hi <= 0 {
		return ceiling // ещё не знаем верхней границы: пробуем потолок
	}
	if hi > ceiling {
		hi = ceiling
	}
	if hi-lo <= MTUGrain {
		return 0 // сошлось
	}
	return lo + (hi-lo)/2
}

// ProbeBuild собирает кадр пробы размером ровно size байт открытого текста.
func ProbeBuild(pt []byte, size int) (int, bool) {
	if size < 4 || size > len(pt) || size > MTUDefault {
		return 0, false
	}
	pt[0] = CtlProbe
	pt[1] = byte(size >> 8)
	pt[2] = byte(size)
	// Набивка нулями, а не случайными байтами: проба всё равно уходит под AEAD, снаружи её не
	// отличить от данных, а нули не требуют источника случайности на каждый кадр.
	for i := 3; i < size; i++ {
		pt[i] = 0
	}
	return size, true
}

// ProbeSize — размер пробы, или -1, если это не проба.
func ProbeSize(pt []byte) int {
	if len(pt) < 3 || pt[0] != CtlProbe {
		return -1
	}
	size := int(pt[1])<<8 | int(pt[2])
	// Заявленный размер обязан совпасть с фактическим: иначе это не проба пути, а кадр, который
	// прикидывается ею — и эхо на него сообщило бы неправду о том, что путь несёт.
	if size != len(pt) {
		return -1
	}
	return size
}

// PackBuild — эхо на пробу: тип и дошедший размер, три байта.
func PackBuild(pt []byte, size int) int {
	if len(pt) < 3 {
		return 0
	}
	pt[0] = CtlPack
	pt[1] = byte(size >> 8)
	pt[2] = byte(size)
	return 3
}

// PackSize — размер из эха, или -1.
func PackSize(pt []byte) int {
	if len(pt) < 3 || pt[0] != CtlPack {
		return -1
	}
	return int(pt[1])<<8 | int(pt[2])
}

// MTUBuild — итог согласования: «дальше несём столько».
func MTUBuild(pt []byte, mtu int) int {
	if len(pt) < 3 {
		return 0
	}
	pt[0] = CtlMTU
	pt[1] = byte(mtu >> 8)
	pt[2] = byte(mtu)
	return 3
}

// MTUValue — значение из кадра итога, или -1.
func MTUValue(pt []byte) int {
	if len(pt) < 3 || pt[0] != CtlMTU {
		return -1
	}
	return int(pt[1])<<8 | int(pt[2])
}
