package wire

import (
	"errors"
	"io"
)

// ---- записи по НАСТОЯЩЕМУ потоку TCP ---------------------------------------
//
// ЗАЧЕМ ЭТО ЕСТЬ. На Windows поддельный TCP невозможен без драйвера: отправка TCP через сырой
// сокет запрещена системой с XP SP2, а погасить RST собственного ядра нечем — брандмауэр не умеет
// матчить флаги, а WFP умеет только из драйвера. Значит либо перехватчик вроде WinDivert (свой
// драйвер, трение с антивирусами, лицензия), либо обычный сокет — и тогда наши записи едут по
// настоящему потоку TCP.
//
// ЧТО ЭТО МЕНЯЕТ НА ПРОВОДЕ, И НЕОЖИДАННО В ЛУЧШУЮ СТОРОНУ. Всё, что мы кропотливо изображали
// руками (блуждающее окно, PSH раз в шесть сегментов, разрешение SACK, голые подтверждения,
// keepalive с разбросом), настоящий стек делает сам и точно. Исчезает и сильнейший остаточный
// признак: в потоке запись живёт своей длиной, может быть 16 КБ и свободно пересекать границы
// сегментов — ровно как у настоящего TLS.
//
// ЧТО ЭТО МЕНЯЕТ ВНУТРИ, И ЭТО ЦЕНА. Внешний транспорт становится надёжным, то есть внутренний TCP
// пользователя едет поверх TCP. От этого протокол и уходил: потеря наружу превращается в задержку,
// а не в потерю, и внутренний TCP успевает пере-отправить то, что уже в пути. Насколько это дорого
// — вопрос замера, а не спора (tests/loss.sh).
//
// ФОРМАТ НЕ МЕНЯЕТСЯ НИ НА БАЙТ. Записи те же, nonce тот же: смещение первого байта записи в
// потоке. В поддельном TCP оно бралось из номера последовательности, здесь — из собственного
// счётчика; счёт с единицы в обоих случаях, потому что нулевой nonce занят подтверждением
// рукопожатия.

// ErrStreamRecord — поток принёс не запись: либо не тот собеседник, либо порча. Соединение после
// этого продолжать нельзя — в потоке нет способа «пропустить один кадр».
var ErrStreamRecord = errors.New("wire: в потоке не запись xsteer")

// Stream — записи поверх байтового потока. Один экземпляр на соединение; чтение и запись могут
// идти из разных горутин (у них разные счётчики и разные буферы), но каждое направление
// принадлежит одной.
type Stream struct {
	rw io.ReadWriter

	// Смещения ШЕСТИДЕСЯТИЧЕТЫРЁХБИТНЫЕ, и это условие стойкости, а не запас на будущее.
	//
	// Смещение — это nonce. Тридцати двух бит хватает на четыре гигабайта, после чего счётчик
	// заворачивается и тот же nonce уходит с тем же ключом; для AES-GCM и ChaCha20-Poly1305 повтор
	// nonce означает не ослабление, а полную потерю стойкости — вскрывается и подделка, и
	// содержимое. Четыре гигабайта в одном соединении — это один фильм, то есть достижимо.
	//
	// Раньше от заворота спасал ретайр по объёму: соединение закрывалось на гигабайте, и туннель
	// на миг падал. Так делать не нужно — шире счётчик и всё. На проводе НИЧЕГО не меняется:
	// смещение не передаётся, обе стороны считают байты сами, а Seal и Open принимают nonce как
	// uint64 с самого начала. Для первых четырёх гигабайт значения те же, что и были, — совместимость
	// с уже работающими сборками сохраняется; дальше счётчик просто продолжает расти.
	//
	// Так же поступает veil: у него порядковый номер восьмибайтный (record/v1: SeqSize = 8), и
	// вопроса заворота там не возникает вовсе. Ротация ключей у него отдельно, эпохами, и её
	// назначение — прямая секретность, а не спасение от повтора nonce.
	txOff uint64 // смещение следующего байта, который мы отправим
	rxOff uint64 // смещение следующего байта, который мы прочитаем

	rbuf []byte // буфер под одну запись целиком
}

// NewStream заводит поток. Счётчики начинаются с единицы: нулевое смещение занято подтверждением
// рукопожатия, и это тот же инвариант, что в поддельном TCP, где ноль забирал SYN.
func NewStream(rw io.ReadWriter) *Stream {
	return &Stream{rw: rw, txOff: 1, rxOff: 1, rbuf: make([]byte, RecHdr+MaxRecord+Tag)}
}

// WriteRaw отправляет байты как есть и учитывает их в смещении. Нужно рукопожатию: его записи
// идут по тому же потоку и так же двигают счётчик — иначе смещения сторон разъедутся на длину
// рукопожатия, и первый же пакет данных не расшифруется.
func (s *Stream) WriteRaw(b []byte) error {
	n, err := s.rw.Write(b)
	s.txOff += uint64(n)
	return err
}

// TxNext — смещение, с которым уйдёт следующая запись: им её и надо шифровать.
func (s *Stream) TxNext() uint64 { return s.txOff }

// ReadRaw читает столько, сколько попросили, и учитывает это в смещении. Нужно рукопожатию,
// которому байты приходят до того, как известны границы записей.
func (s *Stream) ReadRaw(b []byte) (int, error) {
	n, err := s.rw.Read(b)
	s.rxOff += uint64(n)
	return n, err
}

// ReadFull читает ровно len(b) байт и учитывает их в смещении. Нужно рукопожатию: его ответ
// приходит несколькими записями разных типов, и собрать их надо ЦЕЛИКОМ до разбора — разбор
// вбирает прочитанное в транскрипт, и повторный вызов на неполном ответе посчитал бы его дважды.
func (s *Stream) ReadFull(b []byte) error {
	n, err := io.ReadFull(s.rw, b)
	s.rxOff += uint64(n)
	return err
}

// ReadRecord читает ОДНУ запись целиком.
//
// Возвращает шифротекст с тегом, заголовок (он же AAD) и смещение для nonce. Буфер переиспользуется:
// следующий вызов затрёт отданное.
func (s *Stream) ReadRecord() (body, hdr []byte, rel uint64, err error) {
	rel = s.rxOff
	if _, err = io.ReadFull(s.rw, s.rbuf[:RecHdr]); err != nil {
		return nil, nil, 0, err
	}
	s.rxOff += RecHdr
	if s.rbuf[0] != recType || s.rbuf[1] != recV0 || s.rbuf[2] != recV1 {
		return nil, nil, 0, ErrStreamRecord
	}
	n := int(s.rbuf[3])<<8 | int(s.rbuf[4])
	if n < Tag || n > MaxRecord {
		return nil, nil, 0, ErrStreamRecord
	}
	if _, err = io.ReadFull(s.rw, s.rbuf[RecHdr:RecHdr+n]); err != nil {
		return nil, nil, 0, err
	}
	s.rxOff += uint64(n)
	return s.rbuf[RecHdr : RecHdr+n], s.rbuf[:RecHdr], rel, nil
}

// WriteRecord отправляет готовую запись, лежащую по row[HdrRoom-RecHdr:], и шифрует её тем
// смещением, с которым она уходит.
//
// seal вызывается ДО записи в поток и получает смещение — то же неделимое правило, что в поддельном
// TCP: выдать смещение, зашифровать им и отправить нужно как одно действие, иначе два пакета
// уедут под одним nonce.
func (s *Stream) WriteRecord(row []byte, plen int, seal func(rel uint64) error) error {
	if seal != nil {
		if err := seal(s.txOff); err != nil {
			return err
		}
	}
	rec := row[HdrRoom-RecHdr : HdrRoom-RecHdr+plen]
	n, err := s.rw.Write(rec)
	s.txOff += uint64(n)
	return err
}
