// Пакет wire — арифметика провода xsteer: запись, nonce, окно приёма, пределы соединения.
//
// Это порт src/ext/xswire.{c,h} из движка steer. Здесь нет ни сокетов, ни времени из
// системы, ни криптографии — ровно та же граница, что проведена в C, и по той же причине:
// сборка кадра, вывод nonce и защита от повтора проверяются тестом без сети и без прав
// root, а циклы, которые всё это вызывают, живут в пакетах link и client.
//
// ЧТО ЗА ПРОТОКОЛ. xsteer несёт IP-пакеты внутри потока, который для DPI выглядит как TLS
// на :443 поверх обычного TCP: рукопожатие имеет форму ClientHello/ServerHello (пакеты
// chello и noise), а каждый пакет данных — форму записи application_data. Транспорт при
// этом ПОДДЕЛЬНЫЙ: заголовок TCP настоящий, а семантика датаграммная — один пакет, один
// сегмент, одна запись, ни повторов, ни окна, ни контроля потока. Так облик достаётся без
// TCP-поверх-TCP и без второго слоя шифра.
//
// ОТКУДА «НАКЛАДНЫЕ РАСХОДЫ К НУЛЮ». Из кадра выкинуто то, что WireGuard несёт зря: индекс
// получателя (его заменяет четвёрка адрес-порт поддельного TCP) и счётчик (его заменяет
// номер последовательности того же поддельного TCP). Эти 12 байт и оплачивают пятибайтовый
// заголовок записи:
//
//	WireGuard поверх UDP               20 IP + 8 UDP + 32 WG  = 60 байт
//	WireGuard поверх поддельного TCP   20 IP + 20 TCP + 32 WG = 72 байта
//	xsteer                             20 + 20 + 5 + 16 тега  = 61 байт
//
// СОВМЕСТИМОСТЬ С РЕАЛИЗАЦИЕЙ НА C — ТРЕБОВАНИЕ, А НЕ ПОЖЕЛАНИЕ. Десктопный клиент
// подключается к тому же хабу, что и роутер, поэтому каждое число и каждая раскладка здесь
// обязаны совпадать с src/ext/xswire.h побайтово. Расхождение проявится не ошибкой сборки,
// а туннелем, который поднимается и не несёт трафик, — поэтому совпадение закреплено
// векторами в testdata и тестом interop.
package wire

import "errors"

// ---- размеры ---------------------------------------------------------------
//
// Числа, выведенные одно из другого, стоят рядом и спорят при КОМПИЛЯЦИИ (см. проверки в
// конце файла) — то же правило, что записано у XS_STATIC_ASSERT в C: иначе одно поправят, а
// второе останется, и расхождение проявится как «маленькие пакеты ходят, большие пропадают»,
// худший класс отказов в диагностике.
const (
	RecHdr  = 5  // 17 03 03 LL LL
	Tag     = 16 // тег AEAD, у обоих шифров одинаковый
	IPHdr   = 20
	TCPHdr  = 20 // без опций: в сегментах данных их нет
	HdrRoom = IPHdr + TCPHdr + RecHdr
	// Overhead — то, что xsteer добавляет к внутреннему пакету. Главное число протокола.
	Overhead = HdrRoom + Tag
	// LinkMax — обычный Ethernet; MTU канала может быть меньше, и тогда MTU туннеля считает MTU().
	LinkMax = 1500
	// MTUDefault — потолок MTU туннеля при канале 1500.
	MTUDefault = LinkMax - Overhead
	// Row — строка буфера: ровно пакет на проводе при канале 1500.
	Row = LinkMax
	// RowRX — приёмная строка для СЫРОГО СОКЕТА, и она больше Row не про запас.
	//
	// В сырой сокет пакеты приходят ПОСЛЕ сборки GRO: ядро склеивает идущие подряд сегменты одного
	// потока в один, и предъявляет нагрузку в разы длиннее канального предела (замерено на живом
	// сервере: 2904 и 4356 байт при MSS 1452). Чтение в строку на 1500 такой пакет ОБРЕЗАЕТ —
	// остаток теряется молча, вместе с записями, которые в нём лежали. Именно это, а не потери на
	// канале, стоило туннелю двухсот сорока раз по скорости (0,45 против 110 Мбит/с).
	//
	// Предел GRO — 65536 байт (net.core.gro_max_size), поэтому строка такая. Она одна на воркер и
	// живёт всё время работы, то есть цена — четверть мегабайта на четыре воркера.
	RowRX = 65536
	// MaxRecord — самая большая запись, которую мы собираем: столько же, сколько пишет в одну
	// запись настоящий сервер xhttp (измерено: 8218 байт нагрузки). Больше не нужно: выигрыш в
	// накладных дальше почти нулевой, а гибнет такая запись целиком при потере любого сегмента.
	MaxRecord = 8192
	// MaxPlain — самый большой ОТКРЫТЫЙ текст, влезающий в запись. Тело записи — это открытый
	// текст ВМЕСТЕ с тегом, а предел приёмника (Reasm.Feed, Stream.ReadRecord и xs_reasm_feed в
	// реализации на C) стоит на теле. Значит ограничивать сборку самим MaxRecord нельзя: пачка,
	// набитая вплотную к нему, уезжает записью MaxRecord+Tag, и собственный приёмник её
	// отвергает. В поддельном TCP это молчаливая потеря пакета, а в потоке — ОБРЫВ СОЕДИНЕНИЯ:
	// границы следующей записи известны только из длины, которой мы уже не верим. Вплотную к
	// пределу пачка набивается лишь под нагрузкой, поэтому наружу это выглядело как «на скорости
	// туннель отваливается» — и не воспроизводилось на спокойном канале.
	MaxPlain = MaxRecord - Tag
	// BatchFramesMax — сколько кадров кладём в одну запись. Восемь: при полноразмерных пакетах в
	// MaxRecord всё равно влезает пять, а при мелких (внутренние подтверждения) восемь дают
	// заметное сокращение числа пакетов на проводе.
	BatchFramesMax = 8
	// RecMin — самая маленькая осмысленная запись: заголовок плюс тег, открытый текст пустой.
	// Это keepalive; кадр короче — не наш.
	RecMin = RecHdr + Tag
)

// Ошибки разбора. Разные НАРОЧНО: «не наш кадр» и «битая длина» требуют разных решений на
// стороне вызывающего — первое отбрасывается счётчиком, второе означает, что соединение
// пора поднимать заново.
var (
	ErrNotOurs = errors.New("wire: не запись xsteer")
	ErrLength  = errors.New("wire: длина не сходится")
)

// MTU — MTU туннеля от MTU канала. Отдельной функцией, а не выражением на месте, потому что
// это же число печатает диагностика и проверяет клиент при подъёме устройства.
func MTU(link int) int {
	m := link - Overhead
	if m < 576 {
		return 576 // ниже этого IP-стек становится непредсказуем
	}
	return m
}

// ---- тип кадра -------------------------------------------------------------
//
// Внутри записи НЕТ ни поля типа, ни поля длины. Длину даёт заголовок записи (один пакет =
// один сегмент = одна запись), а тип — первый байт открытого текста: у IP-пакета там версия.
// Байта inner content type, который есть в настоящем TLS 1.3, у нас нет намеренно: он лежит
// под AEAD, то есть невидим DPI, а стоил бы байт на каждом пакете.

// Kind — что лежит в расшифрованном кадре.
type Kind int

const (
	KindBad Kind = iota // отбросить со счётчиком; соединение НЕ рвать
	KindIPv4
	KindIPv6
	KindKeepalive // пустой открытый текст: держим отображение NAT живым
	KindCtl       // служебный кадр, первый байт — Ctl*
)

// Служебные кадры. Значения совпадают с XS_CTL_* в C.
const (
	CtlRetire = 0x01 // «это соединение уходит, продолжай на новом»
	CtlMTU    = 0x02 // итог согласования: «дальше несём столько»
	CtlProbe  = 0x03 // проба пути: кадр ровно такого размера, какой проверяем
	CtlPack   = 0x04 // эхо на пробу: размер, который ДОШЁЛ
)

// FrameKind — что за кадр расшифровался.
func FrameKind(pt []byte) Kind {
	if len(pt) == 0 {
		return KindKeepalive
	}
	switch {
	case pt[0]&0xF0 == 0x40:
		if len(pt) >= IPHdr {
			return KindIPv4
		}
		return KindBad
	case pt[0]&0xF0 == 0x60:
		if len(pt) >= 40 {
			return KindIPv6
		}
		return KindBad
	case pt[0] <= 0x0F:
		return KindCtl
	}
	return KindBad
}

// ---- запись ----------------------------------------------------------------

// Версия в заголовке записи — 0x0303, то есть «TLS 1.2», и это не ошибка. TLS 1.3 сам ставит
// в записях именно её ради посредников, которые не понимают версию 1.3 и рвут такие потоки;
// настоящая версия согласуется расширением внутри рукопожатия. Поставить здесь 0x0304 значило
// бы отличаться от всякого настоящего TLS 1.3 первым же байтом каждой записи.
const (
	recType = 0x17
	recV0   = 0x03
	recV1   = 0x03
)

// RecBuild записывает заголовок записи в hdr (ровно RecHdr байт) для нагрузки длиной bodyN
// (шифротекст вместе с тегом).
func RecBuild(hdr []byte, bodyN int) error {
	if len(hdr) < RecHdr {
		return ErrLength
	}
	// Предел ФОРМАТА, а не предел ПОЛЯ: записей длиннее MaxRecord мы не отправляем никогда, и
	// приёмники (Reasm.Feed, Stream.ReadRecord, xs_reasm_feed) проверяют ровно этим числом.
	// Пока здесь стояло 0xFFFF, переполнение пачки на 16 байт тега доезжало до провода — и
	// обрывало соединение у получателя вместо того, чтобы отказать у отправителя.
	if bodyN < Tag || bodyN > MaxRecord {
		return ErrLength
	}
	hdr[0], hdr[1], hdr[2] = recType, recV0, recV1
	hdr[3] = byte(bodyN >> 8)
	hdr[4] = byte(bodyN)
	return nil
}

// RecParse разбирает нагрузку сегмента как ОДНУ запись и возвращает срез шифротекста с тегом,
// подрезанный на месте — без копии.
//
// Проверка «длина в записи равна остатку сегмента» здесь не педантизм, а предфильтр: на
// публичный порт хаба сыплется сканерный шум, и три сравнения отбивают его до AEAD, то есть
// до всей дорогой работы.
func RecParse(seg []byte) ([]byte, error) {
	if len(seg) < RecMin {
		return nil, ErrNotOurs
	}
	if seg[0] != recType || seg[1] != recV0 || seg[2] != recV1 {
		return nil, ErrNotOurs
	}
	n := int(seg[3])<<8 | int(seg[4])
	// РОВНО остаток сегмента, а не «не больше». Одна датаграмма — одна запись, и запись,
	// заявившая меньше, чем лежит в сегменте, означала бы поток: там, где потока нет, это либо
	// чужой пакет, либо попытка спрятать за концом записи что-то ещё.
	if n != len(seg)-RecHdr || n < Tag {
		return nil, ErrLength
	}
	return seg[RecHdr:], nil
}

// ---- nonce -----------------------------------------------------------------

// Rel — смещение внутри потока, из которого выводится nonce.
//
// ОТНОСИТЕЛЬНОЕ, а не абсолютный номер последовательности, и это не косметика. Часть
// межсетевых экранов и CPE рандомизирует начальный номер и прибавляет постоянное Δ ко всем
// номерам потока. При nonce от абсолютного номера это означает, что КАЖДЫЙ пакет
// расшифровывается неверно — тотальный молчаливый отказ, самый злой класс отказов. Получатель
// берёт начальный номер пира из того SYN, который фактически увидел (уже со сдвигом), и Δ
// сокращается тождественно.
func Rel(seq, isn uint32) uint32 { return seq - isn }

// Nonce = iv XOR rel, ровно как в TLS 1.3 (RFC 8446 §5.3): номер записи выравнивается вправо
// и накладывается на статический iv. Совпадение с aead_nonce из tls13.c обязательно — оттуда
// берётся и сам AEAD.
func Nonce(iv [12]byte, rel uint32) [12]byte {
	out := iv
	for i := 0; i < 4; i++ {
		out[11-i] ^= byte(rel >> (8 * i))
	}
	return out
}

// ---- пределы соединения ----------------------------------------------------
//
// Переполнение uint32 в rel не обрабатывается, а ИСКЛЮЧАЕТСЯ: соединение выводится из работы
// задолго до заворота. Это лучше восстановления старших разрядов по SRTP-подобному правилу —
// то правило исполняется раз в 4 ГиБ, а значит не проверено ничем, кроме теста, и ошибка в
// нём даёт разъезд ключей без единой строки в журнале.
//
// Один и тот же ретайр закрывает три задачи, поэтому отдельных механизмов нет: прямую
// секретность (новое соединение — новые эфемерные ключи), пределы AEAD (0,75 млн записей на
// гигабайт против 23 млн, разрешённых RFC 8446 §5.5 для AES-GCM) и отсутствие ратчета на
// проводе (нет кадра обновления ключей, нет бита фазы ключа, нет кода, который это разбирает).
const (
	RelRetire   = uint32(1) << 30    // 1 ГиБ в одну сторону
	AgeRetireMS = int64(1200 * 1000) // или 20 минут — что раньше
	// Успешник поднимается заранее, на девяти десятых порога: три X25519 на слабом процессоре
	// это десятки миллисекунд, и делать их в потоке пересылки значит подарить пакетам такую же
	// паузу.
	renewNum = 9
	renewDen = 10
)

// RenewDue — пора поднимать сменное соединение.
func RenewDue(rel uint32, ageMS int64) bool {
	return rel >= uint32(uint64(RelRetire)*renewNum/renewDen) ||
		ageMS >= AgeRetireMS*renewNum/renewDen
}

// RetireDue — соединение ОБЯЗАНО замолчать, как только это вернуло true, даже если сменное не
// поднялось. Иначе одна сетевая неудача превращается в повтор nonce, то есть в полную потерю
// защиты AEAD.
func RetireDue(rel uint32, ageMS int64) bool {
	return rel >= RelRetire || ageMS >= AgeRetireMS
}

// ---- защита от повтора -----------------------------------------------------
//
// Обязательна, и это не «на всякий случай»: повторно присланный пакет расшифруется — тот же
// nonce, тот же ключ, — поэтому окно здесь единственная защита от воспроизведения.
//
// Помним последние WinRing принятых смещений. Кольцо И ЕСТЬ терпимость к переупорядочиванию:
// при полноразмерных записях 256 номеров это около 368 КиБ потока, заметно больше любого
// переупорядочивания, которое встречается на практике. Проверка при этом ТОЧНАЯ — дырки, в
// которую проскочил бы повтор, не остаётся, в отличие от битовой карты с грубой
// гранулярностью.
const WinRing = 256

// Window — окно приёма одного направления одного соединения.
type Window struct {
	max  uint32 // самое дальнее принятое смещение
	ring [WinRing]uint32
	n    int // сколько заполнено, пока кольцо не обернулось
	head int // куда писать следующее
}

// Reset возвращает окно в исходное состояние: нужно при подъёме соединения заново.
func (w *Window) Reset() { *w = Window{} }

// Check — можно ли пробовать AEAD на этом смещении.
//
// РАЗДЕЛЕНИЕ CHECK И COMMIT ОБЯЗАТЕЛЬНО. Обновить окно до проверки тега значит дать
// подделанному пакету с далёким смещением выбить из окна весь честный поток: max уехал бы
// вперёд, и настоящие пакеты стали бы «слишком старыми». Поэтому Commit зовётся только после
// сошедшегося тега, и в коде это написано там же, где вызывается.
func (w *Window) Check(rel uint32) bool {
	// Нулевое смещение не бывает данными: начальный номер занят самим SYN, поэтому первая
	// запись начинается с единицы. Заодно это позволяет нулём обозначать «ещё ничего не
	// принято» и не держать отдельный признак.
	if rel == 0 {
		return false
	}
	// Знаковая разность — то же понятие «позже», что в арифметике подтверждений. Одно
	// сравнение закрывает подавляющую часть пакетов: они идут по порядку.
	if int32(rel-w.max) > 0 {
		return true
	}
	if w.n == WinRing {
		// Кольцо обернулось: старейшее помнимое лежит там, куда сейчас писать. Всё, что старше
		// него, отвергаем — не потому, что это точно повтор, а потому, что проверить нечем, а
		// пропустить непроверенное здесь нельзя.
		if int32(rel-w.ring[w.head]) < 0 {
			return false
		}
	}
	for i := 0; i < w.n; i++ {
		if w.ring[i] == rel {
			return false
		}
	}
	return true
}

// Commit запоминает принятое смещение. Только после сошедшегося тега — см. Check.
func (w *Window) Commit(rel uint32) {
	w.ring[w.head] = rel
	w.head = (w.head + 1) % WinRing
	if w.n < WinRing {
		w.n++
	}
	if int32(rel-w.max) > 0 {
		w.max = rel
	}
}

// Числа, выведенные одно из другого, обязаны спорить при компиляции. В Go для этого нет
// static_assert, но объявление массива отрицательной длины даёт ту же ошибку на этапе сборки.
const (
	_ = uint(Overhead - (20 + 20 + 5 + 16))          // Overhead разошёлся с раскладкой
	_ = uint(LinkMax - (HdrRoom + MTUDefault + Tag)) // строка буфера не сходится
	_ = uint(Row % 4)                                // строка обязана быть кратной четырём
)

// ---- сборка записи, разрезанной между сегментами ----------------------------
//
// ЗАЧЕМ ЭТО ВООБЩЕ ПОНАДОБИЛОСЬ. Сравнение с настоящим трафиком (tests/xhttp-compare.sh)
// показало самый сильный признак протокола: у нас КАЖДЫЙ сегмент начинается с заголовка записи и
// КАЖДАЯ запись кончается ровно на границе сегмента — 100% против 16% и 0% у настоящего TLS,
// где запись живёт своей длиной и границ сегментов не соблюдает. Проверяется это одной строкой
// разбора и не требует ни расшифровки, ни статистики.
//
// Полностью убрать признак нельзя, не отказавшись от датаграммной семантики: настоящий поток
// означает и повторные передачи, и сборку, то есть TCP поверх TCP. Но можно перестать быть
// ИДЕАЛЬНЫМ: отправитель иногда режет запись между двумя сегментами, получатель её собирает.
// Тогда «всегда» превращается в «обычно», и двоичная проверка перестаёт работать.
//
// ЦЕНА НАЗВАНА ЧЕСТНО. Разрезанная запись гибнет целиком, если пропал любой из двух сегментов, —
// то есть одна потеря стоит одного внутреннего пакета, ровно как и раньше. Именно поэтому режем
// на ДВА, а не собираем много пакетов в одну большую запись: запись из одиннадцати сегментов
// превратила бы один процент потерь в одиннадцать.
//
// Возможность СОГЛАСУЕТСЯ в рукопожатии (бит в подписанной части), поэтому сторона, которая не
// умеет собирать, никогда не получит разрезанного — совместимость с реализацией на C не страдает.

// Reasm — сборка одной разрезанной записи. Нулевое значение готово к работе; принадлежит
// владельцу соединения и из других горутин не трогается.
type Reasm struct {
	buf     []byte
	need    int    // сколько байт нагрузки записи заявлено
	rel0    uint32 // смещение ПЕРВОГО сегмента: им зашифрована вся запись
	nextSeq uint32 // какой номер обязан быть у продолжения
	active  bool
	// Dropped — сколько незаконченных сборок пришлось выбросить. Растёт при потерях и при
	// переупорядочивании; ноль на исправном пути.
	Dropped uint64
}

// Feed отдаёт нагрузку сегмента. Возвращает готовую запись (шифротекст с тегом), её ЗАГОЛОВОК (он
// же AAD — пять байт первого сегмента), смещение для nonce, признак готовности и СКОЛЬКО БАЙТ
// нагрузки съедено. Не готово — значит запись продолжится в следующем сегменте.
//
// Заголовок отдаётся отдельно, а не вычисляется вызывающим: у разрезанной записи он лежит в
// ПЕРВОМ сегменте, и вызывающий, взявший его из последнего, получил бы другой AAD и не сошёлся бы
// тегом — при полностью верной криптографии.
//
// ЗАЧЕМ used, ЕСЛИ «ОДНА ДАТАГРАММА — ОДНА ЗАПИСЬ». Потому что это правило ОТПРАВИТЕЛЯ, а
// получателю ядро отдаёт не то, что послали. На приёме работает GRO: идущие подряд сегменты одного
// потока ядро склеивает в один до всякой доставки, и в сырой сокет приходит нагрузка, где записей
// несколько, а последняя вдобавок обрезана посередине. Пока Feed отвергал такую нагрузку целиком
// («заявлено меньше, чем пришло»), каждая склейка уносила пачку внутренних пакетов, и внутренний
// TCP сидел на окне в один пакет.
//
// Цена была измерена на живой связи роутер↔VPS, и она чудовищна: 0,45 Мбит/с против 110 Мбит/с при
// НУЛЕ потерь на самом канале — то есть в двести сорок раз. В пространствах имён этого не видно
// вовсе: там канал без задержки, и окно в один пакет всё равно даёт гигабит, а склейки не
// случается. Поэтому вызывающий обязан звать Feed в цикле, пока нагрузка не кончится (см. FeedAll),
// а не один раз на сегмент.
func (r *Reasm) Feed(seq uint32, isnRX uint32, payload []byte) (body, hdr []byte, rel uint32, ok bool, used int) {
	if r.active && seq == r.nextSeq {
		// Берём РОВНО недостающий хвост записи, а не всю нагрузку: за концом записи в той же
		// нагрузке может лежать следующая — её разберёт следующий круг цикла.
		want := RecHdr + r.need - len(r.buf)
		if want > len(payload) {
			r.buf = append(r.buf, payload...)
			r.nextSeq = seq + uint32(len(payload))
			return nil, nil, 0, false, len(payload)
		}
		r.buf = append(r.buf, payload[:want]...)
		r.active = false
		return r.buf[RecHdr:], r.buf[:RecHdr], r.rel0, true, want
	}
	if r.active {
		// Продолжение не пришло: сегмент потерялся или приехал не по порядку. Незаконченное
		// выбрасываем — держать его дольше значило бы склеить чужие байты с нашими.
		r.active = false
		r.Dropped++
	}
	if len(payload) < RecMin {
		return nil, nil, 0, false, len(payload)
	}
	if payload[0] != recType || payload[1] != recV0 || payload[2] != recV1 {
		return nil, nil, 0, false, len(payload)
	}
	n := int(payload[3])<<8 | int(payload[4])
	// Предел ФОРМАТА, а не предел ПОЛЯ: записей длиннее MaxRecord мы не отправляем никогда, и
	// проверять надо тем же числом, каким проверяют Stream.ReadRecord и xs_reasm_feed в
	// реализации на C. Сравнение с 0xFFFF пускало сюда заявку на 64 КиБ, и буфер сборки на
	// сессию дорастал до неё раньше, чем подделка отвергалась по тегу.
	if n < Tag || n > MaxRecord {
		return nil, nil, 0, false, len(payload)
	}
	if RecHdr+n <= len(payload) {
		// Целая запись. Отдаём РОВНО её длину: если за ней в той же нагрузке лежит ещё одна
		// (склейка GRO), она достанется следующему кругу цикла.
		return payload[RecHdr : RecHdr+n], payload[:RecHdr], Rel(seq, isnRX), true, RecHdr + n
	}
	// Начало разрезанной записи. Копия обязательна: приёмный буфер перепишется следующим же
	// чтением.
	r.buf = append(r.buf[:0], payload...)
	r.need = n
	r.rel0 = Rel(seq, isnRX)
	r.nextSeq = seq + uint32(len(payload))
	r.active = true
	return nil, nil, 0, false, len(payload)
}

// FeedAll — Feed в цикле по всей нагрузке сегмента: на каждую готовую запись зовётся fn.
//
// Отдельной функцией, а не циклом у каждого вызывающего, потому что вызывающих двое (хаб и клиент)
// и цикл у них обязан быть одинаковым: смещение внутри нагрузки прибавляется к номеру
// последовательности, иначе у второй записи в склейке выйдет чужой nonce и не сойдётся тег.
//
// fn обязана СЪЕСТЬ запись до возврата: body указывает либо в нагрузку, либо в буфер сборки, и
// следующий круг цикла их перепишет.
func (r *Reasm) FeedAll(seq uint32, isnRX uint32, payload []byte, fn func(body, hdr []byte, rel uint32)) {
	for off := 0; off < len(payload); {
		body, hdr, rel, ok, used := r.Feed(seq+uint32(off), isnRX, payload[off:])
		if used <= 0 {
			return // защита от вечного цикла: Feed обязан всегда что-то съедать
		}
		off += used
		if ok {
			fn(body, hdr, rel)
		}
	}
}

// Reset забывает незаконченную сборку: зовётся при подъёме соединения заново.
func (r *Reasm) Reset() { r.active = false; r.buf = r.buf[:0] }

// ---- пачка кадров в одной записи --------------------------------------------
//
// ЗАЧЕМ. Сравнение с настоящим xhttp показало две вещи разом. Первая: у нас каждая запись равна
// одному пакету и кончается ровно на границе сегмента — у настоящего TLS записи по восемь
// килобайт, и границ сегментов они не соблюдают. Вторая: обратное направление у нас состоит из
// сплошных мелких записей (внутренние подтверждения TCP, по 73 байта на проводе), тогда как у
// настоящей загрузки обратное направление — это в основном ГОЛЫЕ подтверждения TCP.
//
// Пачка чинит обе: несколько кадров едут одной записью, запись становится больше сегмента и
// разрезается между ними, а мелких пакетов на проводе становится в разы меньше — и голые
// подтверждения появляются сами, потому что их больше нечем возить.
//
// И ЭТО ДЕШЕВЛЕ, А НЕ ДОРОЖЕ. Один пакет в записи стоит 61 байт накладных. Шесть полноразмерных
// пакетов в одной записи стоят 6×40 (заголовки сегментов) + 5 (запись) + 16 (тег) + 13
// (контейнер) = 274 байта на шесть пакетов, то есть 46 байт на пакет. Пачка не жертвует главным
// числом протокола, а улучшает его.
//
// ЧЕМ ПЛАТИМ. Разрезанная запись гибнет целиком, если пропал любой её сегмент: одна потеря стоит
// всей пачки. Поэтому размер пачки не постоянный, а управляется обратной связью: получатель
// сообщает о несобравшихся записях (CtlReasmLoss), и отправитель немедленно возвращается к одному
// кадру в записи. На чистом пути это ничего не стоит, на рваном — защищает.

const (
	// CtlBatch — контейнер: за ним идут кадры, каждый с двухбайтовой длиной.
	CtlBatch = 0x05
	// CtlReasmLoss — «у меня не собралось N записей»: обратная связь для размера пачки.
	CtlReasmLoss = 0x06
)

// BatchHdr — сколько занимает контейнер сверх самих кадров: байт типа плюс по два байта длины на
// кадр.
const BatchHdr = 1

// BatchBuild складывает кадры в контейнер. Возвращает длину или 0, если не влезло.
//
// Один кадр в пачку НЕ кладётся: он едет как есть, без контейнера, потому что так дешевле на байт
// и потому что подавляющее большинство записей — одиночные (интерактивный трафик).
func BatchBuild(dst []byte, frames [][]byte) int {
	if len(frames) < 2 {
		return 0
	}
	need := BatchHdr
	for _, f := range frames {
		need += 2 + len(f)
	}
	// Предел ОТКРЫТОГО текста, а не ёмкости буфера: буфер держит MaxRecord+Tag и пропустил бы
	// пачку, которую приёмник отвергнет по длине тела. Проверять надо здесь, а не только у
	// вызывающего: ограничителей сборки четыре (два в клиенте, два в хабе), и единственный
	// надёжный рубеж — сам сборщик. Зеркало xs_batch_build.
	if need > len(dst) || need > MaxPlain {
		return 0
	}
	dst[0] = CtlBatch
	o := BatchHdr
	for _, f := range frames {
		dst[o] = byte(len(f) >> 8)
		dst[o+1] = byte(len(f))
		o += 2 + copy(dst[o+2:], f)
	}
	return o
}

// BatchIter разбирает контейнер и отдаёт кадры по одному. Возвращает false, если контейнер битый:
// такое приходит только от порчи или от чужого, и разбирать его дальше нельзя.
//
// Битый контейнер отвергается ЦЕЛИКОМ: при false обработчик не вызван НИ РАЗУ. Ради этого цепочка
// длин проходится дважды — первый проход только проверяет, второй (лишь при удачной проверке)
// доставляет. Отдавать кадры по мере разбора нельзя: «сколько успели до места порчи» означало бы
// доставку половины пачки неизвестного происхождения, а отменить доставленное вызывающему нечем —
// на false он умеет только увеличить счётчик (I-063). Контейнер целиком лежит в памяти и не длиннее
// MaxRecord, поэтому второй проход стоит одно сложение и одно сравнение на кадр.
//
// Кадров в контейнере не больше BatchFramesMax, и это проверяется НА ПРИЁМЕ, а не только на сборке:
// иначе контейнер на 8191 байт из однобайтовых кадров давал бы 2730 вызовов обработчика. Законная
// пачка длиннее предела не бывает — набор кадров ограничен этой же константой и здесь (client,
// hub: batchMax выше неё не растёт), и в реализации на C, а сама константа равна восьми с первого
// дня формата, поэтому предел не отвергнет пачку, собранную уже установленными версиями.
func BatchIter(pt []byte, fn func(frame []byte)) bool {
	if len(pt) < BatchHdr || pt[0] != CtlBatch {
		return false
	}
	frames := 0
	for o := BatchHdr; o < len(pt); {
		if o+2 > len(pt) {
			return false
		}
		n := int(pt[o])<<8 | int(pt[o+1])
		o += 2
		if n == 0 || o+n > len(pt) {
			return false
		}
		frames++
		if frames > BatchFramesMax {
			return false
		}
		o += n
	}
	// Второй проход: проверок нет, цепочка длин пройдена целиком выше.
	for o := BatchHdr; o < len(pt); {
		n := int(pt[o])<<8 | int(pt[o+1])
		o += 2
		fn(pt[o : o+n])
		o += n
	}
	return true
}

// LossBuild — сообщение «не собралось N записей».
func LossBuild(pt []byte, n int) int {
	if len(pt) < 3 {
		return 0
	}
	if n > 0xFFFF {
		n = 0xFFFF
	}
	pt[0] = CtlReasmLoss
	pt[1] = byte(n >> 8)
	pt[2] = byte(n)
	return 3
}

// LossValue — сколько записей не собралось у той стороны, или -1, если это не тот кадр.
func LossValue(pt []byte) int {
	if len(pt) < 3 || pt[0] != CtlReasmLoss {
		return -1
	}
	return int(pt[1])<<8 | int(pt[2])
}
