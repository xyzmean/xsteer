// Пакет wire — арифметика провода xsteer: запись, nonce, окно приёма, пределы соединения.
//
// Это порт src/ext/xswire.{c,h} из движка steer. Здесь нет ни сокетов, ни времени из
// системы, ни криптографии — ровно та же граница, что проведена в C, и по той же причине:
// сборка кадра, вывод nonce и защита от повтора проверяются тестом без сети и без прав
// root, а циклы, которые всё это вызывают, живут в пакетах link и client.
//
// ЧТО ЗА ПРОТОКОЛ. xsteer несёт IP-пакеты внутри потока, который для DPI выглядит как TLS
// на :443 поверх обычного TCP: рукопожатие имеет форму ClientHello/ServerHello (пакеты
// chello и noise), а каждый пакет данных — форму записи application_data. Транспорт при
// этом ПОДДЕЛЬНЫЙ: заголовок TCP настоящий, а семантика датаграммная — один пакет, один
// сегмент, одна запись, ни повторов, ни окна, ни контроля потока. Так облик достаётся без
// TCP-поверх-TCP и без второго слоя шифра.
//
// ОТКУДА «НАКЛАДНЫЕ РАСХОДЫ К НУЛЮ». Из кадра выкинуто то, что WireGuard несёт зря: индекс
// получателя (его заменяет четвёрка адрес-порт поддельного TCP) и счётчик (его заменяет
// номер последовательности того же поддельного TCP). Эти 12 байт и оплачивают пятибайтовый
// заголовок записи:
//
//	WireGuard поверх UDP               20 IP + 8 UDP + 32 WG  = 60 байт
//	WireGuard поверх поддельного TCP   20 IP + 20 TCP + 32 WG = 72 байта
//	xsteer                             20 + 20 + 5 + 16 тега  = 61 байт
//
// СОВМЕСТИМОСТЬ С РЕАЛИЗАЦИЕЙ НА C — ТРЕБОВАНИЕ, А НЕ ПОЖЕЛАНИЕ. Десктопный клиент
// подключается к тому же хабу, что и роутер, поэтому каждое число и каждая раскладка здесь
// обязаны совпадать с src/ext/xswire.h побайтово. Расхождение проявится не ошибкой сборки,
// а туннелем, который поднимается и не несёт трафик, — поэтому совпадение закреплено
// векторами в testdata и тестом interop.
package wire

import "errors"

// ---- размеры ---------------------------------------------------------------
//
// Числа, выведенные одно из другого, стоят рядом и спорят при КОМПИЛЯЦИИ (см. проверки в
// конце файла) — то же правило, что записано у XS_STATIC_ASSERT в C: иначе одно поправят, а
// второе останется, и расхождение проявится как «маленькие пакеты ходят, большие пропадают»,
// худший класс отказов в диагностике.
const (
	RecHdr  = 5  // 17 03 03 LL LL
	Tag     = 16 // тег AEAD, у обоих шифров одинаковый
	IPHdr   = 20
	TCPHdr  = 20 // без опций: в сегментах данных их нет
	HdrRoom = IPHdr + TCPHdr + RecHdr
	// Overhead — то, что xsteer добавляет к внутреннему пакету. Главное число протокола.
	Overhead = HdrRoom + Tag
	// LinkMax — обычный Ethernet; MTU канала может быть меньше, и тогда MTU туннеля считает MTU().
	LinkMax = 1500
	// MTUDefault — потолок MTU туннеля при канале 1500.
	MTUDefault = LinkMax - Overhead
	// Row — строка буфера: ровно пакет на проводе при канале 1500.
	Row = LinkMax
	// RecMin — самая маленькая осмысленная запись: заголовок плюс тег, открытый текст пустой.
	// Это keepalive; кадр короче — не наш.
	RecMin = RecHdr + Tag
)

// Ошибки разбора. Разные НАРОЧНО: «не наш кадр» и «битая длина» требуют разных решений на
// стороне вызывающего — первое отбрасывается счётчиком, второе означает, что соединение
// пора поднимать заново.
var (
	ErrNotOurs = errors.New("wire: не запись xsteer")
	ErrLength  = errors.New("wire: длина не сходится")
)

// MTU — MTU туннеля от MTU канала. Отдельной функцией, а не выражением на месте, потому что
// это же число печатает диагностика и проверяет клиент при подъёме устройства.
func MTU(link int) int {
	m := link - Overhead
	if m < 576 {
		return 576 // ниже этого IP-стек становится непредсказуем
	}
	return m
}

// ---- тип кадра -------------------------------------------------------------
//
// Внутри записи НЕТ ни поля типа, ни поля длины. Длину даёт заголовок записи (один пакет =
// один сегмент = одна запись), а тип — первый байт открытого текста: у IP-пакета там версия.
// Байта inner content type, который есть в настоящем TLS 1.3, у нас нет намеренно: он лежит
// под AEAD, то есть невидим DPI, а стоил бы байт на каждом пакете.

// Kind — что лежит в расшифрованном кадре.
type Kind int

const (
	KindBad Kind = iota // отбросить со счётчиком; соединение НЕ рвать
	KindIPv4
	KindIPv6
	KindKeepalive // пустой открытый текст: держим отображение NAT живым
	KindCtl       // служебный кадр, первый байт — Ctl*
)

// Служебные кадры. Значения совпадают с XS_CTL_* в C.
const (
	CtlRetire = 0x01 // «это соединение уходит, продолжай на новом»
	CtlMTU    = 0x02 // итог согласования: «дальше несём столько»
	CtlProbe  = 0x03 // проба пути: кадр ровно такого размера, какой проверяем
	CtlPack   = 0x04 // эхо на пробу: размер, который ДОШЁЛ
)

// FrameKind — что за кадр расшифровался.
func FrameKind(pt []byte) Kind {
	if len(pt) == 0 {
		return KindKeepalive
	}
	switch {
	case pt[0]&0xF0 == 0x40:
		if len(pt) >= IPHdr {
			return KindIPv4
		}
		return KindBad
	case pt[0]&0xF0 == 0x60:
		if len(pt) >= 40 {
			return KindIPv6
		}
		return KindBad
	case pt[0] <= 0x0F:
		return KindCtl
	}
	return KindBad
}

// ---- запись ----------------------------------------------------------------

// Версия в заголовке записи — 0x0303, то есть «TLS 1.2», и это не ошибка. TLS 1.3 сам ставит
// в записях именно её ради посредников, которые не понимают версию 1.3 и рвут такие потоки;
// настоящая версия согласуется расширением внутри рукопожатия. Поставить здесь 0x0304 значило
// бы отличаться от всякого настоящего TLS 1.3 первым же байтом каждой записи.
const (
	recType = 0x17
	recV0   = 0x03
	recV1   = 0x03
)

// RecBuild записывает заголовок записи в hdr (ровно RecHdr байт) для нагрузки длиной bodyN
// (шифротекст вместе с тегом).
func RecBuild(hdr []byte, bodyN int) error {
	if len(hdr) < RecHdr {
		return ErrLength
	}
	if bodyN < Tag || bodyN > 0xFFFF {
		return ErrLength
	}
	hdr[0], hdr[1], hdr[2] = recType, recV0, recV1
	hdr[3] = byte(bodyN >> 8)
	hdr[4] = byte(bodyN)
	return nil
}

// RecParse разбирает нагрузку сегмента как ОДНУ запись и возвращает срез шифротекста с тегом,
// подрезанный на месте — без копии.
//
// Проверка «длина в записи равна остатку сегмента» здесь не педантизм, а предфильтр: на
// публичный порт хаба сыплется сканерный шум, и три сравнения отбивают его до AEAD, то есть
// до всей дорогой работы.
func RecParse(seg []byte) ([]byte, error) {
	if len(seg) < RecMin {
		return nil, ErrNotOurs
	}
	if seg[0] != recType || seg[1] != recV0 || seg[2] != recV1 {
		return nil, ErrNotOurs
	}
	n := int(seg[3])<<8 | int(seg[4])
	// РОВНО остаток сегмента, а не «не больше». Одна датаграмма — одна запись, и запись,
	// заявившая меньше, чем лежит в сегменте, означала бы поток: там, где потока нет, это либо
	// чужой пакет, либо попытка спрятать за концом записи что-то ещё.
	if n != len(seg)-RecHdr || n < Tag {
		return nil, ErrLength
	}
	return seg[RecHdr:], nil
}

// ---- nonce -----------------------------------------------------------------

// Rel — смещение внутри потока, из которого выводится nonce.
//
// ОТНОСИТЕЛЬНОЕ, а не абсолютный номер последовательности, и это не косметика. Часть
// межсетевых экранов и CPE рандомизирует начальный номер и прибавляет постоянное Δ ко всем
// номерам потока. При nonce от абсолютного номера это означает, что КАЖДЫЙ пакет
// расшифровывается неверно — тотальный молчаливый отказ, самый злой класс отказов. Получатель
// берёт начальный номер пира из того SYN, который фактически увидел (уже со сдвигом), и Δ
// сокращается тождественно.
func Rel(seq, isn uint32) uint32 { return seq - isn }

// Nonce = iv XOR rel, ровно как в TLS 1.3 (RFC 8446 §5.3): номер записи выравнивается вправо
// и накладывается на статический iv. Совпадение с aead_nonce из tls13.c обязательно — оттуда
// берётся и сам AEAD.
func Nonce(iv [12]byte, rel uint32) [12]byte {
	out := iv
	for i := 0; i < 4; i++ {
		out[11-i] ^= byte(rel >> (8 * i))
	}
	return out
}

// ---- пределы соединения ----------------------------------------------------
//
// Переполнение uint32 в rel не обрабатывается, а ИСКЛЮЧАЕТСЯ: соединение выводится из работы
// задолго до заворота. Это лучше восстановления старших разрядов по SRTP-подобному правилу —
// то правило исполняется раз в 4 ГиБ, а значит не проверено ничем, кроме теста, и ошибка в
// нём даёт разъезд ключей без единой строки в журнале.
//
// Один и тот же ретайр закрывает три задачи, поэтому отдельных механизмов нет: прямую
// секретность (новое соединение — новые эфемерные ключи), пределы AEAD (0,75 млн записей на
// гигабайт против 23 млн, разрешённых RFC 8446 §5.5 для AES-GCM) и отсутствие ратчета на
// проводе (нет кадра обновления ключей, нет бита фазы ключа, нет кода, который это разбирает).
const (
	RelRetire   = uint32(1) << 30    // 1 ГиБ в одну сторону
	AgeRetireMS = int64(1200 * 1000) // или 20 минут — что раньше
	// Успешник поднимается заранее, на девяти десятых порога: три X25519 на слабом процессоре
	// это десятки миллисекунд, и делать их в потоке пересылки значит подарить пакетам такую же
	// паузу.
	renewNum = 9
	renewDen = 10
)

// RenewDue — пора поднимать сменное соединение.
func RenewDue(rel uint32, ageMS int64) bool {
	return rel >= uint32(uint64(RelRetire)*renewNum/renewDen) ||
		ageMS >= AgeRetireMS*renewNum/renewDen
}

// RetireDue — соединение ОБЯЗАНО замолчать, как только это вернуло true, даже если сменное не
// поднялось. Иначе одна сетевая неудача превращается в повтор nonce, то есть в полную потерю
// защиты AEAD.
func RetireDue(rel uint32, ageMS int64) bool {
	return rel >= RelRetire || ageMS >= AgeRetireMS
}

// ---- защита от повтора -----------------------------------------------------
//
// Обязательна, и это не «на всякий случай»: повторно присланный пакет расшифруется — тот же
// nonce, тот же ключ, — поэтому окно здесь единственная защита от воспроизведения.
//
// Помним последние WinRing принятых смещений. Кольцо И ЕСТЬ терпимость к переупорядочиванию:
// при полноразмерных записях 256 номеров это около 368 КиБ потока, заметно больше любого
// переупорядочивания, которое встречается на практике. Проверка при этом ТОЧНАЯ — дырки, в
// которую проскочил бы повтор, не остаётся, в отличие от битовой карты с грубой
// гранулярностью.
const WinRing = 256

// Window — окно приёма одного направления одного соединения.
type Window struct {
	max  uint32 // самое дальнее принятое смещение
	ring [WinRing]uint32
	n    int // сколько заполнено, пока кольцо не обернулось
	head int // куда писать следующее
}

// Reset возвращает окно в исходное состояние: нужно при подъёме соединения заново.
func (w *Window) Reset() { *w = Window{} }

// Check — можно ли пробовать AEAD на этом смещении.
//
// РАЗДЕЛЕНИЕ CHECK И COMMIT ОБЯЗАТЕЛЬНО. Обновить окно до проверки тега значит дать
// подделанному пакету с далёким смещением выбить из окна весь честный поток: max уехал бы
// вперёд, и настоящие пакеты стали бы «слишком старыми». Поэтому Commit зовётся только после
// сошедшегося тега, и в коде это написано там же, где вызывается.
func (w *Window) Check(rel uint32) bool {
	// Нулевое смещение не бывает данными: начальный номер занят самим SYN, поэтому первая
	// запись начинается с единицы. Заодно это позволяет нулём обозначать «ещё ничего не
	// принято» и не держать отдельный признак.
	if rel == 0 {
		return false
	}
	// Знаковая разность — то же понятие «позже», что в арифметике подтверждений. Одно
	// сравнение закрывает подавляющую часть пакетов: они идут по порядку.
	if int32(rel-w.max) > 0 {
		return true
	}
	if w.n == WinRing {
		// Кольцо обернулось: старейшее помнимое лежит там, куда сейчас писать. Всё, что старше
		// него, отвергаем — не потому, что это точно повтор, а потому, что проверить нечем, а
		// пропустить непроверенное здесь нельзя.
		if int32(rel-w.ring[w.head]) < 0 {
			return false
		}
	}
	for i := 0; i < w.n; i++ {
		if w.ring[i] == rel {
			return false
		}
	}
	return true
}

// Commit запоминает принятое смещение. Только после сошедшегося тега — см. Check.
func (w *Window) Commit(rel uint32) {
	w.ring[w.head] = rel
	w.head = (w.head + 1) % WinRing
	if w.n < WinRing {
		w.n++
	}
	if int32(rel-w.max) > 0 {
		w.max = rel
	}
}

// Числа, выведенные одно из другого, обязаны спорить при компиляции. В Go для этого нет
// static_assert, но объявление массива отрицательной длины даёт ту же ошибку на этапе сборки.
const (
	_ = uint(Overhead - (20 + 20 + 5 + 16))          // Overhead разошёлся с раскладкой
	_ = uint(LinkMax - (HdrRoom + MTUDefault + Tag)) // строка буфера не сходится
	_ = uint(Row % 4)                                // строка обязана быть кратной четырём
)
