package wire

import "fmt"

// ---- ограничитель частоты сообщений ----------------------------------------
//
// Любая строка в журнал, которую вызывает ПРИШЕДШИЙ ИЗ СЕТИ пакет, — это средство залить чужой
// журнал и забить чужой диск: частоту выбирает не хозяин узла, а тот, кто шлёт. Клиент на
// десктопе слушает меньше хаба, но принимает от него что угодно, и путь «испорченный кадр →
// строка в журнал» одинаков у обеих сторон, поэтому ограничитель общий.
//
// Подавленные НЕ теряются: их число попадает в следующую напечатанную строку. Иначе
// ограничитель врал бы — «одно сообщение» вместо «ста тысяч попыток», а именно это число и
// говорит, чинить настройку или отбивать поток.
const LogEveryMS = 5000

// RateLog — состояние ограничителя для одного места в коде. Нулевое значение готово к работе.
type RateLog struct {
	last int64
	held uint64
}

// Allow — печатать ли сейчас; held получает число подавленных с прошлой печати.
func (r *RateLog) Allow(nowMS, everyMS int64) (bool, uint64) {
	if r.last != 0 && nowMS-r.last < everyMS {
		r.held++
		return false, 0
	}
	held := r.held
	r.held = 0
	// Время печати запоминается, даже если печатать нечего было бы: иначе первая же пауза
	// длиннее окна открывала бы поток заново на каждый пакет.
	if nowMS == 0 {
		r.last = 1
	} else {
		r.last = nowMS
	}
	return true, held
}

// HeldSuffix — готовый хвост для строки: « (и ещё N таких же…)» либо пустая строка.
func HeldSuffix(held uint64) string {
	if held == 0 {
		return ""
	}
	return fmt.Sprintf(" (и ещё %d таких же за последние %d с)", held, LogEveryMS/1000)
}
