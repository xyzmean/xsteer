#!/bin/sh
# Замер ТЕЛЕФОННОГО пути данных: устройство без разгрузки сегментации, отданное клиенту готовым
# дескриптором, и режим потока — ровно то, что получается на Android из VpnService.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ СТЕНД, КОГДА ЕСТЬ speed.sh. speed.sh меряет десктопный путь: устройство там
# открывает сам движок, с IFF_VNET_HDR, то есть с разгрузкой сегментации, и в ядро уезжают
# супер-кадры. На телефоне устройство открывает система, флага IFF_VNET_HDR у него нет и
# поставить его некому — он задаётся при создании. Значит и мерить надо другой путь: один пакет,
# одно чтение, один пакет, одна запись. Клиента для этого поднимает tests/phonepath.go, где
# настройки списаны с mobile/mobile.go значение в значение.
#
#     sudo sh tests/phone.sh              полный набор: соединений 1, 2, 4, по три прогона
#     sudo sh tests/phone.sh 1            только одно соединение
#     XSP_RUNS=5 XSP_SECS=10 sudo sh tests/phone.sh
#     XSP_VNET=1 sudo sh tests/phone.sh 1 образец: тот же клиент, но устройство с разгрузкой
#     XSP_RTT_MS=40 sudo sh tests/phone.sh 1  путь с задержкой: сотовая сеть, а не соседний процесс
#     XSP_RTT_MS=40 XSP_LOSS=0.1 sudo sh tests/phone.sh  путь с потерями: он и есть настоящий
#     XSP_CPUS=0 sudo sh tests/phone.sh 1     клиент на ОДНОМ ядре: телефон, а не сервер
#
# ПОЧЕМУ ПРОГОНОВ НЕСКОЛЬКО. Числа туннеля разнятся между прогонами на десятки процентов, и
# одиночное число не значит ничего. Отсюда же и столбец повторных передач: несколько соединений
# на ОДНОЙ очереди устройства переставляют пакеты, а перестановка бьёт по внутреннему TCP сильнее,
# чем помогает параллельность, — и увидеть это можно только по повторам, а не по скорости.
#
# ЧТО ЭТОТ СТЕНД ПОКАЗАЛ (x86_64, 8 ядер, четыре потока iperf3, по три прогона на клетку; хаб и
# пир — соседние пространства имён одной машины). Размах по трём прогонам, Мбит/с:
#
#   задержка  потери  соед.   наверх        повторов        вниз          ядер на Гбит
#   0 мс      —       1       3000..3180    238025..256749  2588..2666    0,64..0,67
#   0 мс      —       4       1491..1523    335694..341815  2618..4043    0,63..0,81
#   5 мс      —       1       2079..2159    172523..190880  2166..2358    0,67..0,71
#   5 мс      —       4       1978..2026    237414..261679  2337..2827    0,73..0,85
#   40 мс     —       1        557..567      43955..55413    628..648     0,67..0,70
#   40 мс     —       2        885..960      64756..69896    647..909     0,74..0,77
#   40 мс     —       4       1697..1954       1780..8931    642..1285    0,77..0,97
#   40 мс     0,5%    1        314..336      21171..31155    162..398     0,70..1,05
#   40 мс     0,5%    4        535..689       9854..15296    457..820     0,87..1,01
#
# ЧИТАЕТСЯ ЭТО ТАК. Жалоба «на телефоне около ста мегабит вниз» НА СЕРВЕРЕ НЕ ВОСПРОИЗВОДИТСЯ:
# тот же путь данных — чужой дескриптор, разгрузки нет, режим потока — даёт здесь гигабиты.
# Значит предел телефона лежит в самом телефоне (его ядра, его радио), а не в устройстве пути.
# Зато видно, где у пути запас: профиль клиента (--pprof) на приёме — 84% времени в системных
# вызовах, из них половина это по одному write(2) на каждый пакет в устройство. Разгрузки
# сегментации у дескриптора от VpnService нет и быть не может, поэтому убрать эти вызовы нечем,
# — но разложить их по ядрам можно, и это делают несколько соединений.
#
# Выигрыш от нескольких соединений ЗАВИСИТ ОТ ЗАДЕРЖКИ, и зависимость обратная ожиданию. На пути
# с задержкой (то есть на любом настоящем) четыре соединения дают втрое больше отдачи и впятеро
# меньше повторных передач: одно соединение упирается в своё окно. На стенде без задержки вовсе
# они отдачу вдвое ухудшают — там окна хватает, а четыре читателя одной очереди только
# переставляют пакеты. Пути без задержки у телефона не бывает.
set -eu
umask 077

BIN=${XSTEER_BIN:-./build/xsteer}
PHONE=${XSP_PHONE_BIN:-./build/phonepath}
RUNS=${XSP_RUNS:-3}
SECS=${XSP_SECS:-6}
STREAMS=${XSP_STREAMS:-4}
# RTT — задержка пути в обе стороны, миллисекунды. Ноль означает «соседний процесс», и это самый
# нечестный из возможных стендов: у телефона путь до хаба идёт через сотовую сеть, а окно, делённое
# на задержку, и есть потолок скорости, если окна не хватает.
RTT=${XSP_RTT_MS:-0}
# LOSS — потери на ПУТИ ДО ХАБА, в процентах. Ноль означает идеальный провод, какого у телефона не
# бывает никогда. Потеря здесь бьёт по НАШЕМУ внешнему TCP, а не по внутреннему: одна потеря на
# одном соединении останавливает весь туннель на круг, потому что поток обязан доставить всё по
# порядку. Это и есть та переменная, ради которой соединений бывает больше одного.
LOSS=${XSP_LOSS:-0}
# CPUS — на каких ядрах держать КЛИЕНТА. Пусто означает «на всех». Одно ядро — ближайшее, что
# можно изобразить из телефона на сервере: горячий путь у нас однопоточный на соединение, и разница
# между ядром телефона и ядром сервера остаётся, но хотя бы число ядер перестаёт врать.
CPUS=${XSP_CPUS:-}
# TXQ — длина очереди устройства. По умолчанию 500: столько даёт ядро устройству, созданному
# VpnService, и поменять её приложение не может — прав нет. Свои устройства мы поднимаем с 4096
# (tun.TxQueueLen), и разница между этими числами видна на отдаче.
TXQ=${XSP_TXQ:-500}
# PPROF — куда сложить профиль клиента, снятый во время ПЕРВОГО прогона вниз. Пусто — не снимать.
# Нужно ровно для одного вопроса: если потолок не здесь, а на телефоне, то надо показать, во что
# именно уходит время клиента, а не рассуждать о нём.
PPROF=${XSP_PPROF:-}
NSH=xsp-hub
NSA=xsp-a
WORK=

cleanup() {
    for ns in $NSH $NSA; do
        ip netns pids $ns 2>/dev/null | xargs -r kill 2>/dev/null || true
        ip netns del $ns 2>/dev/null || true
    done
    [ -n "$WORK" ] && [ -z "${XSP_KEEP:-}" ] && rm -rf "$WORK"
    return 0
}
trap cleanup EXIT INT TERM PIPE HUP

[ "$(id -u)" = 0 ] || { echo "нужен root"; exit 2; }
[ -c /dev/net/tun ] || { echo "нет /dev/net/tun"; exit 2; }
command -v iperf3 >/dev/null || { echo "нет iperf3"; exit 2; }
[ -x "$BIN" ] || { echo "нет $BIN — соберите: go build -o build/xsteer ./cmd/xsteer"; exit 2; }
if [ ! -x "$PHONE" ]; then
    echo "собираю стенд телефонного пути…"
    go build -o "$PHONE" tests/phonepath.go
fi

# num вытаскивает из отчёта iperf3 скорость и повторные передачи ОТПРАВИТЕЛЯ. Повторы нужны
# наравне со скоростью: они показывают, что стало с внутренним TCP, когда пакеты переставили.
num() {
    python3 - "$1" "$2" <<'PY'
import json, sys
# Несостоявшийся прогон печатается прочерком, а не нулём. Ноль читался бы как «скорость нулевая»,
# а это другое: iperf3 на пути с потерями иногда бросает своё управляющее соединение (оно идёт
# тем же туннелем), и тогда замера просто нет.
try:
    d = json.load(open(sys.argv[1]))
    if d.get("error"):
        raise ValueError(d["error"])
    if sys.argv[2] == "mbps":
        print(int(d["end"]["sum_received"]["bits_per_second"] / 1e6))
    else:
        print(int(d["end"]["sum_sent"].get("retransmits", -1)))
except Exception:
    print("—")
PY
}

# cpu_ms — сколько процессорного времени (своего и ядерного) съел процесс, в миллисекундах.
# Считается по /proc: без него «упирается ли в процессор» остаётся догадкой, а именно этот вопрос
# и решает, виноват ли телефон или наш код. Единица тика — 100 в секунду на всех наших системах.
cpu_ms() {
    awk '{print ($14 + $15) * 10}' "/proc/$1/stat" 2>/dev/null || echo 0
}

# setup поднимает два пространства имён, хаб и телефонный клиент. $1 — число соединений.
setup() {
    conns="$1"
    cleanup
    WORK="$(mktemp -d)"; chmod 700 "$WORK"
    for ns in $NSH $NSA; do ip netns add $ns; ip -n $ns link set lo up; done
    ip link add ha netns $NSH type veth peer name ah netns $NSA
    ip -n $NSH addr add 10.213.1.1/24 dev ha
    ip -n $NSA addr add 10.213.1.2/24 dev ah
    ip -n $NSH link set ha up; ip -n $NSA link set ah up
    netem=""
    [ "$RTT" != 0 ] && netem="delay $((RTT / 2))ms"
    [ "$LOSS" != 0 ] && netem="$netem loss ${LOSS}%"
    if [ -n "$netem" ]; then
        # Задержка и потери вешаются на ОБА конца: netem работает на исходящем, и одна сторона
        # дала бы несимметричный путь, на котором подтверждения приходят быстрее данных.
        # shellcheck disable=SC2086
        ip netns exec $NSH tc qdisc add dev ha root netem $netem limit 20000
        # shellcheck disable=SC2086
        ip netns exec $NSA tc qdisc add dev ah root netem $netem limit 20000
    fi

    priv_hub=$("$BIN" genkey); pub_hub=$(printf '%s\n' "$priv_hub" | "$BIN" pubkey)
    priv_a=$("$BIN" genkey);   pub_a=$(printf '%s\n' "$priv_a" | "$BIN" pubkey)
    cat > "$WORK/hub.conf" <<EOF
[Interface]
PrivateKey = $priv_hub
Address    = 10.79.0.1/24
ListenPort = 443

[Peer]
PublicKey  = $pub_a
AllowedIPs = 10.79.0.2/32
EOF
    cat > "$WORK/a.conf" <<EOF
[Interface]
PrivateKey = $priv_a
Address    = 10.79.0.2/24
SNI        = www.microsoft.com

[Peer]
PublicKey  = $pub_hub
AllowedIPs = 10.79.0.0/24
Endpoint   = 10.213.1.1:443
PersistentKeepalive = 25
EOF
    chmod 600 "$WORK"/*.conf

    # Хаб — наш обычный, в режиме потока: поддельного TCP на телефоне не бывает.
    ip netns exec $NSH "$BIN" hub "$WORK/hub.conf" --stream-only --stream-port 443 \
        > "$WORK/hub.log" 2>&1 &
    sleep 0.8
    vnet=""
    [ -n "${XSP_VNET:-}" ] && vnet="--vnet"
    pin=""
    [ -n "$CPUS" ] && pin="taskset -c $CPUS"
    prof=""
    [ -n "$PPROF" ] && prof="--pprof 127.0.0.1:6060"
    # shellcheck disable=SC2086
    ip netns exec $NSA $pin "$PHONE" --conf "$WORK/a.conf" --dev xsp0 --addr 10.79.0.2/24 \
        --route 10.79.0.0/24 --stream-port 443 --conns "$conns" --txqueue "$TXQ" $vnet $prof \
        > "$WORK/a.log" 2>&1 &
    CLIPID=$!

    for i in $(seq 1 80); do
        grep -q 'рукопожатие прошло' "$WORK/a.log" 2>/dev/null && break
        sleep 0.25
    done
    if ! grep -q 'рукопожатие прошло' "$WORK/a.log" 2>/dev/null; then
        echo "  туннель не поднялся:"; sed 's/^/    /' "$WORK/a.log" | tail -10; return 1
    fi
    sleep 1
    # Сервер запускается фоном, а не ключом -D: отделиться от терминала iperf3 умеет не везде
    # (в контейнере без управляющего терминала daemon() отвечает «No such device»), и тогда замер
    # молча даёт нули.
    ip netns exec $NSH iperf3 -s -B 10.79.0.1 > "$WORK/is.log" 2>&1 &
    sleep 0.5
}

# bench — один набор прогонов при заданном числе соединений. $1 — conns, $2 — подпись.
bench() {
    conns="$1"; label="$2"
    setup "$conns" || return 1
    head -1 "$WORK/a.log" | sed 's/^/  /'
    i=1
    while [ "$i" -le "$RUNS" ]; do
        ip netns exec $NSA iperf3 -c 10.79.0.1 -P "$STREAMS" -t "$SECS" -J \
            > "$WORK/up.json" 2>/dev/null || true
        c0=$(cpu_ms "$CLIPID")
        curlpid=""
        if [ -n "$PPROF" ] && [ "$i" = 1 ]; then
            ip netns exec $NSA curl -s -o "$PPROF" \
                "http://127.0.0.1:6060/debug/pprof/profile?seconds=$SECS" &
            curlpid=$!
        fi
        ip netns exec $NSA iperf3 -c 10.79.0.1 -P "$STREAMS" -t "$SECS" -R -J \
            > "$WORK/dn.json" 2>/dev/null || true
        # Ждём ИМЕННО снимок профиля: голый wait ждал бы и хаб, и клиента, то есть навсегда.
        [ -n "$curlpid" ] && wait "$curlpid"
        c1=$(cpu_ms "$CLIPID")
        dn=$(num "$WORK/dn.json" mbps)
        # Ядер на гигабит: процессорное время клиента, делённое на длительность и на скорость.
        # Число больше единицы означает, что одного ядра на этот гигабит не хватает.
        case "$dn" in
            ''|*[!0-9]*) cores="—" ;;
            *) cores=$(python3 -c "print('%.2f' % (($c1-$c0)/1000.0/$SECS/max($dn,1)*1000))") ;;
        esac
        printf '  %-22s прогон %d:  наверх %5s Мбит/с (повторов %6s)   ВНИЗ %5s Мбит/с (повторов %5s, ядер на Гбит %s)\n' \
            "$label" "$i" \
            "$(num "$WORK/up.json" mbps)" "$(num "$WORK/up.json" rtx)" \
            "$dn" "$(num "$WORK/dn.json" rtx)" "$cores"
        i=$((i + 1))
    done
}

echo "стенд: $(uname -m), $(nproc) ядер, потоков iperf3 $STREAMS, по $SECS с, прогонов $RUNS"
echo "путь: задержка $RTT мс, потери $LOSS %, клиент на ядрах ${CPUS:-всех}, очередь устройства $TXQ"
echo "путь: устройство отдано готовым дескриптором, разгрузки сегментации нет, режим потока"
echo

if [ $# -ge 1 ]; then
    bench "$1" "соединений $1"
else
    for n in 1 2 4; do
        bench "$n" "соединений $n"
        echo
    done
fi
