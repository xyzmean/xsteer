// Пакет route — куда отдать пакет: поиск пира по адресу и правки заголовков на пути.
//
// ДВЕ ЗАДАЧИ, ДВА РЕШЕНИЯ, И РАЗНИЦА НЕ В КРАСОТЕ, А В ЧАСТОТЕ ВЫЗОВА.
//
// Поиск пира по AllowedIPs — линейный обход, и это правильно. Тридцать два пира по два-три
// префикса дают около шестидесяти проверок вида (dst & mask) == net, то есть порядка семидесяти
// циклов. Против времени, которое стоит один проход AEAD по пакету, это доли процента. Дерево
// или хеш здесь были бы кодом, который экономит эти доли процента и добавляет место для ошибки
// в МАРШРУТИЗАЦИИ — то есть для тихого «трафик ушёл не тому пиру», который по симптому не
// ищется вовсе. Вместо структуры данных: префиксы разложены по длине по убыванию (тогда самое
// длинное совпадение получается само, без всякого дерева), пересечения между пирами отвергнуты
// ещё разбором конфигурации, и есть кэш на одну запись.
//
// ПОРЯДОК БАЙТОВ. Адреса здесь в ХОСТОВОМ порядке — маски так удобнее строить и сравнивать, а
// цена ровно один разворот на пакет против шестидесяти сравнений. Порядок назван в именах
// параметров, потому что именно на нём в этом проекте уже ломались порты.
//
// Порт src/ext/xsroute.{c,h}. Одно отличие от C, и оно про Go, а не про протокол: кэш вынесен
// из роутера в отдельное значение (см. Cache). В C у каждого воркера свой роутер, поэтому кэш
// лежит внутри; в Go роутер один и его читают все горутины, а изменяемое поле внутри общей
// структуры — это гонка, которую детектор найдёт под нагрузкой, а не на стенде.
package route

import "github.com/xyzmean/xsteer/conf"

// entry — один префикс с указанием, кому он принадлежит.
type entry struct {
	net, mask uint32
	peer      int
	plen      int
}

// Router — таблица префиксов всех пиров. После построения НЕ МЕНЯЕТСЯ, поэтому её можно читать
// из любого числа горутин без замка. Правка конфигурации означает новый роутер, а не правку
// этого: подменить указатель целиком дешевле и безопаснее, чем защищать поля.
type Router struct {
	ent []entry
}

// NewRouter раскладывает префиксы всех пиров по длине по убыванию.
//
// Смысл сортировки в том, что после неё «самое длинное совпадение» получается ПЕРВЫМ найденным
// — то есть без дерева, без второго прохода и без сравнения длин на горячем пути.
func NewRouter(peers []conf.Peer) *Router {
	r := &Router{}
	for i := range peers {
		for _, a := range peers[i].Allowed {
			r.ent = append(r.ent, entry{net: a.Net, mask: a.Mask, peer: i, plen: a.Plen})
		}
	}
	// Сортировка вставками: список короткий (десятки записей) и строится один раз, поэтому
	// простой алгоритм здесь дешевле умного — с ним нечему пойти не так. Устойчивость важна:
	// при равной длине порядок остаётся тем, что задан конфигурацией.
	for i := 1; i < len(r.ent); i++ {
		e := r.ent[i]
		k := i
		for k > 0 && r.ent[k-1].plen < e.plen {
			r.ent[k] = r.ent[k-1]
			k--
		}
		r.ent[k] = e
	}
	return r
}

// Cache — кэш на ОДНУ запись, личный для каждой горутины.
//
// Всплески трафика идут потоками — подряд летят пакеты к тому же адресу, — поэтому попадание
// около девяти случаев из десяти, а стоит кэш одного сравнения. Больше одной записи не нужно:
// второй уровень уже сравним по цене с самим обходом.
//
// Нулевое значение готово к работе. Передавать его между горутинами нельзя — в этом весь смысл
// того, что он не внутри Router.
type Cache struct {
	dst   uint32
	peer  int
	valid bool
}

// Lookup — кому принадлежит этот адрес. Возвращает индекс пира или -1.
//
// -1 означает ОТБРОСИТЬ. Отдать такой пакет «первому пиру» было бы утечкой трафика между
// пирами в звезде, поэтому отсутствие совпадения — это решение, а не повод искать запасной
// вариант. Закреплено тестом.
func (r *Router) Lookup(dstHost uint32, c *Cache) int {
	if c != nil && c.valid && c.dst == dstHost {
		return c.peer
	}
	found := -1
	for i := range r.ent {
		if dstHost&r.ent[i].mask == r.ent[i].net {
			found = r.ent[i].peer
			break
		}
	}
	if c != nil {
		c.dst, c.peer, c.valid = dstHost, found, true
	}
	return found
}

// SrcOK — имеет ли пир право отправлять пакеты с этого адреса источника.
//
// ОБЯЗАТЕЛЬНАЯ проверка на хабе, а не гигиеническая: без неё любой пир маршрутизирует от чужого
// имени — то есть достаточно одного скомпрометированного пира, чтобы подделать трафик любого
// другого. Это та же «маршрутизация по ключам», что у WireGuard: право на адрес даёт
// конфигурация, а не сам пакет.
func SrcOK(p *conf.Peer, srcHost uint32) bool {
	for _, a := range p.Allowed {
		if srcHost&a.Mask == a.Net {
			return true
		}
	}
	return false
}

// ipCsum — контрольная сумма заголовка IPv4, посчитанная ЗАНОВО, а не поправленная
// инкрементально.
//
// Инкрементальная поправка (RFC 1624) сэкономила бы девять сложений на пакет — против времени
// AEAD это ноль, — а стоила бы отдельного класса ошибок: заворот переноса при уменьшении TTL
// через границу байта даёт неверную сумму на редких значениях, и проявляется это как молча
// отброшенный пакет у той стороны. Здесь дешёвое и очевидно верное лучше быстрого и хитрого;
// тест сверяет результат с независимым подсчётом на всех значениях TTL.
func ipCsum(ip []byte, hl int) uint16 {
	var s uint32
	for i := 0; i < hl; i += 2 {
		if i == 10 {
			continue // поле самой суммы считается нулём
		}
		s += uint32(ip[i])<<8 | uint32(ip[i+1])
	}
	for s>>16 != 0 {
		s = s&0xFFFF + s>>16
	}
	return uint16(^s)
}

// TTLDec уменьшает TTL проходящего пакета. false — отбросить (TTL истёк или пакет негоден).
//
// Нужно потому, что хаб пересылает пакет между пирами САМ, не отдавая его ядру: без уменьшения
// TTL петля маршрутизации в звезде живёт вечно и находится только по нагрузке на канал.
func TTLDec(ip []byte) bool {
	if len(ip) < 20 || ip[0]>>4 != 4 {
		return false
	}
	hl := int(ip[0]&0x0F) * 4
	if hl < 20 || hl > len(ip) {
		return false
	}
	// TTL 1 и 0 нести дальше нельзя: следующий узел обязан отбросить пакет, а мы бы отправили
	// его по кругу. Отбрасываем здесь и считаем — ICMP «время истекло» не порождаем намеренно:
	// хаб не является узлом маршрутизации в глазах клиента, и ответ от него удивил бы больше,
	// чем помог.
	if ip[8] <= 1 {
		return false
	}
	ip[8]--
	c := ipCsum(ip, hl)
	ip[10], ip[11] = byte(c>>8), byte(c)
	return true
}

// tcpCsumFix — пересчёт суммы TCP целиком, с псевдозаголовком. Инкрементальную поправку по
// RFC 1624 здесь не делаем НАРОЧНО: правка касается только SYN, то есть одного пакета на
// соединение, а не горячего пути, и полный подсчёт на сорока байтах нельзя испортить незаметно
// — в отличие от поправки, ошибка в которой даёт битую сумму лишь на некоторых значениях поля.
func tcpCsumFix(ip []byte, hl, total int) {
	tcp := ip[hl:total]
	tcp[16], tcp[17] = 0, 0
	var s uint32
	for i := 12; i < 20; i += 2 { // адреса из псевдозаголовка
		s += uint32(ip[i])<<8 | uint32(ip[i+1])
	}
	s += 6 // протокол
	s += uint32(len(tcp))
	for i := 0; i+1 < len(tcp); i += 2 {
		s += uint32(tcp[i])<<8 | uint32(tcp[i+1])
	}
	if len(tcp)&1 != 0 {
		s += uint32(tcp[len(tcp)-1]) << 8
	}
	for s>>16 != 0 {
		s = s&0xFFFF + s>>16
	}
	c := uint16(^s)
	tcp[16], tcp[17] = byte(c>>8), byte(c)
}

// MSSClamp подрезает MSS в проходящем SYN до того, что несёт туннель; true — поле поправлено.
//
// Смысл — снять класс отказа «мелкие пакеты ходят, большие пропадают» для того трафика, который
// его и создаёт, не полагаясь на ICMP: узел, объявивший MSS 1460, сам построит слишком большой
// сегмент, а сообщение «нужна фрагментация» на пути к нему запросто отфильтровано. Ровно это
// делает `iptables --clamp-mss-to-pmtu` на каждом втором роутере, и делает по той же причине.
//
// Предел — mtu-40 (заголовки IP и TCP), БЕЗ запаса на опции TCP: по RFC 6691 объявленный MSS
// означает максимум ДАННЫХ, и на длину опций сегмент уменьшает сам отправитель. Запас стоил бы
// 12 байт на каждом сегменте всего трафика туннеля.
func MSSClamp(ip []byte, mtu int) bool {
	n := len(ip)
	if n < 40 || ip[0]>>4 != 4 {
		return false
	}
	hl := int(ip[0]&0x0F) * 4
	if hl < 20 || n < hl+20 {
		return false
	}
	if ip[9] != 6 { // только TCP
		return false
	}
	// Длина берётся из заголовка, а не из принятого размера: на приёме из туннеля они совпадают,
	// но полагаться на это нельзя — пакет с завышенной длиной заставил бы считать сумму по
	// чужой памяти. В Go это была бы паника, а не тихая порча, но паника в потоке пересылки
	// означает упавший клиент, то есть тот же обрыв туннеля.
	total := int(ip[2])<<8 | int(ip[3])
	if total < hl+20 || total > n {
		return false
	}
	// Фрагмент, кроме первого, заголовка TCP не несёт вовсе.
	if (int(ip[6])<<8|int(ip[7]))&0x1FFF != 0 {
		return false
	}
	tcp := ip[hl:total]
	thl := int(tcp[12]>>4) * 4
	if thl < 20 || hl+thl > total {
		return false
	}
	if tcp[13]&0x02 == 0 { // опция MSS бывает только в SYN
		return false
	}
	limit := mtu - 20 - 20
	if limit < 536 {
		limit = 536 // ниже этого не опускаемся: RFC 1122
	}
	if limit > 0xFFFF {
		return false
	}
	for i := 20; i+1 <= thl; {
		kind := tcp[i]
		if kind == 0 { // конец списка опций
			break
		}
		if kind == 1 { // NOP
			i++
			continue
		}
		if i+1 >= thl {
			return false // опция без длины — битый заголовок
		}
		ol := int(tcp[i+1])
		if ol < 2 || i+ol > thl {
			return false
		}
		if kind == 2 && ol == 4 {
			cur := int(tcp[i+2])<<8 | int(tcp[i+3])
			if cur <= limit {
				return false
			}
			tcp[i+2], tcp[i+3] = byte(limit>>8), byte(limit)
			tcpCsumFix(ip, hl, total)
			return true
		}
		i += ol
	}
	return false
}

// FlowHash — хеш ВНУТРЕННЕГО потока: адреса и порты расшифрованного пакета.
//
// Нужен там, где к одному пиру ведёт несколько соединений (пир открывает по одному на воркер):
// выбирать соединение случайно нельзя — пакеты одного потока TCP пошли бы разными путями и
// приезжали бы переставленными, а это для получателя выглядит как потери и рушит скорость. Один
// поток — всегда одно и то же соединение, пока их число не изменилось.
func FlowHash(ip []byte) uint32 {
	n := len(ip)
	if n < 20 || ip[0]>>4 != 4 {
		return 0
	}
	h := uint32(2166136261) // FNV-1a: коротко и без таблиц
	for i := 12; i < 20; i++ {
		h ^= uint32(ip[i])
		h *= 16777619
	}
	h ^= uint32(ip[9]) // протокол
	h *= 16777619
	hl := int(ip[0]&0x0F) * 4
	// Порты берём только у TCP и UDP и только если заголовок целиком на месте: у остального
	// (ICMP, фрагменты) поток определяется адресами, и это верно — фрагменты одного пакета
	// обязаны уйти по одному пути.
	if (ip[9] == 6 || ip[9] == 17) && hl >= 20 && n >= hl+4 &&
		(int(ip[6])<<8|int(ip[7]))&0x1FFF == 0 {
		for i := hl; i < hl+4; i++ {
			h ^= uint32(ip[i])
			h *= 16777619
		}
	}
	return h
}
