package noise

import (
	"crypto/sha256"
	"io"

	"golang.org/x/crypto/hkdf"
)

// Эпохи — периодическая смена транспортных ключей ради ПРЯМОЙ СЕКРЕТНОСТИ, без нового
// рукопожатия и без разрыва соединения.
//
// ЗАЧЕМ. Рукопожатие Noise IK даёт прямую секретность один раз: вскрыв статический ключ пира
// потом, записанный трафик уже не расшифровать. Но транспортные ключи после Split живут всё
// соединение, и утечка ОПЕРАТИВНОЙ памяти в конце сессии вскрывает её целиком с самого начала —
// хоть терабайт. Ратчет закрывает это: ключи прошлых эпох стёрты и не выводятся из текущих.
//
// ПОЧЕМУ НЕ РУКОПОЖАТИЕМ И НЕ РАЗРЫВОМ. Разрыв соединения ради смены ключей рвёт все внутренние
// сессии TCP на ровном месте — плата, которой в протоколе быть не должно. Повторное рукопожатие
// внутри потока стоило бы новых записей: настоящий xhttp после установки соединения не шлёт
// ничего, кроме записей данных (17 03 03 LL LL), и запись иного вида — или узнаваемый обмен
// фиксированных размеров посередине потока — это ровно тот признак, за который цепляется
// определитель.
//
// ПОЭТОМУ РАТЧЕТ НЕЯВНЫЙ, И ЭТО ГЛАВНОЕ СВОЙСТВО. Номер эпохи НЕ ПЕРЕДАЁТСЯ вовсе: обе стороны
// считают одни и те же байты потока (смещение и без того служит nonce) и выводят номер эпохи
// делением смещения на её длину. На проводе не меняется НИ ОДНОГО БАЙТА: ни нового типа записи,
// ни служебного кадра, ни лишнего круга, ни изменения размеров и времён. Отличить поток с
// ротацией от потока без неё нельзя даже зная, что она есть, — сравнивать не с чем.
//
// Тем же приёмом, но с явным номером эпохи в контексте KDF, пользуется veil (пакет epoch:
// Context кладёт epochNumber в контекст, Advance ратчетит корень). Здесь номер выводится из
// смещения, поэтому его не надо ни передавать, ни согласовывать.
//
// ЧЕГО ЭТОТ РАТЧЕТ НЕ ДАЁТ. Он привязан к ОБЪЁМУ, а не ко времени: соединение, которое сутки
// стоит почти без трафика, остаётся в одной эпохе (keepalive двигает смещение на десятки байт в
// минуту). Это осознанный выбор: смена по времени требует либо часов, сходящихся у сторон, либо
// пробных расшифровок, а объём — величина, которую обе стороны знают точно и одинаково. Риск
// утечки при этом растёт вместе с объёмом, то есть ровно там, где ратчет и работает.
//
// ГДЕ ВКЛЮЧЕНО. Только в режиме потока (Go↔Go). В поддельном TCP смещение берётся из
// относительного номера последовательности, а его выбирает отправитель сегмента — то есть
// посторонний может назвать любой номер и заставить нас ратчетить вперёд. Там ключи меняются
// прежним способом (ретайр соединения по объёму), и включать эпохи можно будет вместе с
// переносом в C, где эта же половина протокола ещё не написана.

// EpochBytes — длина эпохи в байтах потока. Шестьдесят четыре мегабайта: на гигабитном канале это
// эпоха в полсекунды, а стоимость смены (два HKDF и разворот шифра) — микросекунды, то есть
// незаметна даже при восьми сменах в секунду. Меньше делать нет смысла: выигрыш в секретности
// уже упирается не в размер эпохи, а в то, как быстро память попадает к противнику.
const EpochBytes = uint64(1) << 26

// epochJumpMax — на сколько эпох вперёд разрешено прыгнуть за один раз. В потоке смещения точны и
// прыжок всегда единичный; предел стоит от испорченного или подделанного смещения, чтобы одна
// запись не заставила считать миллион HKDF.
const epochJumpMax = 64

// EnableEpochs включает ратчет на этом направлении. Корень уже выведен рукопожатием (см. split),
// поэтому аргументов нет. Зовётся ПОСЛЕ рукопожатия и только режимом потока; до вызова поведение
// Keys ровно прежнее, байт в байт.
//
// Обе стороны обязаны включить его ДО первой записи данных: номер эпохи считается из смещения, и
// сторона, включившая ратчет позже, разошлась бы с другой на те записи, что успели уехать.
func (k *Keys) EnableEpochs() {
	k.epoch = 0
	k.epochsOn = true
}

// EpochNow — номер текущей эпохи. Нужен журналу и стенду: на проводе его нет, и увидеть смену
// иначе негде.
func (k *Keys) EpochNow() uint64 { return k.epoch }

// epochOf — какой эпохе принадлежит запись с этим смещением. Считается ОДИНАКОВО обеими
// сторонами: смещение у них общее, а длина эпохи — константа протокола.
func epochOf(seq uint64) uint64 { return seq / EpochBytes }

// advance делает один шаг ратчета: выводит следующий корень из текущего и разворачивает на нём
// шифр. Прошлый корень СТИРАЕТСЯ — в этом весь смысл: назад по хешу не пройти, и вскрытая память
// не выдаёт прошлые эпохи.
func (k *Keys) advance() error {
	// Тот же порядок, что у veil: новый корень = Extract(ikm = метка, salt = прежний корень).
	next := hkdf.Extract(sha256.New, []byte("xsteer epoch advance"), k.root[:])

	var out [44]byte
	prk := hkdf.Extract(sha256.New, nil, next)
	if _, err := io.ReadFull(hkdf.Expand(sha256.New, prk, []byte("xsteer epoch keys")), out[:]); err != nil {
		return ErrCrypto
	}
	nk, err := newKeys(k.kind, out[0:32], out[32:44])
	if err != nil {
		return err
	}

	// Прошлая эпоха остаётся ОДНОЙ ступенью назад: в потоке порядок гарантирован и она не нужна,
	// но запись, застрявшая на границе, не должна стоить обрыва. Дальше одной ступени не храним —
	// иначе ратчет не даёт того, ради чего сделан.
	k.prevAEAD, k.prevIV, k.prevOK = k.aead, k.iv, true

	k.aead, k.iv = nk.aead, nk.iv
	copy(k.root[:], next)
	// Стираем выведенный материал: корень уже скопирован, а ключ развёрнут в шифре.
	for i := range out {
		out[i] = 0
	}
	for i := range next {
		next[i] = 0
	}
	k.epoch++
	return nil
}

// toEpoch подводит направление к нужной эпохе. Назад не ходит: эпохи только вперёд.
func (k *Keys) toEpoch(e uint64) error {
	if e <= k.epoch {
		return nil
	}
	if e-k.epoch > epochJumpMax {
		return ErrAuth
	}
	for k.epoch < e {
		if err := k.advance(); err != nil {
			return err
		}
	}
	return nil
}
