const (
	// WorkersMax — предел числа воркеров, и это не «на всякий случай», а результат замера в
	// движке на C. Цена воркера лежит в ядре: приём идёт сырым сокетом, и ядро на каждый локально
	// доставляемый TCP-пакет КЛОНИРУЕТ буфер для КАЖДОГО такого сокета, а фильтр отбрасывает
	// лишние уже потом. При восьми воркерах каждый наш же туннельный пакет клонируется восемь раз.
	// Замер (два пира, сумма): 1 воркер — 0,67 Гбит/с, 2 — 1,20, 4 — 1,11, 8 — 0,97.
	//
	// Чтобы расти дальше, нужен приём не сырым сокетом, а AF_PACKET с PACKET_FANOUT: там ядро
	// отдаёт пакет ровно одному сокету группы. Это отдельная работа.
	WorkersMax = 4
	// SessTotal — сколько сессий держит хаб ЦЕЛИКОМ, на всех воркерах вместе. Вдвое больше
	// законного максимума звезды (32 пира × 4 соединения): запас на переподключение без разрыва и
	// на неравномерность раскладки по портам.
	//
	// Считается ЦЕЛИКОМ, а делится по фактическому числу воркеров (sessPerWorker) — и это не
	// косметика. Предел был константой «на воркера», выведенной делением на WorkersMax, то есть
	// на предел, а не на факт: на одноядерном VPS воркер один, и суммарная ёмкость выходила 64
	// против законных 128. Полная звезда физически не помещалась в таблицу, а при исчерпании
	// таблицы accept вытесняет чужую сессию — то есть звезда входила в цикл переподключений на
	// ровном месте. В движке на C суммарная ёмкость от числа ядер не зависит (XSH_MAX_SESS,
	// отрезок делится по фактическому числу воркеров), и здесь теперь так же.
	SessTotal = conf.PeersMax * wire.ConnsMax * 2
	// IdleMS — после какой тишины сессия убирается.
	IdleMS = 180000
	// KeepaliveMS — хаб присылает пустую запись, если получал данные, но сам давно не отправлял.
	// Обязательно, а не «полезно»: см. link.Conn.NeedKeepalive.
	KeepaliveMS = 10000
	// evictIdleMS — сколько ПОДТВЕРЖДЁННАЯ сессия должна молчать, чтобы её можно было забрать под
	// нового пира при полной таблице (см. worker.evict).
	//
	// Шесть периодов keepalive, и число выведено из двух соседних сроков, а не выбрано на глаз.
	// Живой пир не молчит дольше одного периода: он присылает пустую запись, даже когда ему нечего
	// сказать, и такая запись обновляет время последнего приёма. Четыре пропущенных keepalive —
	// это уже link.DeadMS (45 с): пир, который в это время что-то отправлял, сам объявил путь
	// мёртвым и пересоединяется. Шесть — с запасом за этой границей, то есть забираем сессию,
	// которая в лучшем случае и так доживает последние секунды.
	//
	// Сверху срок ограничен IdleMS: он должен наступать ЗАМЕТНО раньше, иначе правило ничего не
	// меняет — сессия ушла бы сама, обслуживанием. Шестьдесят секунд против ста восьмидесяти дают
	// втрое, то есть место освобождается задолго до уборки.
	//
	// То же число обязано стоять в движке на C (xshub.c, sess_alloc): политика отказа у двух
	// реализаций одного протокола должна совпадать, иначе один и тот же пир на одном хабе
	// принимается, а на другом — нет.
	evictIdleMS = KeepaliveMS * 6
	// Device — имя устройства. Постоянное: его же ищет диагностика и правила оператора.
	Device = "xshub0"
	// decoyMax — сколько неопознанных соединений можно проксировать одновременно. Тридцать два:
	// зондирование приходит поштучно, а поток означает, что кто-то использует нас как инструмент
	// против сайта-прикрытия.
	decoyMax = 32
	// ---- переезд пира на новую точку ----
	//
	// roamProbeMS и roamProbes: проба «жив ли ещё старый путь» — три пустые записи через 150 мс, то
	// есть решение принимается за 450 мс. Числа выведены из того, что проверяется: пустая запись
	// уходит и возвращается за круг обмена, а три попытки закрывают одну потерю на рваном пути.
	//
	// Верхняя граница выбрана НЕ по осторожности, а по цене ошибки. Ждать тишины вместо пробы
	// пришлось бы дольше периода keepalive пира (до двадцати пяти секунд по конфигурации), и всё
	// это время часть трафика уезжала бы в точку, которой больше нет: получатель выбирается хешем
	// потока среди живых соединений пира, поэтому «половина слотов мёртвая» означает «половина
	// потоков в никуда». Полсекунды против двадцати пяти — в этом вся разница.
	roamProbeMS = 150
	roamProbes  = 3
	// Обратная связь по сборке разрезанных записей — те же числа, что у клиента, и по тем же
	// причинам (см. константы в пакете client).
	reasmCooldownMS = 10000
	reasmReportMS   = 2000
	reasmGrowMS     = 3000
)

// ---- потолок MTU и буфер продолжения разрезанной записи ----------------------
//
// Числа выведены одно из другого и стоят рядом — то же правило, что у размеров в шапке wire.go:
// иначе одно поправят, а второе останется, и расхождение проявится как «мелкие пакеты ходят,
// крупные молча пропадают», худший класс отказов в диагностике.
const (
	// mtuCeil — потолок СОГЛАСОВАННОГО MTU. Больше в кадр Ethernet не влезает вместе с нашими
	// накладными, поэтому это же число зажимает и то, что назвал пир, и то, что стоит в
	// конфигурации (см. worker.onCtl).
	mtuCeil = wire.MTUDefault
	// maxSegCeil — самый большой сегмент, какой может получиться при разрезании записи: то же
	// выражение, что считает sendTo (mtu + Overhead - 40), но при предельном MTU. 1460 байт —
	// ровно кадр 1500 минус заголовки IP и TCP, дальше некуда.
	maxSegCeil = mtuCeil + wire.Overhead - 40
	// contLen — размер буфера продолжения записи: заголовок TCP плюс предельный сегмент.
	//
	// Считается ОТ ПОТОЛКА СОГЛАСОВАНИЯ, а не от строки пакета на проводе, и это не косметика.
	// Пока он был 20+Row = 1520, он держал согласованный MTU только до 1479 — а сверху MTU не
	// проверялся вовсе: число из провода зажималось лишь числом из конфигурации, а конфигурация
	// принимает MTU до 1500. При хабе с MTU 1480..1500 и пире, назвавшем столько же, КАЖДАЯ
	// разрезаемая запись отваливалась в «мал буфер под продолжение записи» и уходила в счётчик
	// отброшенных молча. Теперь оба числа выведены из mtuCeil и разойтись не могут.
	contLen = 20 + maxSegCeil
)

