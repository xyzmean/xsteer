// Options — что нужно хабу, чтобы подняться.
type Options struct {
	Conf *conf.Conf
	Sec  *conf.Secrets
	// Workers — сколько воркеров. Ноль означает «по числу ядер, но не больше числа возможных
	// сессий и не больше WorkersMax», округляя ВНИЗ до степени двойки: раскладка делается маской
	// по младшим битам порта, а у cBPF нет деления.
	Workers int
	// Device — имя устройства; пусто означает Device.
	Device string
	// NoOffload — не включать разгрузку сегментации устройства. Смысл ключа тот же, что у клиента:
	// возможность прогнать то же самое без неё и сравнить.
	NoOffload bool
	// NoTUN — не поднимать устройство вовсе. Нужно там, где хаб обслуживает только трафик пир↔пир
	// (например, в тесте): на LXC и OpenVZ устройства TUN часто нет, и отказ из-за него означал бы
	// «звезда не работает» там, где она работала бы полностью.
	NoTUN bool
	// Logf — куда писать журнал; nil означает stderr.
	Logf func(format string, args ...any)
	// Decoy — что делать с тем, кто не опознан. Пусто означает «ответить фатальным оповещением
	// TLS», см. onStranger.
	Decoy DecoyMode
	// NoBatch — не собирать кадры в одну запись и не разрезать записи между сегментами. Нужно для
	// разговора с клиентом на C, который этого пока не умеет; цена — облик на проводе (см. те же
	// поля в client.Options).
	NoBatch bool
	// StreamOnly — не поднимать половину поддельного TCP вовсе: ни сырых сокетов, ни правила против
	// RST, ни воркеров.
	//
	// Нужно там, где пиры ходят только потоком (например, десктопы на Windows): тогда порт занят
	// ровно одним слушателем, и можно поставить поток на тот же номер, который иначе занял бы
	// поддельный TCP. Без этого пришлось бы держать два порта, и один из них — впустую.
	StreamOnly bool
	// StreamPort — порт для режима потока (настоящий TCP). Ноль означает «не слушать».
	//
	// Отдельный порт, а не тот же: слушающий сокет ядра отвечал бы SYN-ACK и пирам поддельного
	// TCP, и на один их SYN приходило бы два ответа с разными начальными номерами.
	StreamPort int
}

// Hub — поднятый хаб.
type Hub struct {
	opt    Options
	router *route.Router
	dev    []tun.Device
	guard  *link.Guard

	// peerSess — сессии пира: по одной на каждое его соединение. Номер соединения пир называет в
	// ПОДПИСАННОЙ части рукопожатия, поэтому место в наборе определяет он, а не порядок прихода —
	// переподключение одного соединения не задевает остальные.
	//
	// atomic.Pointer, а не массив под замком: читается это на КАЖДЫЙ пакет, идущий пиру, а
	// меняется раз на рукопожатие. Замок на таком отношении частот — чистая потеря.
	peerSess [conf.PeersMax][wire.ConnsMax]atomic.Pointer[session]

	ctl sync.Mutex
	// lastStamp — последняя метка времени от каждого пира: защита от воспроизведения записанного
	// msg1. Общая для всех воркеров: один и тот же пир приходит с разных портов, то есть к разным
	// воркерам, и защита обязана быть общей. В памяти, а не на диске: перезапуск хаба и так
	// требует нового рукопожатия.
	lastStamp [conf.PeersMax]uint64
	devMTU    int

	stats struct {
		rxPkts, txPkts, rxBytes, txBytes, dropped, strangers atomic.Uint64
	}
	// decoyLive — сколько неопознанных проксируется прямо сейчас.
	decoyLive atomic.Int64
	// streamLive — сколько соединений РЕЖИМА ПОТОКА обслуживается прямо сейчас. Предел на них
	// (streamMax) обязателен по той же причине, что и decoyMax: горутина и буферы занимаются до
	// рукопожатия, то есть кем угодно, кто постучался на публичный порт.
	streamLive atomic.Int64

	// Ограничители частоты слушателя потока. Читаются и пишутся только из streamServe, то есть
	// из одной горутины: замок им не нужен, как и остальным RateLog в этом движке.
	rlAccept, rlStream wire.RateLog

	wg sync.WaitGroup
}

type session struct {
	// mu — замок на ОТПРАВКУ и на смену состояния. Отправлять в сессию может любой воркер, а
	// владеет ею один; всё остальное (окно приёма, расшифровка) трогает только владелец.
	mu   sync.Mutex
	conn *link.Conn
	// cont — буфер под ПРОДОЛЖЕНИЕ разрезанной записи: второй и последующие сегменты собираются
	// в нём, потому что их заголовки TCP иначе затёрли бы хвост предыдущего (см. link.SendRecord).
	//
	// ЛЕЖИТ У СЕССИИ, А НЕ У ВОРКЕРА, и это единственное верное место. Буфер защищён замком
	// сессии-ПОЛУЧАТЕЛЯ — тем же, под которым идёт вся отправка, — а отправлять в сессию может
	// любой воркер. Пока буфер принадлежал воркеру, у двух получателей это были два РАЗНЫХ замка,
	// и один и тот же буфер писали одновременно: хвост записи уезжал с чужими байтами, у пира не
	// сходился тег AEAD, и запись пропадала молча. Достижимо штатно и без всякой злой воли — кадр
	// предельного размера пиру с меньшим MTU режется на сегменты, а цикл TUN в это же время везёт
	// пачку другому пиру. В движке на C такой гонки нет по построению: там очередь TUN и сырой
	// сокет живут в одном poll одного потока.
	//
	// Заводится ЛЕНИВО, при первой разрезаемой записи (см. worker.sendTo). Не в accept потому, что
	// accept зовёт любой посторонний SYN из интернета: тогда зондирование платило бы полтора
	// килобайта за пакет до предела таблицы, а сессия, которая ничего не отправляет, буфер и не
	// использует.
	cont []byte
	hs   *noise.HS
	tx   *noise.Keys
	rx   *noise.Keys
	win  wire.Window

	phase int
	// hsBuf — накопленные байты ClientHello: он приходит несколькими сегментами.
	hsBuf  []byte
	peer   int // индекс пира или -1, пока не опознан
	connID int
	// mtu — MTU, о котором договорились с ЭТИМ пиром; 0 — ещё нет.
	//
	// АТОМАРНОЕ, потому что пишет его ВЛАДЕЛЕЦ сессии (onCtl по служебному кадру пира), а читают
	// ОТПРАВИТЕЛИ — любой воркер: цикл TUN подрезает по нему MSS каждому кадру, маршрутизация
	// пир↔пир берёт минимум из двух сессий, отправка считает по нему предельный сегмент,
	// обслуживание MTU устройства обходит по нему все сессии хаба. Замок у сессии для этого есть,
	// но брать его на этих путях нельзя одним из двух: цикл TUN читает поле ДО того, как узнал
	// получателя записи (то есть держал бы чужой замок отправки поперёк чтения устройства), а
	// retuneMTU обходит все сессии под общим замком хаба — брать под ним ещё и замок каждой сессии
	// значило бы заводить второй порядок замков там, где хватает одного слова. Цена атомарного
	// доступа здесь никакая: запись раз в две минуты на пира, чтение — обычная загрузка на amd64 и
	// arm64. Порчи значения на этих машинах не было бы и без атомарности, но «новый MTU применился
	// к половине пакетов пачки» возможно, а детектор гонок пометил бы это в первом же тесте, где
	// оба пути сходятся (см. TestПоляСессииЧитаютсяСоСвоимЗамком).
	mtu         atomic.Int32
	handshakeAt time.Time

	// lastAuth — когда по сессии последний раз пришёл ПОДТВЕРЖДЁННЫЙ кадр: запись, у которой
	// сошёлся тег AEAD.
	//
	// ЗАЧЕМ ОТДЕЛЬНО ОТ conn.Idle(). Время последнего приёма в соединении обновляет КАЖДЫЙ принятый
	// сегмент, включая посторонний и нерасшифрованный, — а на публичный порт хаба сыплется
	// сканерный шум. Значит по conn.Idle() сессия, в которую больше не пишет её пир, может
	// считаться живой сколько угодно долго: достаточно, чтобы кто-то посылал в её четвёрку мусор.
	// Все решения о живости (уборка, вытеснение при полной таблице, переезд пира на новую точку)
	// обязаны считаться по тому трафику, который доказан ключом.
	//
	// АТОМАРНОЕ: пишет владелец сессии, читают другие воркеры — переезд пира сверяет по этому полю,
	// жив ли ещё старый путь, а он приходит к другому воркеру (другой порт источника).
	lastAuth atomic.Int64

	// roamCheck — «пир поднялся заново, проверь, ведёт ли ты ещё куда-нибудь».
	//
	// Ставит ЧУЖОЙ воркер — тот, у которого пир только что поднялся, — а разбирается с этим
	// владелец сессии в своём обслуживании: посылает пустую запись и ждёт ответа. Ответила — сессия
	// остаётся; промолчала — снимается немедленно, не дожидаясь ни IdleMS, ни DeadMS.
	//
	// ПОЧЕМУ ПРОВЕРКА, А НЕ ПРОСТО СНЯТЬ. Снять по признаку «пир поднялся заново» значило бы рвать
	// все остальные его соединения на каждом переподключении одного. Верить же тишине нельзя в
	// другую сторону: живая сессия на покое молчит до периода keepalive, то есть до двадцати пяти
	// секунд, — и ровно столько трафик уезжал бы в точку, которой нет. Проба снимает обе ошибки: она
	// стоит трёх пустых записей и заканчивается за полсекунды.
	roamCheck atomic.Int64
	// Счётчики пробы переезда — ТОЛЬКО владельца сессии, из чужих горутин не трогаются. roamFirst —
	// когда ушла ПЕРВАЯ проба: ответом считается сегмент, принятый после неё.
	roamSent  int
	roamNext  int64
	roamFirst int64

	upPkts, downPkts uint64

	// ---- пачки и сборка разрезанных записей ----
	//
	// reasm принадлежит воркеру-владельцу сессии; batchMax читается набором пачки из любого воркера
	// и правится владельцем по обратной связи от пира — поэтому он атомарный, см. ниже.
	reasm     wire.Reasm
	lastDrops uint64
	// batchMax — сколько кадров хаб везёт одной записью ЭТОМУ пиру. Атомарное по той же причине,
	// что mtu: правит его владелец (onCtl по обратной связи «записи не собираются» и обслуживание,
	// растящее пачку), а читает набор пачки в цикле TUN любого воркера.
	batchMax   atomic.Int32
	coolUntil  int64
	lastReport int64
	lastGrow   int64
	keepNext   int64

	// up — соединение к сайту-прикрытию в фазе phProxy. Nil во всех остальных.
	up netConn
	// st — поток, если сессия ведётся по НАСТОЯЩЕМУ TCP. Nil у сессий поддельного TCP; отправка
	// смотрит на это поле и выбирает путь.
	st *wire.Stream
	// nc — то же соединение, но как net.Conn: нужен, чтобы ЗАКРЫТЬ поток при смене ключей.
	// Закрытие — единственный способ сказать пиру «поднимай заново»: читающая горутина получит
	// ошибку и уберёт сессию, а пир переподключится с новым рукопожатием.
	nc netConn
	// dead — «эту сессию пора убрать». Ставится ЛЮБОЙ горутиной (например, той, что переливает
	// байты прикрытия), а убирает сессию всегда владелец: таблица сессий его личная, и править её
	// со стороны значило бы завести гонку в самом неудачном месте.
	dead atomic.Bool
}

// netConn — то немногое, что нужно от соединения с сайтом-прикрытием. Интерфейсом, а не net.Conn,
// чтобы пакет hub не тащил зависимость от сети в тесты, которым она не нужна.
type netConn interface {
	Read(p []byte) (int, error)
	Write(p []byte) (int, error)
	Close() error
}

type skey struct {
	addr [4]byte
	port uint16
}

type worker struct {
	id, n int
	mask  uint16
	h     *Hub
	rx    link.Raw // свой сокет приёма с фильтром-раскладкой
	tx0   link.Raw // сокет для RST тем, чьей сессии нет
	dev   tun.Device

	// sess — таблица СВОИХ сессий. Читает и меняет её только этот воркер (фильтр гарантирует, что
	// чужие сегменты сюда не придут), поэтому замка у неё нет.
	sess map[skey]*session

	// row — строка для пересылки: заголовки пишутся перед нагрузкой. Принадлежит ГОРУТИНЕ ПРИЁМА
	// (rxLoop, а в режиме потока — цикл чтения соединения); у горутины tunLoop своя, заведённая
	// локально, — см. шапку tunLoop.
	row  []byte
	hbuf []byte // отдельный буфер под ответ рукопожатия: он до ~1300 байт и в строку пакета не влезет

	// rcache — кэш последнего решения маршрутизации, ПРИНАДЛЕЖИТ ГОРУТИНЕ ПРИЁМА, как и row.
	// У tunLoop свой, заведённый локально. Router общий и только для чтения; изменяемая часть
	// обязана быть личной — ровно то, о чём говорит шапка route.Cache. Без него каждый пакет
	// платил полным обходом таблицы: замерено 40,7 нс против 0,47 нс на звезде из 32 пиров.
	rcache route.Cache

	// sessMax — сколько сессий держит ЭТОТ воркер. Поле, а не константа: отрезок общей таблицы
	// делится по ФАКТИЧЕСКОМУ числу воркеров, см. sessPerWorker.
	sessMax int

	// Ограничители на строки, которые вызывает ЧУЖОЙ пакет: до них добирается кто угодно из
	// интернета, и без ограничителя одна такая строка — способ залить журнал сервера. Свои у
	// каждого воркера: общие потребовали бы замка на пути, который и так под потоком.
	//
	// РАЗДЕЛЬНЫЕ, а не один на всё: с общим ограничителем поток по одной причине (скажем, кадры
	// IPv6 от неверно настроенного пира) съедал бы окно и глушил строки про другую причину —
	// именно то сообщение, за которым человек и пришёл в журнал.
	rlUnknown, rlStamp, rlProbe, rlSynEst, rlMTU, rlIPv6, rlOver, rlFull wire.RateLog
}

// Опознание пира и защита от воспроизведения — общие для обеих половин хаба (поддельный TCP и
// поток). Логика одна; различаются лишь журнал (у воркера с ограничителем частоты, у потока
// простой) и что делать при отказе (освободить сессию или закрыть соединение), поэтому вынесены
// именно эти три шага, а решения оставлены на месте вызова.

// findPeer — индекс пира по его статическому ключу, или -1. Линейный обход: раз на рукопожатие.
func (h *Hub) findPeer(pub [32]byte) int {
	for i := range h.opt.Conf.Peers {
		if h.opt.Conf.Peers[i].Pub == pub {
			return i
		}
	}
	return -1
}

// replayFresh — метка времени msg1 новее прошлой от этого пира (или прошлой ещё не было). Ложь
// означает воспроизведение записанного msg1: сессию оно не даёт (подтверждение не подделать), но
// стоит хабу трёх зря потраченных X25519, поэтому обрывается заранее.
func (h *Hub) replayFresh(peer int, stamp uint64) bool {
	h.ctl.Lock()
	seen := h.lastStamp[peer]
	h.ctl.Unlock()
	return stamp == 0 || stamp >= seen
}

// commitStamp запоминает метку времени пира. Общая для всех воркеров: один пир приходит с разных
// портов, то есть к разным воркерам, и защита обязана быть общей.
func (h *Hub) commitStamp(peer int, stamp uint64) {
	h.ctl.Lock()
	h.lastStamp[peer] = stamp
	h.ctl.Unlock()
}

func (h *Hub) logf(f string, a ...any) {
	if h.opt.Logf != nil {
		h.opt.Logf(f, a...)
		return
	}
	fmt.Fprintf(os.Stderr, "hub: "+f+"\n", a...)
}

// Run поднимает хаб и работает до отмены контекста.
func Run(ctx context.Context, opt Options) error {
	if opt.Conf == nil || opt.Sec == nil || !opt.Sec.HasPriv {
		return errors.New("нет конфигурации или приватного ключа")
	}
	if opt.Conf.ListenPort == 0 {
		return errors.New("хабу нужен ListenPort")
	}
	h := &Hub{opt: opt, router: route.NewRouter(opt.Conf.Peers)}

	n := workerCount(opt)
	if opt.StreamOnly {
		if opt.StreamPort == 0 {
			return errors.New("--stream-only без --stream-port: слушать было бы нечем")
		}
		n = 1 // очередь устройства всё равно нужна одна
	}
	dev := opt.Device
	if dev == "" {
		dev = Device
	}

	if !opt.NoTUN {
		open := tun.OpenQueues
		if opt.NoOffload {
			open = tun.OpenQueuesPlain
		}
		devs, err := open(dev, n)
		if err != nil {
			return fmt.Errorf("%w — хаб не сможет отдавать трафик наружу (на LXC и OpenVZ "+
				"устройства TUN часто нет вовсе; тогда --no-tun и только трафик пир↔пир)", err)
		}
		h.dev = devs
		name := devs[0].Name()
		mtu := opt.Conf.MTU
		if mtu == 0 {
			mtu = wire.MTUDefault
		}
		cidr := fmt.Sprintf("%s/%d", ip4str(opt.Conf.Addr), opt.Conf.AddrPlen)
		if err := tun.SetAddr(name, cidr); err != nil {
			return fmt.Errorf("не удалось задать адрес %s: %w", cidr, err)
		}
		if err := devs[0].SetMTU(mtu); err != nil {
			return fmt.Errorf("не удалось задать MTU: %w", err)
		}
		// Хабу запас очереди нужнее, чем клиенту: через одно его устройство идёт трафик всех пиров,
		// и виток цикла у него длиннее ровно во столько же раз. Отказ — осведомляющей строкой:
		// туннель работает и с ядерной очередью, теряется только скорость на пиках.
		if err := tun.SetTxQueueLen(name, tun.TxQueueLen); err != nil {
			h.logf("%s: очередь передачи осталась ядерной (%v) — просили %d пакетов; ждать чтения "+
				"их сможет меньше, остальные ядро на пиках отбросит", name, err, tun.TxQueueLen)
		}
		h.devMTU = mtu
		h.logf("%s: %s", name, offloadLine(devs[0]))
		// Маршруты к сетям пиров: без них ядро не знает, что ответы им идут через это устройство, и
		// выход в интернет работал бы только в одну сторону.
		for i := range opt.Conf.Peers {
			for _, a := range opt.Conf.Peers[i].Allowed {
				if a.Plen == 0 {
					continue // 0.0.0.0/0 — не наш маршрут
				}
				if err := tun.AddRoute(name, fmt.Sprintf("%s/%d", ip4str(a.Net), a.Plen)); err != nil {
					h.logf("маршрут к сети пира %d не встал: %v", i+1, err)
				}
			}
		}
	}

	// Правило против RST собственного ядра. Хабу оно нужнее, чем пиру: на его порту нет
	// слушающего сокета, поэтому ядро отвечает RST на КАЖДОЕ рукопожатие пира.
	if g, err := link.GuardUpServer(opt.Conf.ListenPort); err != nil {
		h.logf("правило против RST не встало (%v): если порт %d не закрыт политикой firewall, "+
			"ядро будет рвать сессии", err, opt.Conf.ListenPort)
	} else {
		h.guard = g
	}
	defer h.guard.Down()

	// Воркеры. В обычном режиме у каждого свой сырой сокет (поддельный TCP); в режиме потока сырых
	// сокетов нет вовсе, НО воркер с очередью устройства нужен и там: без него некому читать ОТВЕТЫ
	// из ядра (интернет → пир) в tunLoop, и туннель нёс бы данные лишь в одну сторону. Именно этого
	// и не хватало в --stream-only — цикл создания стоял под `opt.StreamOnly == false` и не делал ни
	// одного воркера: поток поднимался, наружу пакеты уходили (их кладёт воркер соединения из
	// stream.go), а обратно не возвращалось ничего — рукопожатие есть, данных ноль.
	workers := make([]*worker, 0, n)
	for i := 0; i < n; i++ {
		w := &worker{
			id: i, n: n, mask: uint16(n - 1), h: h,
			sess:    make(map[skey]*session),
			sessMax: sessPerWorker(n),
			row:     make([]byte, wire.HdrRoom+wire.MaxRecord+wire.Tag),
			hbuf:    make([]byte, 2048),
		}
		if !opt.StreamOnly {
			rx, err := link.OpenRawListen(uint16(opt.Conf.ListenPort), w.mask, uint16(i))
			if err != nil {
				return err
			}
			w.rx = rx
			// Сокет для RST тем, чьей сессии нет. Ошибка не смертельна: без него пир узнает о
			// перезапуске хаба по тишине, то есть через сорок пять секунд простоя.
			if tx0, err := link.OpenRawSend([4]byte{0, 0, 0, 0}, [4]byte{}); err == nil {
				w.tx0 = tx0
			}
		}
		if len(h.dev) > 0 {
			w.dev = h.dev[i%len(h.dev)]
		}
		workers = append(workers, w)
	}

	if !opt.StreamOnly {
		h.logf("слушаю поддельный TCP :%d, пиров %d, воркеров %d, шифр решает клиент",
			opt.Conf.ListenPort, len(opt.Conf.Peers), n)
	} else {
		h.logf("поддельный TCP не поднимаю (--stream-only), пиров %d, чтение устройства для обратного пути включено",
			len(opt.Conf.Peers))
	}
	if opt.Decoy.Mode != "" {
		h.logf("неопознанным: %s", opt.Decoy.describe())
	}

	if opt.StreamOnly && len(h.dev) == 0 && !opt.NoTUN {
		return errors.New("устройство не поднялось, а потокам оно нужно для выхода наружу")
	}
	if opt.StreamPort > 0 {
		h.wg.Add(1)
		go func() {
			defer h.wg.Done()
			if err := h.streamListen(ctx, opt.StreamPort); err != nil && ctx.Err() == nil {
				h.logf("слушатель потока остановился: %v", err)
			}
		}()
	}

	for _, w := range workers {
		if w.rx != nil {
			h.wg.Add(1)
			go func(w *worker) { defer h.wg.Done(); w.rxLoop(ctx) }(w)
		}
		if w.dev != nil {
			h.wg.Add(1)
			go func(w *worker) { defer h.wg.Done(); w.tunLoop(ctx) }(w)
		}
	}

	// Устройство и сырые сокеты закрываются ПОСЛЕ того, как воркеры ушли, и никогда до. Тот же
	// урок, что в клиенте, и та же причина: побудка закрытием отдавала номер дескриптора трубе
	// первого же exec (nft у правила против RST), пока по этому номеру ещё читали и писали
	// (I-109). Уходят воркеры сами — rxLoop ждёт 50 мс, tunLoop 200 мс, оба смотрят на контекст.
	closeAll := func() {
		for _, d := range h.dev {
			d.Close()
		}
		for _, w := range workers {
			if w.rx != nil {
				w.rx.Close()
			}
		}
	}
	if !drainThenClose(ctx, &h.wg, 3*time.Second, closeAll) {
		// Устройство и сокеты НЕ закрываем: их номера ещё в работе, а заберёт их выход процесса.
		h.logf("не все воркеры закрылись за 3 с — выхожу, устройство оставляю открытым")
	}
	return ctx.Err()
}

// workerCount — сколько воркеров. Степень двойки обязательна: раскладка делается маской по
// младшим битам порта источника. Верхний предел — не только ядра, но и число ВОЗМОЖНЫХ сессий:
// лишний воркер платится клонированием буферов на всём трафике машины, а приносит пользу только
// если ему достанется своя сессия.
// Переменной, а не функцией, только ради теста ёмкости: число ядер — единственный вход, который
// нельзя задать параметрами, а именно от него и зависела найденная нехватка таблицы сессий.
var numCPU = runtime.NumCPU

// sessPerWorker — отрезок общей таблицы на одного воркера при n воркерах.
func sessPerWorker(n int) int {
	if n < 1 {
		n = 1
	}
	per := SessTotal / n
	if per < 1 {
		per = 1
	}
	return per
}

func workerCount(opt Options) int {
	want := opt.Workers
	if want <= 0 {
		want = numCPU()
		if lim := len(opt.Conf.Peers) * wire.ConnsMax; want > lim {
			want = lim
		}
	}
	if want > WorkersMax {
		want = WorkersMax
	}
	if want < 1 {
		want = 1
	}
	n := 1
	for n*2 <= want {
		n *= 2
	}
	return n
}
