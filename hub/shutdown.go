package hub

import (
	"context"
	"sync"
	"time"
)

// drainThenClose ждёт, пока горутины уйдут сами, и только ПОСЛЕ этого закрывает то, чем они
// пользовались.
//
// ЗАЧЕМ ИМЕННО В ТАКОМ ПОРЯДКЕ. Прежде отмена контекста будила чтение устройства ЗАКРЫТИЕМ его
// дескриптора, и это открывало окно, в котором номер дескриптора уже свободен, а воркеры всё ещё
// обращаются по нему. Окно не теоретическое и не узкое: в том же окне снимается обвязка туннеля —
// nft у правила против RST, ip у маршрутов, — и каждый такой вызов идёт через exec с трубами, а
// трубам ядро выдаёт НАИМЕНЬШИЕ свободные номера, то есть в первую очередь только что
// освободившиеся. Тогда запись пакета уходит в буфер вывода дочернего процесса, а чтение
// вычитывает из него чужие байты и разбирает их как IP-пакет (I-109). Тот же класс ошибки, за
// который в движке на C уже платили вниманием: conn_drop, закрывавший fd 0 (I-010).
//
// Будить закрытием при этом НЕ НУЖНО, и это главное наблюдение. Все циклы, читающие устройство,
// написаны через WaitRead с таймаутом (200 мс у устройства, 50 мс у сырого сокета) и проверяют
// ctx.Err() в условии цикла — то есть уходят сами, максимум через один таймаут после отмены.
// Закрытие лишь укорачивало эти 200 мс, а платой за них была подмена объекта по номеру
// дескриптора. Отсрочка в три секунды, отсчитываемая от отмены, вмещает один таймаут с запасом
// больше чем в десять раз.
//
// Возвращает false, если отсрочка истекла: тогда закрывать НЕЛЬЗЯ — кто-то ещё в цикле, и его
// номер дескриптора нельзя отдавать никому. Дескрипторы в этом случае заберёт выход процесса,
// а вместе с ними уйдёт и непостоянное устройство TUN.
//
// Близнец этой функции живёт в пакете client: у хаба и у клиента одна форма завершения, но общего
// дома для пятнадцати строк здесь нет, а заводить пакет ради них — цена выше пользы. Появится
// третий такой же — вот тогда и переезжать.
func drainThenClose(ctx context.Context, wg *sync.WaitGroup, grace time.Duration,
	closeAll func()) bool {
	done := make(chan struct{})
	go func() { wg.Wait(); close(done) }()
	select {
	case <-done:
	case <-ctx.Done():
		// Отсрочка отсчитывается ТОЛЬКО от отмены, а не от запуска. Первая версия ждала три
		// секунды безусловно — и туннель тихо снимался через три секунды работы: журнал
		// заканчивался на «путь подтвердил пробой», устройство исчезало, ни одной строки об
		// ошибке. Стенд поймал это как «нет /sys/class/net/xsa/mtu».
		select {
		case <-done:
		case <-time.After(grace):
			return false
		}
	}
	closeAll()
	return true
}
