// Что делать с тем, кто постучался, но своим не оказался.
//
// ЗАЧЕМ ЗДЕСЬ ВЫБОР, А НЕ ОДНО ПОВЕДЕНИЕ. Активное зондирование — это прибор, который сам
// присылает настоящий ClientHello на наш порт и смотрит, что ответят. Ответ и есть отпечаток, и у
// каждого варианта своя цена:
//
//	alert  — фатальное оповещение TLS (handshake_failure). Так отвечает настоящий сервер, которому
//	         предложили то, чего он не может, — но НЕ так отвечает сервер, у которого есть
//	         сертификат для запрошенного имени. То есть отличимо: настоящий HTTPS на :443 после
//	         ClientHello присылает ServerHello и сертификат, а мы — семь байт отказа. Это поведение
//	         движка на C, и оно оставлено ради совместимости ожиданий, а не потому, что хорошо.
//	silent — не отвечать вовсе. Отличимо СИЛЬНЕЕ, чем оповещение: открытый порт, завершивший
//	         рукопожатие TCP и замолчавший на ClientHello, в интернете почти не встречается.
//	reset   — RST. Выглядит как «сервис упал между SYN и данными»; повторяемость выдаёт подделку
//	         сразу — настоящий сервер так себя не ведёт на каждом соединении.
//	proxy  — ОТДАТЬ соединение настоящему серверу. Прибор получает подлинный ServerHello,
//	         подлинный сертификат и подлинную страницу — то есть видит ровно то, что увидел бы на
//	         сайте-прикрытии. Это единственный вариант, который отвечает на зондирование не
//	         «признаком», а правдой.
//
// ПОЧЕМУ proxy ВОЗМОЖЕН ЗДЕСЬ, ХОТЯ В ПЛАНЕ ДВИЖКА НА C НАПИСАНО, ЧТО НЕТ. Там сказано:
// «проксирование требует настоящей точки TCP, а настоящий слушающий сокет на том же порту отвечал
// бы SYN-ACK нашим же пирам». Это верно про СЛУШАЮЩИЙ СОКЕТ ЯДРА — и неверно про нас: поддельным
// TCP владеем мы сами, в пользовательском пространстве, и никакого сокета ядра на порту нет. Значит
// мы можем сами открыть настоящее соединение к сайту-прикрытию и переливать байты в обе стороны
// через своё поддельное. Пир при этом не задет ничем: его сессия опознана раньше, чем начинается
// эта дорожка.
//
// ЧЕГО proxy НЕ ДАЁТ, СКАЗАНО ПРЯМО. Наш поддельный TCP не делает повторных передач: потерянный
// сегмент рукопожатия TLS означает для прибора зависшее соединение, а не «поддельный сервер». На
// обычном пути потерь нет, и прибор видит настоящий сайт; на пути с потерями он увидит обрыв —
// подозрительно, но неотличимо от плохой связи. Настоящая точка TCP в пользовательском пространстве
// (с окном и повторами) — отдельная работа, и её стоимость надо мерить, а не предполагать.
type DecoyMode struct {
	// Mode: "", "alert", "silent", "reset" или "proxy".
	Mode string
	// Dest — куда отдавать соединение в режиме proxy: "host:port". Пусто вместе с FollowSNI
	// означает, что режим proxy включить нельзя.
	Dest string
	// FollowSNI — соединяться с тем именем, которое назвал сам прибор, а не с постоянным Dest.
	//
	// Даёт правильный сертификат на ЛЮБОЕ запрошенное имя, то есть закрывает главную дырку
	// постоянного назначения: прибор просит SNI, которого мы не обслуживаем, получает сертификат
	// сайта-прикрытия и видит несовпадение. Цена — наш порт становится пересылкой к произвольному
	// узлу на :443, поэтому имена ограничены Allow.
	FollowSNI bool
	// Allow — какие имена разрешено пересылать при FollowSNI. Пусто означает «только Dest».
	Allow []string
	// Timeout — сколько ждать сайт-прикрытие. Ноль означает пять секунд.
	Timeout time.Duration
}

func (d DecoyMode) describe() string {
	switch d.Mode {
	case "silent":
		return "не отвечать (отличимо: открытый порт, замолчавший на ClientHello)"
	case "reset":
		return "RST"
	case "proxy":
		if d.FollowSNI {
			return fmt.Sprintf("отдавать настоящему серверу по имени из SNI (по умолчанию %s)", d.Dest)
		}
		return "отдавать настоящему серверу " + d.Dest
	default:
		return "фатальное оповещение TLS (отличимо от настоящего сервера с сертификатом)"
	}
}

// Validate проверяет настройку до подъёма хаба: неверная настройка защиты, обнаруженная в бою, —
// это защита, которой нет.
func (d DecoyMode) Validate() error {
	switch d.Mode {
	case "", "alert", "silent", "reset":
		return nil
	case "proxy":
		if d.Dest == "" {
			return fmt.Errorf("для режима proxy нужен адрес сайта-прикрытия")
		}
		if _, _, err := net.SplitHostPort(d.Dest); err != nil {
			return fmt.Errorf("адрес сайта-прикрытия должен быть вида host:port: %w", err)
		}
		return nil
	}
	return fmt.Errorf("неизвестный режим для неопознанных: %q (alert, silent, reset или proxy)", d.Mode)
}

// dialDecoy — открыть соединение к сайту-прикрытию. Через поле h.dial, если оно задано (стенд),
// иначе настоящей сетью.
func (h *Hub) dialDecoy(dest string, timeout time.Duration) (net.Conn, error) {
	if h.dial != nil {
		return h.dial(dest, timeout)
	}
	return net.DialTimeout("tcp", dest, timeout)
}

// onStranger — единственная дорожка для тех, кто не наш. hsErr — почему не наш (nil означает
// «рукопожатие разобралось, но такого пира нет в конфигурации»).
//
// ВАЖНО, ЧТО ЭТА ДОРОЖКА ОДНА. Первая версия отвечала оповещением из двух разных мест (не разобрали
// Hello и не нашли пира), и они успели разойтись по поведению — а разница в ответе на два разных
// «не наш» это ровно то, что прибор и ищет: она рассказывает, ГДЕ мы его отвергли.
func (w *worker) onStranger(k skey, s *session, seg *link.Seg, hsErr error) {
	d := w.h.opt.Decoy
	switch d.Mode {
	case "silent":
		w.free(k, s)
		return
	case "reset":
		w.sendRST(seg)
		w.free(k, s)
		return
	case "proxy":
		if w.startProxy(k, s, seg) {
			return // сессия жива и переливает байты; освободит её сама дорожка
		}
		// Не удалось дозвониться до сайта-прикрытия — отвечаем как настоящий сервер, у которого
		// не сошлось: это хуже проксирования, но лучше молчания.
		fallthrough
	default:
		_ = s.conn.Send(link.PSH|link.ACK, noise.Alert())
		w.free(k, s)
	}
	_ = hsErr
}

// startProxy начинает отдавать соединение настоящему серверу: занимает место в пределе, выбирает
// адрес и ЗАПУСКАЕТ ЗВОНОК, не дожидаясь его.
//
// Возвращает true, если дорожка началась: тогда сессию освобождает сама дорожка, а не вызывающий.
//
// ЗВОНОК НЕ ЗДЕСЬ, И ЭТО ГЛАВНОЕ В ЭТОЙ ФУНКЦИИ. Прежде тут стоял net.DialTimeout — то есть
// рукопожатие TCP со сторонним узлом шло внутри onStranger, внутри onSeg, внутри rxLoop, а rxLoop
// это ОДНА горутина на воркера, и она же ведёт обслуживание. На время звонка (до DecoyMode.Timeout,
// по умолчанию пять секунд) воркер не принимал ни одного сегмента своих пиров, не слал keepalive,
// не отдавал отложенных подтверждений и не убирал сессий по простою — и вызвать это мог кто угодно
// из интернета одним сегментом, похожим на начало TLS, ничего не подтверждая (I-126). Теперь звонок
// уходит в горутину, а сессия ждёт в фазе phDial.
//
// Реализация на C пришла к тому же раньше и другим инструментом: decoy_start открывает сокет
// SOCK_NONBLOCK и допускает EINPROGRESS, готовность приходит событием POLLOUT в decoy_event, а
// сегменты, пришедшие до готовности, decoy_up дописывает в hs_buf. Здесь роль hs_buf играет
// session.dialBuf, роль up_ready — session.upReady, а роль POLLOUT — возврат из net.DialTimeout в
// своей горутине.
func (w *worker) startProxy(k skey, s *session, seg *link.Seg) bool {
	d := w.h.opt.Decoy
	// Предел на число одновременно проксируемых, и он обязателен: каждое такое соединение — это
	// настоящий сокет к сайту-прикрытию и горутина. Без предела поток зондирования превращался бы в
	// нашу же атаку на прикрытие и на собственные дескрипторы. Место занимается ДО запуска горутины
	// и возвращается на каждом выходе — в том числе на выходах внутри неё (I-125).
	if w.h.decoyLive.Add(1) > decoyMax {
		w.h.decoyLive.Add(-1)
		if ok, held := w.rlProbe.Allow(nowMS(), wire.LogEveryMS); ok {
			w.h.logf("неопознанных больше %d одновременно — этому отказываю%s", decoyMax,
				wire.HeldSuffix(held))
		}
		return false
	}
	dest := w.decoyDest(s, seg)
	if dest == "" {
		// Место возвращается и здесь: этот выход был единственным, где занятое первым действием не
		// освобождалось, и каждое срабатывание съедало одно из decoyMax мест навсегда (I-125).
		// Ветка сегодня недостижима — Validate отвергает proxy без Dest, — но она и существует как
		// оборона от «Dest пуст», а оборона не должна подтачивать предел, за которым режим proxy
		// тихо становится alert.
		w.h.decoyLive.Add(-1)
		return false
	}
	timeout := d.Timeout
	if timeout <= 0 {
		timeout = 5 * time.Second
	}
	if ok, held := w.rlProbe.Allow(nowMS(), wire.LogEveryMS); ok {
		w.h.logf("неопознанный с %s: отдаю настоящему серверу %s%s", ip4b(k.addr), dest,
			wire.HeldSuffix(held))
	}
	// Первым делом прикрытию уйдёт ВСЁ, что он прислал, — целиком и без правок. Именно всё
	// накопленное, а не последний сегмент: Hello браузерного размера приходит несколькими
	// сегментами, и отдать прикрытию только последний значило бы, что оно видит обрубок и отвечает
	// не так, как ответило бы прибору напрямую.
	sent := s.hsBuf
	if len(sent) == 0 {
		sent = seg.Payload
	}
	hello := make([]byte, len(sent))
	copy(hello, sent)

	// Фаза ставится ЗДЕСЬ, владельцем и до запуска горутины, — и в этом весь смысл того, что
	// «соединяюсь» выражено флагом upReady, а не отдельной фазой (см. phProxy): phase остаётся с
	// единственным писателем, и проверки фазы без замка в onSeg, onSyn, evict и maintain остаются
	// верными. С этого мига продолжение потока идёт в dialBuf, а не теряется.
	s.phase = phProxy
	go w.dialProxy(k, s, dest, timeout, hello)
	return true
}

// dialProxy — звонок сайту-прикрытию и всё, что за ним. Живёт в своей горутине: см. шапку
// startProxy.
//
// ОТДЕЛЬНАЯ ГОРУТИНА ЗНАЧИТ, ЧТО СЕССИЮ МОГЛИ УБРАТЬ ПОД НАМИ. Владелец (тот же воркер) волен
// освободить её, пока мы звоним, — по простою, по вытеснению или по остановке хаба. Поэтому каждый
// раз, когда мы возвращаемся к сессии, фаза перечитывается под замком: phProxy означает «нас ещё
// ждут», всё остальное — «уходим молча». Убирает сессию всегда владелец, мы только помечаем
// (s.dead), потому что таблица сессий его личная.
//
// ФАЗУ ЗДЕСЬ НЕ ПИШЕТ НИКТО. Единственный писатель phase — владелец сессии, и всё, что мы
// публикуем наружу, публикуется флагом upReady под замком сессии.
func (w *worker) dialProxy(k skey, s *session, dest string, timeout time.Duration, hello []byte) {
	up, err := w.h.dialDecoy(dest, timeout)
	if err != nil {
		w.h.decoyLive.Add(-1)
		w.h.logDialFail(ip4b(k.addr), dest, err)
		// Не удалось дозвониться — отвечаем как настоящий сервер, у которого не сошлось: это хуже
		// проксирования, но лучше молчания. Ровно то же делал onStranger своим fallthrough, когда
		// startProxy возвращал false; изменился только тот, кто это делает и когда.
		s.mu.Lock()
		alive := s.phase == phProxy
		s.dialBuf = nil
		s.mu.Unlock()
		if alive {
			_ = s.conn.Send(link.PSH|link.ACK, noise.Alert())
			s.dead.Store(true)
		}
		return
	}

	// Накопленное отдаётся ДО того, как владелец начнёт писать в up сам, и цикл здесь не
	// украшение. Пока идёт запись, прибор может прислать ещё — эти байты обязаны уйти ПЕРЕД теми,
	// что пойдут напрямую, иначе продолжение потока обгонит своё же начало. Пока upReady не
	// поднят, единственный писатель в up — мы.
	s.mu.Lock()
	if s.phase != phProxy {
		s.mu.Unlock()
		up.Close()
		w.h.decoyLive.Add(-1)
		return
	}
	s.up = up
	out := hello
	for {
		out = append(out, s.dialBuf...)
		s.dialBuf = nil
		s.mu.Unlock()

		_, werr := up.Write(out)

		s.mu.Lock()
		if werr != nil || s.phase != phProxy {
			gone := s.phase != phProxy
			// Обнуляется здесь же: иначе уборка у владельца закрыла бы уже закрытое.
			s.up = nil
			s.mu.Unlock()
			up.Close()
			w.h.decoyLive.Add(-1)
			if !gone {
				s.dead.Store(true)
			}
			return
		}
		if len(s.dialBuf) == 0 {
			// Публикация под замком: снаружи замка владелец успел бы увидеть «ещё не готово» и
			// дописать в dialBuf уже после того, как мы его отдали, — и эти байты не ушли бы
			// никогда.
			s.upReady.Store(true)
			s.mu.Unlock()
			break
		}
		out = out[:0]
	}

	// Обратное направление: что ответил настоящий сервер — то и отдаём прибору через поддельное
	// соединение. Резать на сегменты обязательно: у нас датаграммная семантика, и сегмент больше
	// MSS просто не дойдёт. Место в пределе возвращает proxyDown своим defer.
	w.proxyDown(k, s, up)
}

// proxyPending — продолжение потока, пришедшее ПОКА прикрытие не подняло трубку. Копится в сессии
// и уходит одним куском сразу за Hello (см. dialProxy). В реализации на C это decoy_up при
// !up_ready, дописывающий в hs_buf.
//
// Возвращает false, если копить уже поздно: звонок состоялся, и писать надо напрямую. Проверка
// готовности идёт ЗДЕСЬ, под замком, а не только у вызывающего — тот читает флаг без замка, и
// между его чтением и этим вызовом звонок мог успеть завершиться.
func (w *worker) proxyPending(s *session, seg *link.Seg) bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.upReady.Load() {
		return false
	}
	if s.phase != phProxy {
		return true
	}
	// Предел на накопленное обязателен по той же причине, что и helloMax выше по дорожке: сюда
	// пишет кто угодно из интернета, пока мы держим звонок к стороннему узлу. Перебравший предел
	// уходит целиком — обрезать разговор с прикрытием посередине бессмысленно: оно ответит на
	// испорченный запрос не так, как ответило бы прибору.
	if len(s.dialBuf)+len(seg.Payload) > dialMax {
		s.dead.Store(true)
		return true
	}
	s.dialBuf = append(s.dialBuf, seg.Payload...)
	return true
}

// proxyDown переливает ответ сайта-прикрытия прибору.
func (w *worker) proxyDown(k skey, s *session, up net.Conn) {
	defer up.Close()
	defer w.h.decoyLive.Add(-1)
	buf := make([]byte, 1200)
	_ = up.SetReadDeadline(time.Now().Add(30 * time.Second))
	for {
		n, err := up.Read(buf)
		if n > 0 {
			// Отправка идёт через ту же неделимую операцию, что и данные пиров, только БЕЗ
			// шифрования: прибор говорит настоящий TLS с настоящим сервером, и наше дело —
			// перенести байты, а не подписать их.
			s.mu.Lock()
			alive := s.phase == phProxy
			s.mu.Unlock()
			if !alive {
				return
			}
			if err := s.conn.Send(link.PSH|link.ACK, buf[:n]); err != nil {
				return
			}
			_ = up.SetReadDeadline(time.Now().Add(30 * time.Second))
		}
		if err != nil {
			// Прикрытие закрыло соединение (или ответило и закрыло) — ЗАКРЫВАЕМ И МЫ, и это не
			// вежливость.
			//
			// Настоящий сервер HTTPS на запрос HTTP отвечает отказом или закрывает соединение, но
			// делает это БЫСТРО. Пока этого не было, прибор, приславший «GET / HTTP/1.1», не
			// получал ничего: прикрытие закрывалось, а наше поддельное соединение оставалось
			// висеть, и снаружи это выглядело как открытый порт, который молчит — то есть как
			// ровно тот признак, ради устранения которого вся дорожка и заведена. Стенд поймал это
			// пятисекундным ожиданием curl.
			s.mu.Lock()
			alive := s.phase == phProxy
			s.mu.Unlock()
			if alive {
				_ = s.conn.Send(link.FIN|link.ACK, nil)
			}
			s.dead.Store(true)
			return
		}
	}
}

// proxyUp — то, что прибор присылает дальше, уходит настоящему серверу.
func (w *worker) proxyUp(k skey, s *session, seg *link.Seg) {
	if len(seg.Payload) == 0 {
		return
	}
	// Прикрытие ещё не подняло трубку — копим (I-126). До правки этой ветки не было и не могло
	// быть: звонок шёл в этом же цикле, и сегмент попросту ждал в очереди сокета, пока воркер
	// стоял.
	if !s.upReady.Load() && w.proxyPending(s, seg) {
		return
	}
	if s.up == nil {
		w.free(k, s)
		return
	}
	if _, err := s.up.Write(seg.Payload); err != nil {
		s.up.Close()
		w.free(k, s)
	}
}

// allowedHost — можно ли пересылать к этому имени.
//
// Список нужен не из осторожности: без него порт хаба становится открытой пересылкой на :443 к
// любому узлу, то есть чужим инструментом. Пустой список означает «только постоянное назначение».
// decoyDest — КОМУ звонить: имя, названное самим прибором, если оно разрешено, иначе постоянный
// Dest. Отдельной функцией по той же причине, по которой в реализации на C отдельной функцией
// сделан decoy_dest_for: разбор идёт по недоверенным байтам с публичного порта, до всякой
// аутентификации, и проверять его надо самим по себе, а не через сокеты вокруг.
func (w *worker) decoyDest(s *session, seg *link.Seg) string {
	// Разбирается ВСЁ накопленное, а не последний сегмент, и это здесь важнее, чем при переливе
	// байтов: SNI лежит в НАЧАЛЕ ClientHello, а браузерный Hello в один сегмент не влезает — то
	// есть по последнему сегменту имя не разобралось бы никогда, и звонок молча уходил бы в
	// постоянный Dest. Накопленного нет только у Hello, влезшего в один сегмент; тогда он и есть
	// всё присланное.
	hello := s.hsBuf
	if len(hello) == 0 {
		hello = seg.Payload
	}
	return w.h.decoyDestFor(hello)
}

// decoyDestFor — куда отдавать ЭТОГО неопознанного. Отдельно от worker.decoyDest, потому что тем
// же выбором пользуется половина ПОТОКА, где ни воркера, ни сессии поддельного TCP нет вовсе, а
// правило выбора обязано быть одно: разойдясь, две половины давали бы прибору разный сертификат
// на один и тот же запрос — то есть сами становились бы признаком.
func (h *Hub) decoyDestFor(hello []byte) string {
	d := h.opt.Decoy
	dest := d.Dest
	if !d.FollowSNI {
		return dest
	}
	// Имя из SNI — то, ради чего прибор и пришёл. Отдав ему сертификат другого сайта, мы сообщим
	// ровно то, что пытались скрыть.
	if ref, err := chello.Parse(hello); err == nil && ref.SNI != "" {
		if host := allowedHost(ref.SNI, d.Allow); host != "" {
			dest = net.JoinHostPort(host, "443")
		}
	}
	return dest
}

func allowedHost(sni string, allow []string) string {
	sni = strings.ToLower(strings.TrimSuffix(sni, "."))
	if sni == "" || strings.ContainsAny(sni, "/\\ ") {
		return ""
	}
	for _, a := range allow {
		a = strings.ToLower(a)
		if a == sni {
			return sni
		}
		// Подстановка вида «.example.com» разрешает поддомены: сайты-прикрытия обычно живут
		// целыми доменами, и перечислять каждый узел вручную означало бы, что список не обновят.
		if strings.HasPrefix(a, ".") && strings.HasSuffix(sni, a) {
			return sni
		}
	}
	return ""
}
